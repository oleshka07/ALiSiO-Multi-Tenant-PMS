-- 0121: відмова, яку бачить ГОТЕЛЬ, а не лог контейнера (Р13.1, Р13.7)
--
-- Дві колонкові родини, одна причина: стан «щось не працює» жив там, куди
-- ніхто не дивиться.
--
-- fin_recurring_templates.failed_runs / last_error / last_error_at
--
--   `runRecurringTick` ловив виняток `createOperationInTx` і ставив
--   is_active = FALSE. З ПЕРШОЇ відмови. Тобто помилка конфігурації —
--   найчастіше «курсу валюти на сьогодні ще немає», тобто ТИМЧАСОВА —
--   мовчки вимикала готелю регулярний платіж: оренда просто переставала
--   нараховуватись, ніхто нічого не бачив, а причина лишалась у логу
--   контейнера. Погашений шаблон сам не вмикається.
--
--   Тепер: відмови рахуються ПОСПІЛЬ (успішний прогін скидає лічильник),
--   шаблон гасне після третьої, і причина видима в списку шаблонів.
--
-- fin_auto_rules.broken_fields
--
--   Варта належності стоїть на ЗБЕРЕЖЕННІ правила (Д35), але правило могло
--   лягти в базу раніше за неї. Спрацювання такого правила операцію більше не
--   змінює — і не мовчить: поля, чиє посилання веде в чужий довідник,
--   записуються сюди списком JSON і їдуть у список правил, де їх бачить
--   оператор. Мовчазного пропуску немає в жодному разі.
--
--   NULL означає «зламаного нічого»; успішне збереження правила очищає
--   колонку, бо варта щойно довела належність кожного посилання.
--
-- Обидві таблиці тенантні, обидві під RLS; колонки не змінюють ні політик, ні
-- ключів. Ідемпотентна.

ALTER TABLE fin_recurring_templates ADD COLUMN IF NOT EXISTS failed_runs   INTEGER NOT NULL DEFAULT 0;
ALTER TABLE fin_recurring_templates ADD COLUMN IF NOT EXISTS last_error    TEXT;
ALTER TABLE fin_recurring_templates ADD COLUMN IF NOT EXISTS last_error_at TIMESTAMPTZ;

ALTER TABLE fin_auto_rules ADD COLUMN IF NOT EXISTS broken_fields TEXT;
