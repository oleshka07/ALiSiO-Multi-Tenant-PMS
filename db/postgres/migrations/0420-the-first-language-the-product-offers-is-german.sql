-- 0420: дефолт мови організації = базова мова продукту.
--
-- ── Що міняється і що НІ ────────────────────────────────────────────────
--
-- Міняється ДЕФОЛТ колонки, тобто відповідь на майбутні вставки, які мови не
-- називають. Наявні рядки не чіпаються жодним: готель, який уже обрав мову
-- (а обрали всі — `provisionOrganization` називає її явно), лишається зі
-- своєю.
--
-- ── Навіщо, якщо код і так завжди називає мову ──────────────────────────
--
-- Бо інакше відповідей на питання «яка мова базова» стає ДВІ: код каже
-- `DEFAULT_LANGUAGE = 'de'`, колонка каже 'uk', і відповідає та, кого спитали
-- останнім. Це той самий клас, що `|| 'CZK'` і `|| 'Europe/Prague'`: обидві
-- відповіді виглядають правильними, розходяться мовчки, і побачить це лише
-- той, чий рядок пішов не через код.
--
-- Українська при цьому нікуди не дівається: нею написані літерали продукту
-- (`UI_SOURCE_LANGUAGE`), і це ІНША роль — мова, у яку впирається запасний
-- шлях каталогу. Дві ролі розводить `language-order.check`.
--
-- RLS на `organizations` не чіпається (таблиця не нова, колонка не нова), тож
-- `check-migration-rls` тут нічого не вимагає.

ALTER TABLE organizations ALTER COLUMN language SET DEFAULT 'de';
