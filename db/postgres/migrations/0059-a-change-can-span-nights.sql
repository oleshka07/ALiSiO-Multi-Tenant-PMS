-- Координата черги може бути ДІАПАЗОНОМ ночей: `cm_outbox.stay_date_to`.
--
-- ── Навіщо ────────────────────────────────────────────────────────────────
--
-- Черга тримає координату, не значення (0054): «ціна пари тип × тариф на
-- ніч N змінилась». Але одна правка матриці цін без дат — це КОЖНА майбутня
-- ніч; подобово це тисячі рядків на кожне зʼєднання за один клік в екрані,
-- і сам INSERT у транзакції ціни тривав би секунди. Діапазон — один рядок.
--
-- Рішення Ц13 назвало це наперед: діапазон безпечний саме тому, що черга
-- тримає координату — два рядки, що перекриваються, розвʼязуються з одного
-- джерела в один момент і дають однакове число. Надлишкове перевідправлення,
-- ніколи не розходження. Форму відкладали, доки не зʼявиться писач; писач
-- зʼявився (запис у чергу з доменних транзакцій), і ось форма (Ц15).
--
-- ── Семантика ─────────────────────────────────────────────────────────────
--
-- `stay_date..stay_date_to` ВКЛЮЧНО, як `date_from/date_to` у вендора. NULL —
-- одна ніч, і батчер читає її як «та сама дата». Кінець не раніше за
-- початок: перевіряє код, бо CHECK на SQLite не додати до наявної таблиці.
-- Писач обрізає діапазон горизонтом (500 ночей — стільки бере повний синк),
-- батчер — сьогоднішнім днем: минулих ночей вендор не приймає.
--
-- ── Індекс злиття ─────────────────────────────────────────────────────────
--
-- Кінець діапазону входить у ключ: той самий діапазон двічі — один рядок, як
-- і та сама дата; два різні діапазони — два рядки. `CREATE … IF NOT EXISTS`
-- за іменем старий індекс не оновив би (той самий обхід, що з констрейнтами,
-- AGENTS §4), тому спершу DROP. Вираз мусить дослівно збігатися з ціллю
-- `ON CONFLICT` у `outbox.repo.ts` — конфлікт збігається з ІНДЕКСОМ.
--
-- Живих даних немає: черга ще не мала писачів поза перевірками (Р11).

ALTER TABLE cm_outbox
  ADD COLUMN IF NOT EXISTS stay_date_to DATE;

DROP INDEX IF EXISTS idx_cm_outbox_coord;

CREATE UNIQUE INDEX IF NOT EXISTS idx_cm_outbox_coord
  ON cm_outbox (connection_id, kind, (COALESCE(unit_type_id, '')), (COALESCE(rate_plan_id, '')),
                stay_date, (COALESCE(stay_date_to, stay_date)))
  WHERE claimed_at IS NULL AND sent_at IS NULL;
