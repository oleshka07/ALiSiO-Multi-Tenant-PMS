-- 0130: коли каталог цього зʼєднання востаннє їздив до вендора.
--
-- Навіщо. Рід житла (`properties.property_type`) — вісь РАХУНКУ вендора:
-- готельна група тарифікується за обʼєкт, оренда за юніт
-- (`docs/vendor/channex/billing-2026-09-09.md`). Оператор міняє це поле,
-- бачить успішне збереження — і у вендора лишається старий рід доти, доки
-- хтось не зробить синк каталогу з іншої причини. Шлях оновлення існує
-- (`PUT /properties/:id`, П1), але живе ВСЕРЕДИНІ `syncConnectionCatalog`, і
-- ніщо не запускає його після правки обʼєкта (Р15.1).
--
-- Що дає ця колонка. Мітку, з якою можна ЛОКАЛЬНО сказати «наш обʼєкт
-- змінився після того, як ми востаннє відправили його вендору»:
-- `properties.updated_at > cm_connections.catalog_synced_at`. Без походу до
-- вендора — екран не має права ходити в чужий API, щоб намалювати підказку,
-- а гейт не має права залежати від мережі.
--
-- Чому мітка, а не знімок надісланих полів. Знімок точніший, але дорожчий і
-- зайвий: усе, що ми взагалі відправляємо (`PROPERTY_FIELDS_WE_OWN` —
-- назва, валюта, країна, місто, адреса, індекс, пошта, телефон, пояс, рід
-- житла), лежить на тому самому рядку `properties` і рухає той самий
-- `updated_at`. Тобто мітка не бреше — вона лише трохи щедріша: правка
-- телефону теж скаже «каталог розійшовся», і це ПРАВДА, бо телефон ми
-- вендору теж шлемо.
--
-- Чому не `last_full_sync_at`, яка вже є. Та мітка про ARI — наявність і
-- ціни, зовсім інший прохід і зовсім інша частота. Змішати їх означало б,
-- що нічна розсилка цін «полагодила» рід житла, якого ніхто не надсилав.
--
-- Наявних даних не чіпає: `NULL` означає «каталог іще не їздив», і читач
-- (`propertyCatalogDrift`) вважає таке зʼєднання не розійденим — обʼєкта у
-- вендора ще немає, розходитись нема з чим.
ALTER TABLE cm_connections ADD COLUMN IF NOT EXISTS catalog_synced_at TIMESTAMPTZ;
