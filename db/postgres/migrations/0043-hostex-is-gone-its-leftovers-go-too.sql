-- Хвости Hostex: те, чого не читає ніхто.
--
-- Міст Hostex видалено рішенням власника 2026-08-22. Лишились три речі, і
-- всі три — не «історичні дані», а порожні місця, які виглядають як робочі
-- підсистеми.
--
-- ── Що ЛИШАЄТЬСЯ, і чому ──────────────────────────────────────────────────
--
-- `reservations.hostex_reservation_code` і `hostex_channel_type` НЕ чіпаємо.
-- Їх читають екрани: перший — код броні в каналі, за яким її ще можна
-- звірити; другий — єдине місце, що каже «ця бронь прийшла з Airbnb», бо
-- `source` у таких рядків «direct». Це історія, а не інтеграція: нових
-- рядків не буде, старі лишаються читабельними — так само, як рядки
-- `fin_operations` з `source='teya'`.
--
-- `availability_blocks.hostex_code` — з тієї ж причини: блокування, що
-- приїхало з каналу, лишається впізнаваним.
--
-- ── Що ЙДЕ ────────────────────────────────────────────────────────────────
--
-- Три колонки, які існували лише у списку `ALTER TABLE ADD COLUMN` у
-- `src/lib/db.ts`: жоден запит їх не вибирав, жоден код не писав.
ALTER TABLE "reservations" DROP COLUMN IF EXISTS "hostex_stay_code";
ALTER TABLE "reservations" DROP COLUMN IF EXISTS "hostex_channel_id";
ALTER TABLE "reservations" DROP COLUMN IF EXISTS "hostex_listing_id";

-- `guest_chat_messages` — листування гостя й готелю. Таблиця створювалась,
-- індексувалась, і жоден рядок коду її не читав і не писав. Приїхала разом
-- із мостом; чат гостя, коли зʼявиться, буде іншим і матиме свою таблицю.
DROP TABLE IF EXISTS "guest_chat_messages";

-- `payment_webhook_log` — журнал вебхуків Teya. Три індекси, дописування
-- орендаря в міграції 0005 — і жодного запису за весь час.
--
-- Порожня таблиця з індексами гірша за її відсутність: адміністратор,
-- якому сказали «подивись у журнал вебхуків», побачить порожньо й вирішить,
-- що вебхук не приходив, — замість того щоб дізнатися, що журналу немає.
DROP TABLE IF EXISTS "payment_webhook_log";
