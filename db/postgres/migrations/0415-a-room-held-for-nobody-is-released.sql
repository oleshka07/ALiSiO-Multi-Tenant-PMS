-- Бронь, яку гість почав і не підтвердив, тримає номер — і звільняє його сама.
--
-- КІ23: бронь із гостьового застосунку народжується `tentative`, бо
-- справжньою її робить ПІДТВЕРДЖЕННЯ ГОСТЯ. Наслідок, якого рішення не
-- називало, але без якого воно не працює: `tentative` уже стоїть у вікні
-- `no_double_booking` (0133) і в пошуку застосунку. Тобто гість, який обрав
-- номер і пішов пити каву, забирає кімнату НАЗАВЖДИ — звільняти її нема кому.
--
-- Тому строк живе в самому рядку, а не в голові крона: крон, який рахує «30
-- хвилин від created_at», перестає бути правдою, щойно хтось захоче інший
-- строк для іншого готелю або продовження строку для гостя, який ще пише
-- прізвище. Порожня колонка означає «ніхто не тримає» — так у всіх броней,
-- заведених не воротами.
ALTER TABLE reservations ADD COLUMN IF NOT EXISTS hold_expires_at TIMESTAMPTZ;

-- Індекс частковий: крон питає рівно «у кого строк минув», а таких рядків у
-- базі одиниці проти сотень тисяч броней без строку взагалі.
CREATE INDEX IF NOT EXISTS idx_reservations_hold_expires
  ON reservations (hold_expires_at) WHERE hold_expires_at IS NOT NULL;
