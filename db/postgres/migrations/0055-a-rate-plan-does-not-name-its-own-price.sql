-- Тариф не називає власної ціни: `rate_plans.fixed_price` геть (рішення Ц7).
--
-- ── Що це була за колонка ─────────────────────────────────────────────────
--
-- Вона існувала з першого дня і НЕ МАЛА ЖОДНОГО ЧИТАЧА Й ЖОДНОГО ПИСАЧА за всю
-- історію `src/` — перевірено `git log -S`. Три гілки у віджеті (пошук,
-- календар, бронювання) питали `fixed_price` в обʼєкта, зчитаного із
-- `site_rate_plans`, а там такої колонки немає ніколи: мертвий код над мертвою
-- колонкою, який мовчки віддавав базову ціну там, де мав віддати фіксовану.
--
-- Рішення Ц7 зробило це не недоглядом, а забороною: ціну ночі називає лише
-- `priceNights()`, точка збуту її ЗСУВАЄ через `pricing_modifier_percent`.
-- Колонка, у якій тариф МОЖЕ написати власне число, — заряджена рушниця:
-- наступний читач з'явиться без жодної помилки, і дві ціни на одну дату
-- розійдуться мовчки.
--
-- ── Чому не просто DROP ───────────────────────────────────────────────────
--
-- «Писача не було» — це твердження про КОД. Про базу воно нічого не доводить:
-- рядок міг зʼявитися з psql. Тому спершу питаємо базу, і якщо там є хоч одне
-- непорожнє значення — міграція ВІДМОВЛЯЄ і не видаляє нічого (інваріант 13:
-- перевірка, яка не знайшла очікуваного, відмовляє, а не дозволяє).
--
-- Оператор побачить це як зупинений деплой із числом у повідомленні, а не як
-- тихо викинуті гроші. Що робити далі — рішення людини, і воно записується
-- окремою міграцією.
--
-- `row_security = off` тут не потрібен (міграції ходять власником-суперкорис-
-- тувачем, RLS його не стосується), але й не завадить, якщо колись
-- ходитимуть не ним: під FORCE RLS запит тоді ВПАДЕ з помилкою, а не поверне
-- порожнечу. Обидва варіанти — відмова, і це те, чого ми хочемо: `count(*)`,
-- який бачить нуль через політику, а не через порожню колонку, — це рівно та
-- брехня, від якої застерігає інваріант 13.

DO $$
DECLARE
  filled bigint;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'rate_plans'
       AND column_name = 'fixed_price'
  ) THEN
    RETURN;   -- нова база: колонки не було й у schema.sql
  END IF;

  SET LOCAL row_security = off;
  EXECUTE 'SELECT count(*) FROM rate_plans WHERE fixed_price IS NOT NULL' INTO filled;

  IF filled > 0 THEN
    RAISE EXCEPTION
      'rate_plans.fixed_price має % непорожніх значень — міграція зупинена. Жоден рядок коду її ніколи не читав і не писав, тож ці числа з''явились поза застосунком. Рішення про них ухвалює людина: перенести в pricing_modifier_percent (Ц7) або свідомо викинути окремою міграцією.',
      filled;
  END IF;

  ALTER TABLE rate_plans DROP COLUMN fixed_price;
END $$;
