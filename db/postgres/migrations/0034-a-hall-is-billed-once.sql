-- Зала виставляється в рахунок один раз.
--
-- Кнопка «Рахунок» на екрані залів робить три кроки поспіль: кладе позиції на
-- фоліо броні, випускає рахунок, відкриває PDF. Другий крок ідемпотентний —
-- `openFolio` повертає наявне фоліо, а `issueInvoice` відмовляється брати вже
-- зафактуровану позицію. Перший — ні: `postEventCharges` при кожному виклику
-- ДОДАЄ нові рядки.
--
-- Тому друге натискання кладе ту саму залу й ті самі доповнення ще раз, і
-- наступний випуск бере їх як нові. Готель отримує другий рахунок із тим самим
-- заходом, з іншим номером у книзі рахунків. Це не чернетка й не попередній
-- перегляд: у Німеччині номер видано, і прибрати його можна лише сторно.
--
-- `setBilling(true)` на екрані блокує лише подвійний клік у межах одного
-- запиту. Портьє, який відкрив діалог удруге — бо не побачив PDF, бо гість
-- попросив ще каву, бо перший раз здався невдалим, — отримує дублікат.
--
-- Тут запам'ятовується РЯДОК, а не прапорець «уже виставлено».
--
-- Прапорець сказав би «залу оплачено» і збрехав би у двох випадках: коли рядок
-- сторновано (тоді залу треба виставити наново, і система мусить дозволити) і
-- коли доповнення додають пізніше — додаткова кава на тому ж заході це
-- нормальна операція, а не дублікат. Посилання на рядок відповідає на обидва
-- питання само: рядок живий — зала вже в рахунку; рядка немає або він
-- сторнований — можна виставляти.
--
-- Доповнення свідомо НЕ обмежуються: їх додають до заходу законно.
