-- Наліпка відчиняє рядок і в БАЗІ, ЯКА ВЖЕ ЖИЛА.
--
-- ── Що було зламано на живій беті ───────────────────────────────────────
--
-- Оператор видав ключ карткою застосунку, відкрив `/stay/<ключ>` і дістав
-- 404. Ключ правильний, вимикач увімкнений, код розгорнутий — а сторінки
-- немає.
--
-- Причина: політика. `properties` читається публічною перепусткою
-- (інваріант 14) — `runWithPublicToken(ключ)` ставить `app.public_token` на
-- зʼєднання, і рядок має відчинити САМА політика. Дзеркало цього рядка я
-- додав у `PUBLIC_TOKEN_READ` (`scripts/pg-schema.mjs`), тобто НОВА база
-- політику дістала. А міграції не написав — і кожне середовище, яке вже
-- жило (бета, прод), лишилося зі старою політикою назавжди.
--
-- Виміряно на стенді тим самим запитом: зі старою політикою читання ключа
-- роллю застосунку віддає 0 рядків, з новою — 1.
--
-- Коментар у міграції 0411 попереджав про це дослівно: «Дзеркало цього рядка
-- — PUBLIC_TOKEN_READ у pg-schema.mjs, щоб схема нового клієнта збіглася з
-- мігрованою». Я зробив половину дзеркала.
--
-- ── Чому цього не спіймав жоден гейт ────────────────────────────────────
--
-- `check-schema-drift` порівнює колонки, індекси, таблиці й констрейнти —
-- ПОЛІТИК серед них немає. Але навіть із політиками він цього не побачив би:
-- обидві його бази починаються з `schema.sql`, тож те, що є в `schema.sql` і
-- чого не приносить жодна міграція, присутнє в ОБОХ. Напрямок «schema.sql
-- має щось, чого міграція не дає» — той самий, що в його шапці названий
-- метою, — не виявляється за побудовою. Записано як INC-210.
--
-- ── Що саме відчинено ───────────────────────────────────────────────────
--
-- Лише ЧИТАННЯ і лише по `guest_app_key`. Запис — як усюди, під орендарем:
-- `WITH CHECK` не змінюється. Вікно, у якому перепустка щось значить,
-- шириною в один запит — прочитавши рядок, застосунок іде звичайним
-- `runWithOrganization`.
ALTER TABLE properties ENABLE ROW LEVEL SECURITY;
ALTER TABLE properties FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS properties_tenant ON properties;
CREATE POLICY properties_tenant ON properties
  USING (organization_id = current_setting('app.organization_id')
     OR guest_app_key = NULLIF(current_setting('app.public_token', true), ''))
  WITH CHECK (organization_id = current_setting('app.organization_id'));
