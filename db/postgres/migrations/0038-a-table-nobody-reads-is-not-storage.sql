-- Таблиця, з якої ніхто не читає, — не сховище.
--
-- Дві таблиці створювалися на кожній базі й не мали жодного читача:
--
--   settings(key, value, updated_at)
--     Ключ-значення без `organization_id`. У мультитенантній базі це не
--     «глобальні налаштування», а спільна миска: перший готель, який щось
--     туди запише, перезапише те саме іншому. Саме тому в неї так ніхто й не
--     написав — усі налаштування живуть у `organization_settings`,
--     `property_guest_config`, `organization_features` і `site_settings`,
--     кожне зі своїм орендарем. Порожня таблиця без орендаря — це не запас
--     на майбутнє, це пастка: наступний, хто побачить назву `settings`,
--     вирішить, що місце для налаштувань уже є.
--
--   cost_allocations(month, alloc_method, business_unit_id, percentage)
--     Розподіл витрат по напрямах. Писала її форма, якої немає; читав її
--     єдиний `SELECT COUNT(*)` у `countLinkedRows` — тобто перевірка «чи
--     можна видалити напрям», яка на порожній таблиці завжди відповідала
--     «так». Таблиця жила рівно стільки, щоб про неї згадували в підказці
--     інтерфейсу: «витрати розподіляються через cost_allocations». Не
--     розподілялися.
--
-- Обидві прибираємо разом зі створенням у `src/lib/db.ts`. Розподіл витрат
-- повернеться модулем із екраном, правилами і власником рядка — тоді ж
-- зʼявиться і таблиця, з орендарем у ключі.
--
-- `IF EXISTS` навмисно: на беті це вже могло проїхати іншим шляхом, і
-- міграція, яка падає на відсутній таблиці, зупиняє деплой цілком.
DROP TABLE IF EXISTS "cost_allocations";
DROP TABLE IF EXISTS "settings";
