-- 0096: операція знає рядок, який вона поклала в книгу гостя (Р10.6)
--
-- Гроші за бронь лежать у двох книгах: платіж у `fin_folio_payments` і рядок
-- `fin_operations`. Видалення другого мусить зняти перший — інакше рахунок
-- гостя показує сплачене, якого вже ніде немає (INC-025 сусід, Р8.7).
--
-- Але реверс мусить знати, ЩО саме він знімає. Доти він знімав із фоліо
-- будь-який дохід із `reservation_id`, а відрізнити свій платіж від чужого
-- було нічим: `source` не розрізняє — місток теж пише 'manual'.
--
-- Наслідок без жодної помилки в системі: гість платить 5000 готівкою (у фоліо
-- 5000), бухгалтер заводить у Фінансах помилковий дохід 1200 з
-- `reservation_id` — за Д21 у фоліо він не лягає, — потім видаляє його, і
-- реверс забирає 1200 З ГРОШЕЙ ГОСТЯ. Рахунок показує 3800 при 5000 у касі,
-- бронь стає `partial`, на виселенні борг, якого гість не винен.
-- Пара була асиметрична: створення у фоліо не додає, видалення знімає.
--
-- Порожня колонка означає «ця операція у книзі гостя нічого не клала» — стан
-- переважної більшості рядків, усіх ручних проводок обліку. Тому спадок не
-- заповнюється: колонка описує, що операція ЗРОБИЛА, а для старих рядків це
-- невідомо, і вгадувати означало б повернути ту саму діру заднім числом.
--
-- Зовнішнього ключа тут НЕМАЄ навмисно. Ключ на `fin_folio_payments(id)`
-- повторив би INC-025 — посилання без орендаря, — а складений ключ по
-- (organization_id, id) вимагає унікального індексу на цю пару і робиться
-- разом із рештою довідників. Посилання резолвиться запитом, у якому
-- орендар названий явно; видалення платежу у фоліо не існує за задумом, тож
-- висяче посилання виникнути не може.

ALTER TABLE fin_operations ADD COLUMN IF NOT EXISTS folio_payment_id TEXT;
