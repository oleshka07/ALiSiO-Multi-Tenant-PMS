-- 0423: повтор знімка лишає слід.
--
-- ── Що було видно оператору ───────────────────────────────────────────────
--
-- Власник прислав таблицю знімків із живої беты: десять рядків «дельта дня»
-- і ДІРКА о 05:00. Дірка читається однозначно — «агент не бігав, ПК вимкнули,
-- щось зламалось». Насправді агент бігав і приніс те саме: вночі готель не
-- працює, вікно дельти (сьогодні −1 … +3) не змінюється, байти ті самі, тож
-- sha256 збігається — і маршрут віддає наявний рядок (`duplicate: true`), не
-- створюючи нового.
--
-- Захист від подвійного завантаження правильний: два однакових знімки — це
-- один знімок, і зберігати його двічі немає сенсу. Неправильна ПОДАЧА:
-- оператор не може відрізнити «не бігав» від «бігав і приніс те саме», а
-- саме цю різницю екран і створений показувати (INC-053).
--
-- Питання перестає бути косметичним рівно тоді, коли ПК готелю почнуть
-- вимикати на ніч: «тиша» стане звичайним станом, і відрізнити її від смерті
-- агента можна буде тільки цим стовпцем.
--
-- ── Чому лічильник на рядку-переможці, а не нові рядки ────────────────────
--
-- Нові рядки на кожен повтор зламали б `UNIQUE (organization_id, sha256)` —
-- ту саму умову, якою тримається «один знімок = один рядок», — і за тиждень
-- дали б 600 рядків там, де знімків десять. Лічильник відповідає на те саме
-- питання («коли агент озивався востаннє») і нічого не ламає.
--
-- `seen_count` починається з 1, а не з 0: рядок існує тому, що знімок принесли
-- ОДИН раз. Нуль означав би «ніколи не бачили», а такого рядка не буває.
--
-- `last_seen_at` порожній у наявних рядках і це правильно: коли їх бачили
-- востаннє, ми не знаємо і вигадувати не будемо (`received_at` — це коли
-- ПРИЙНЯЛИ, інша подія). Екран у такому разі показує саме прийом.

-- BIGINT, а не INTEGER, і це не про розмір числа. `scripts/pg-schema.mjs`
-- виводить тип із локальної SQLite, де лічильник — `INTEGER`, і для свіжого
-- клієнта пише `BIGINT`. Міграція з `INTEGER` дала б дві РІЗНІ бази: створену
-- зі `schema.sql` і мігровану, — а `check-schema-drift` у CI порівнює саме їх
-- і червоніє за означенням (клас Д65: тип, виведений генератором, проти типу,
-- оголошеного рукою). Сусідні лічильники тут теж BIGINT (`sort_order`,
-- `next_debtor_no`).
ALTER TABLE winhotel_snapshots ADD COLUMN IF NOT EXISTS seen_count BIGINT NOT NULL DEFAULT 1;
ALTER TABLE winhotel_snapshots ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ;
