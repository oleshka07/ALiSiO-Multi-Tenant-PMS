-- 0142: недороблена TSS запамʼятовується, а не створюється вдруге.
--
-- Блок «Застосунки», рецензія 2 (А1, А2). Підключення TSE — шість кроків до
-- вендора, і кожна TSS у fiskaly коштує грошей. Якщо `PUT /tss` пройшов, а
-- наступний крок упав, TSS існує, а рядок обʼєкта — ні; наступний натиск
-- створював би другу. І два ОДНОЧАСНІ натиски створювали дві: перевірка
-- `tss_id IS NULL` читалась до походу до вендора.
--
-- `tse_pending_tss_id` — id TSS, створеної у fiskaly, але не персоналізованої
-- до кінця; разом із `tse_admin_puk` (0141) її можна дограти. NULL — немає
-- такої. `tss_id` при цьому лишається NULL: недороблена TSS не підписує.
--
-- `tse_connecting_at` — замок на час походу до вендора: писач ставить його
-- одним UPDATE з умовою «замка немає», і другий запит, який цієї умови не
-- пройшов, дістає 409, не другу TSS. Знімається наприкінці; замок, старший за
-- десять хвилин, вважається покинутим (процес упав посеред кроків).
--
-- Наявних даних не чіпає: NULL в обох.
-- SQLite-дзеркало — `src/lib/db.ts`, `migrateApps()`.

ALTER TABLE fin_fiscal_settings ADD COLUMN IF NOT EXISTS tse_pending_tss_id TEXT;
ALTER TABLE fin_fiscal_settings ADD COLUMN IF NOT EXISTS tse_connecting_at TIMESTAMPTZ;
