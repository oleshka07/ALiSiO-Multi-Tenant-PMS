-- Ціна вихідних нуль — це не ціна (рецензія Блоку 2.0, 05.09.2026).
--
-- 0062 зробила «нуль — не ціна» лише для `base_price`: наявні нулі стали NULL,
-- писачі відмовляють. `weekend_price` лишився поза цим: писачі відмовляють
-- нулю й там (`assertPositivePrice`), але нулі, записані раніше, читались як
-- ціна — і з пʼятниці по неділю ніч продавалась за 0 тим самим шляхом, який
-- INC-017 закрив для буднів. Читач (`nightly-price.ts dayPrice`) тепер читає
-- 0 як «немає» незалежно від бази; цей крок прибирає саме число, щоб екран
-- цін і експорти не показували 0 там, де ціни вихідних просто немає.
--
-- Повторно накочується без наслідків.

UPDATE price_calendar SET weekend_price = NULL WHERE weekend_price <= 0;
