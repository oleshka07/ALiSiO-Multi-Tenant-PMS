-- Блок 6: «розширені ціни» — перемикач ГОТЕЛЮ, не браузера.
--
-- Привід не гіпотетичний. 07.09.2026 власник — автор системи — не зміг
-- поставити ціну 333 на 22 листопада. Не через баг: на дні лежала ціна
-- вихідних 115, вона перебивала базову беззвучно, і ніде на екрані не було
-- сказано, звідки взялося число. Перегравання сертифікації коштувало близько
-- сорока прогонів, з них половина — переробка після таких пасток. Для готелю
-- на 1–15 номерів чинний екран цін непрохідний.
--
-- Тому екран отримує простий режим: за замовчуванням видно «Ціну» і
-- «Мін. ночей», а ціна вихідних, матриця заселеності, CTA/CTD і максимум
-- ночей — за перемикачем.
--
-- Чому колонка організації, а не `localStorage`. Стан «цей готель уже
-- працює з розширеними цінами» належить ГОТЕЛЮ: інакше другий адміністратор
-- відкриває той самий екран у своєму браузері й бачить інший набір полів —
-- а поруч у цьому ж продукті вже є випадок, коли невидиме поле міняло гроші.
-- Дефолт FALSE: новий готель починає з простого екрана.
ALTER TABLE organizations ADD COLUMN IF NOT EXISTS pricing_advanced BOOLEAN NOT NULL DEFAULT FALSE;
