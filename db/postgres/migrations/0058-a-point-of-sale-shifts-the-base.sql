-- Зсув точки збуту переїжджає на зʼєднання: `cm_connections.pricing_modifier_percent`.
--
-- ── Що саме вирішує Ц7 ────────────────────────────────────────────────────
--
-- Ціна одна: база з `price_calendar × rate_plans`, названа `priceNights()`.
-- Кожна точка збуту — сайт і зʼєднання з каналом — має власний відсоток, який
-- ЗСУВАЄ базу і нічого не називає. Модифікатор однієї точки збуту ніколи не
-- потрапляє в іншу; це і є визначення «прямо дешевше».
--
-- До цієї міграції зсувати вмів лише сайт. Канал отримував немодифіковану
-- базу — асиметрія, а не рішення, і саме вона породила розвилку Ц7.
--
-- ── Чому число ЗНАКОВЕ, а не пара «відсоток + напрямок» ───────────────────
--
-- Сайтова колонка зроблена парою: `pricing_modifier_percent` плюс
-- `pricing_modifier_type` зі значеннями `less`/`more`. Два поля можуть
-- суперечити одне одному — відʼємний відсоток із напрямком «дешевше» це
-- подвійне заперечення, і жоден із двох читачів не зобовʼязаний тлумачити
-- його однаково. Тут одне знакове число: -10 дешевше, +10 дорожче.
--
-- ── Чому DEFAULT 0, хоч сусідня міграція 0057 нуля цурається ──────────────
--
-- Бо це різні нулі. Нуль ціни дитини означав би «безкоштовно» — ціну, якої
-- готель не називав. Нуль зсуву означає «як база», тобто буквально
-- відсутність дії: точка збуту, яка нічого не сказала, нічого й не міняє.
--
-- ── Живих даних це не чіпає ───────────────────────────────────────────────
--
-- Виміряно на проді 01.09.2026 (`deploy/measure-price-modifier.sh prod`,
-- роллю-власником під `row_security = off`): `site_rate_plans` ПОРОЖНЯ,
-- `rows_total = 0`. Тобто перенесення — чистий рух схеми, нічиїх грошей не
-- торкається (рішення Р12).

ALTER TABLE cm_connections
  ADD COLUMN IF NOT EXISTS pricing_modifier_percent NUMERIC(5,2) NOT NULL DEFAULT 0;
