-- INC-301. Ключ походження: повторний імпорт не заводить тих самих людей удруге.
--
-- ── Навіщо саме зараз ───────────────────────────────────────────────────
--
-- Імпорт Winhotel прогонять щонайменше двічі — раз пробно, раз насправді. Без
-- ключа походження другий прогін заведе всі 34 795 живих адрес удруге, і
-- дублікати розповзуться по бронях, фактурах і згодах ще до того, як хтось
-- гляне на результат. Це не «покращення потім», а умова того, щоб імпорт
-- узагалі можна було прогнати двічі.
--
-- ── Виміряно, а не переказано ───────────────────────────────────────────
--
-- CORE-GAPS п. 12 припускав, що місце вже є: «`import_entity_mappings` —
-- САМЕ ВОНА і є місцем; перевірити її форму». Перевірено: **такої таблиці в
-- схемі немає взагалі**. З 24 сутностей, які заводить імпорт (IMPORT-PLAN §1),
-- чуже посилання має куди лягти рівно у ДВОХ:
--
--   reservations.external_uid   — і воно ЗАЙНЯТЕ: пишуть iCal-синк і канали,
--                                 причому спільно («не ключ» — так і сказано
--                                 в `ical-sync.handlers.ts:144`);
--   fin_operations.source_ref   — пара до `source`, для фінансових проводок.
--
-- Решта 22 — без місця. Тут заводиться колонка на ДВОХ, названих у задачі
-- (гості й броні); решта лишається списком у звіті, а не колонками наперед.
--
-- ── Чому окрема колонка, а не `external_uid` ────────────────────────────
--
-- Те поле ділять кілька шляхів запису, і саме тому воно не унікальне. Класти
-- туди ще й походження імпорту означало б, що на питання «звідки ця бронь»
-- відповідає той, хто записав останнім. А без унікальності колонка не тримає
-- нічого — тобто не робить того, заради чого заводиться.
--
-- ── Значення — КВАЛІФІКОВАНЕ ────────────────────────────────────────────
--
-- `winhotel:adressen:1234` — система, таблиця, ідентифікатор у ній. Один
-- рядок замість пари колонок «система» + «ключ»: пара розходиться (рядок із
-- ключем і без системи нічого не означає), а `guests.source` уже зайнятий
-- іншим змістом (`direct`/…), і перевантажувати його було б тим самим.
--
-- ── Предикат — це РОЗМІР, а не правильність. Виміряно ───────────────────
--
-- Спершу тут стояло протилежне: «без предиката другий гість без походження не
-- завівся б». Це неправда, і перевірено прямо — тимчасова таблиця з
-- УНІКАЛЬНИМ індексом БЕЗ предиката прийняла два рядки з `NULL` в обидва боки:
-- у унікальному індексі NULL-и не рівні між собою (`NULLS DISTINCT` — типова
-- поведінка), тож рядки без походження не конфліктують ні з чим за означенням.
--
-- Отже `WHERE external_ref IS NOT NULL` тримає індекс малим — у ньому лежать
-- лише імпортовані рядки, а не всі гості готелю, — і не тримає нічого більше.
-- Записано саме так, бо це ДРУГИЙ випадок тієї самої хибної підстави за дві
-- доби: у 0133 такою ж «умовою, що тримає смугу», виглядав `unit_id IS NOT
-- NULL`, і теж не тримав. Пояснення правильної поведінки не тією причиною
-- переживає код: наступний, хто спростить предикат, вирішить, що ламає
-- заборону, — а він її не ламає.

ALTER TABLE "guests"       ADD COLUMN IF NOT EXISTS "external_ref" TEXT;
ALTER TABLE "reservations" ADD COLUMN IF NOT EXISTS "external_ref" TEXT;

-- Унікальність включає ОРЕНДАРЯ (інваріант 3): `ADRESSEN.LNR = 1` існує в
-- кожній базі Winhotel на світі, і тотальний індекс зробив би неможливим
-- імпорт другого готелю.
CREATE UNIQUE INDEX IF NOT EXISTS idx_guests_external_ref
  ON "guests" ("organization_id", "external_ref") WHERE "external_ref" IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_reservations_external_ref
  ON "reservations" ("organization_id", "external_ref") WHERE "external_ref" IS NOT NULL;
