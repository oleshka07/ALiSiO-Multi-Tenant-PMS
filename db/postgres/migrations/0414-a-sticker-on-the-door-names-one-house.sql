-- Гостьовий застосунок: ключ, яким наліпка на дверях називає свій будинок.
--
-- Сторінка, куди веде QR зі скла, публічна — сесії там немає за визначенням.
-- Тому орендаря мусить називати сама адреса, інакше публічний endpoint
-- вгадував би його мовчазним дефолтом (інваріант 8).
--
-- ── Чому колонка, а не `booking_sites` ──────────────────────────────────
--
-- Кандидат «взяти slug наявного сайту» відхилено: той рядок описує ВІДЖЕТ,
-- вбудований у власний сайт готелю; його `slug` буває порожній, а
-- `provisionOrganization` сайту не створює взагалі. Новий готель дістав би
-- застосунок без адреси, і виявилось би це вже в холі.
--
-- ── Чому на обʼєкті, а не на організації ────────────────────────────────
--
-- Наліпка висить на дверях КОНКРЕТНОГО корпусу, і гість, який її сканував,
-- стоїть саме там. Рахунок із двома корпусами дістає два ключі й дві наліпки.
ALTER TABLE properties ADD COLUMN IF NOT EXISTS guest_app_key TEXT;

-- Унікальний СЕРЕД ЗАПОВНЕНИХ: порожньо = застосунок ще не ввімкнено, і
-- таких обʼєктів більшість. Це ОБМЕЖЕННЯ, не пришвидшення — без нього два
-- обʼєкти могли б дістати один ключ, і QR одного готелю відчиняв би сторінку
-- другого. Предикат обовʼязковий: тотальний індекс тут забороняв би ДРУГИЙ
-- обʼєкт без ключа.
CREATE UNIQUE INDEX IF NOT EXISTS idx_properties_guest_app_key
  ON properties (guest_app_key) WHERE guest_app_key IS NOT NULL;
