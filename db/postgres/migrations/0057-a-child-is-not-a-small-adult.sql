-- Ціна дитини: `rate_plans.child_extra_gross` (рішення Ц12).
--
-- ── Що саме розділяється ──────────────────────────────────────────────────
--
-- До 01.09.2026 цінова матриця адресувалася сумою «дорослі + діти»
-- (`price_occupancy.persons`), тобто дитина коштувала рівно як доросла, а
-- сімʼя 2+2 платила за чотирьох.
--
-- Розділ при цьому вже існував УСЮДИ, крім ціни: `unit_types` має
-- `max_adults`/`max_children`/`max_occupancy`, `reservations` — `adults`/
-- `children`/`infants`. Сплющувала його одна колонка. Тепер `persons`
-- означає ДОРОСЛИХ, а дитина отримує власне число.
--
-- ── Чому на тарифі, а не на типі номера ───────────────────────────────────
--
-- Так каже Ц12, і так само влаштовано в менеджера каналів: `children_fee` та
-- `infant_fee` — атрибути ТАРИФУ. Це свідомо НЕ те саме, що доплата за
-- додаткового дорослого (Ц2), яка спільна для тарифів одного типу номера:
-- звести їх в одну колонку означало б стерти різницю між родами гостя, заради
-- якої рішення й ухвалене.
--
-- ── Чому nullable, і чому це не те саме, що нуль ──────────────────────────
--
-- NULL — «готель цього не називав», і тоді ніч із дітьми НЕ ПРОДАЄТЬСЯ:
-- домен повертає її в `missing` (інваріант 17). Нуль — теж ціна, але названа:
-- «діти безкоштовно», і каже це готель, а не міграція.
--
-- `DEFAULT 0` тут був би рівно тією помилкою, яка вже коштувала цьому проєкту
-- бронювання за нуль: `?? 0` у `bulkUpdatePrices` перетворював «ціни немає» на
-- «ніч коштує нуль», і котирування відповідало `hasPricing: true, total: 0`.
--
-- ── Живих даних це не чіпає ───────────────────────────────────────────────
--
-- На 01.09.2026 на проді немає жодного живого готелю — усі дані тестові
-- (рішення Р11). Саме тому перетлумачення осі робиться зараз: після першого
-- клієнта воно стало б міграцією нарахованих сум, а інваріант 18 забороняє
-- переписувати нараховане.

ALTER TABLE rate_plans ADD COLUMN IF NOT EXISTS child_extra_gross NUMERIC(14,2);
