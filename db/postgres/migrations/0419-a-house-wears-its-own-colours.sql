-- 0419: обʼєкт носить ВЛАСНІ кольори і власне лого.
--
-- ── Що було ─────────────────────────────────────────────────────────────
--
-- Гостьовий застосунок (`/stay/<ключ>`) і гостьова сторінка (`/guest/<токен>`)
-- — це те, що гість бачить замість рецепції. Обидві мали рівно один вигляд на
-- всіх клієнтів: теплий беж і латунь в одної, темна зелень у другої. Для
-- першого готелю це його бренд, для наступного — чужий одяг, і єдиним
-- способом відрізнятись було не заповнювати назву.
--
-- ── Чому дві колонки, а не таблиця теми ─────────────────────────────────
--
-- Бо міняється рівно дві речі, і обидві належать ОБʼЄКТУ: набір кольорів і
-- лого. Таблиця `property_theme` з десятком колонок під кожен відтінок була б
-- обіцянкою, якої ми не виконуємо: кольори між собою повʼязані (тло, чорнило,
-- лінія, акцент мусять бути читабельні разом), і готель, якому дали окремо
-- «колір кнопки», рано чи пізно зробить білу кнопку на білому.
--
-- Тому `brand_palette` — це ІМʼЯ набору, а не колір. Набори живуть у CSS
-- (`guest-app.css`, `guest-page.css`), реєстр імен — `src/core/brand-palettes.ts`,
-- і гейт `brand-palettes.check` стверджує, що обиране імʼя справді має блок на
-- ОБОХ поверхнях. Палітра, яку можна обрати і яка нічого не міняє, це
-- фальшивий вимикач (П5).
--
-- ── Імена названо КОЛЬОРОМ, не готелем ──────────────────────────────────
--
-- `teal_warm_grey`, `sand_brass`, `forest_stone`, `ink_amber` — інваріант 20.
-- Ключ на кшталт назви клієнта зробив би палітру його власністю: наступний
-- готель із бірюзою або обирав би зі списку чуже імʼя, або чекав би релізу
-- заради власних кольорів. Хто саме носить який набір — рядок у ЦІЙ колонці.
--
-- ── Дефолти порожні, і це важливо ───────────────────────────────────────
--
-- NULL у `brand_palette` читається як «той вигляд, що був» (`sand_brass` для
-- застосунку, поточний набір для сторінки). Жоден наявний готель не змінює
-- вигляду від самої міграції — те саме міркування, що в 0417 і 0410.
--
-- NULL у `brand_logo_url` означає «показати НАЗВУ готелю текстом». Назва є
-- завжди, лого — ні, і порожній прямокутник замість нього гірший за слово.
--
-- ── Чому TEXT без CHECK на палітру ──────────────────────────────────────
--
-- Той самий довід, що в 0410 про `kiosk_walkin_url`: CHECK тут означав би, що
-- нова палітра вимагає міграції бази. Слово звіряє КОД (`readBrandPalette`),
-- і невідоме значення дає дефолт, а не порожню сторінку — тобто найгірше, що
-- може статися від чужого рядка в колонці, це знайомі кольори.
--
-- RLS на `properties` уже стоїть (таблиця не нова), тож `check-migration-rls`
-- тут нічого не вимагає.

ALTER TABLE properties ADD COLUMN IF NOT EXISTS "brand_palette" TEXT;
ALTER TABLE properties ADD COLUMN IF NOT EXISTS "brand_logo_url" TEXT;
