-- Розписка вендора на відправленій координаті: `cm_outbox.receipt`.
--
-- ── Навіщо ────────────────────────────────────────────────────────────────
--
-- Менеджер каналів приймає ціну як ЗАДАЧУ: відповідь `200` з task id означає
-- «взяв», а не «застосував» (живий прогін 01.09 читав назад зарано і бачив
-- старе число). Батчер отримував розписку і викидав її на `markSent` — тож
-- асинхронний провал був невидимий: «мовчить і коштує грошей», той самий
-- клас, що черга без екрана (Ц14). Форма сертифікації Channex просить саме
-- ці розписки.
--
-- ── Семантика ─────────────────────────────────────────────────────────────
--
-- Одна пачка — одна розписка; рядок-діапазон, що поїхав кількома пачками,
-- несе всі свої через кому. NULL — рядок ще не відправлено або знято
-- (`retired:` у last_error). Стан задачі у вендора не читається — такого
-- ендпоінта немає; «доїхало» доводить читання календаря назад.
--
-- Живих даних немає: колонка додається до порожньої на проді черги.

ALTER TABLE cm_outbox
  ADD COLUMN IF NOT EXISTS receipt TEXT;
