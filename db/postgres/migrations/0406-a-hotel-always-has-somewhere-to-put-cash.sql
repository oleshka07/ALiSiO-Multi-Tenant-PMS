-- Готелю завжди є КУДИ покласти готівку.
--
-- ── Що сталося ──────────────────────────────────────────────────────────
--
-- Портьє на беті взяв 200 EUR, натиснув «Прийняти оплату», побачив «Платіж
-- додано!» — і нічого не змінилось: вартість 200, сплачено 0. Сервер при
-- цьому відповів 409 із бездоганним реченням («немає активного рахунку в
-- EUR, додайте касу»), а екран це речення викинув. Екран полагоджено окремо
-- (`payment-outcome.ts`), але саму ВІДМОВУ це не прибирає: готель і далі не
-- може взяти готівку, поки не заведе рахунок руками, про який ніхто не
-- сказав.
--
-- ── Чому в готелю не було каси ──────────────────────────────────────────
--
-- Засів каси зʼявився в `provisionOrganization` лише 08.09.2026 (INC-028,
-- коміт 7d26b79e); план рахунків — 07.09 (INC-025). Обидві правки лікують
-- НОВИХ клієнтів, і жодна не озирнулась на наявних: зворотного заповнення не
-- було написано ні тоді, ні потім. Тобто кожен готель, заведений до 08.09, —
-- а це всі, що зараз живуть на беті й проді, — лишився без каси, і перша ж
-- готівка на рецепції впиралась у 409.
--
-- Це той самий клас, що INC-025 і INC-028, лише з іншого боку: там колонки
-- не було в новій базі, тут рядка немає в старій. Правку «на майбутнє» без
-- зворотного заповнення видно лише на клієнтах, які вже є, — тобто на тих,
-- хто платить.
--
-- ── Кому саме заводиться ────────────────────────────────────────────────
--
-- Умова тут — РІВНО та, на якій відмовляє місток платежів
-- (`payment-bridge.ts`): немає активного рахунку типу `cash`/`bank` у валюті,
-- якою готель торгує. Не «немає жодного рахунку»: готель із банківським
-- рахунком у кронах і бронями в євро впирається в ту саму відмову, і
-- порахувати його «забезпеченим» означало б лишити його там, де він є.
--
-- Валюта — `organizations.default_currency`, не літерал. Каса в кронах
-- німецькому готелю не помогла б узагалі: місток шукає рахунок ЗА ВАЛЮТОЮ
-- операції, і відмова повернулась би там, де її найважче звʼязати з причиною
-- (той самий довід, що в `provisioning.ts`).
--
-- ── Назва ───────────────────────────────────────────────────────────────
--
-- Мовою готелю, тим самим списком, що в `provisionOrganization`
-- (`DEFAULT_CASH_ACCOUNT_NAME`). Тут це НЕ мовчазний дефолт і не дані
-- клієнта (інваріант 20): «Каса» — слово продукту, як `reservations.status`,
-- а не назва бізнесу; готель перейменує її одним полем у Фінансах.
--
-- Мова, якої немає в списку, отримує англійське `Cash`, а не порожнечу:
-- колонка `name` — NOT NULL, і рядок мусить народитись читабельним.
--
-- ── Ідемпотентність ─────────────────────────────────────────────────────
--
-- `WHERE NOT EXISTS` за ДАНИМИ, не `ON CONFLICT` за іменем обмеження: на
-- свіжій базі імена обмежень свої (AGENTS §4), і сторож за іменем знайшов би
-- не те. Другий прогін міграції не створює другої каси.

BEGIN;

-- ── 1. Каса тому, кому нема куди класти гроші ───────────────────────────
INSERT INTO "finance_accounts" (id, organization_id, name, type, currency, sort_order)
SELECT encode(gen_random_bytes(16), 'hex'),
       o.id,
       CASE o.language
         WHEN 'uk' THEN 'Каса'
         WHEN 'de' THEN 'Kasse'
         WHEN 'cs' THEN 'Pokladna'
         WHEN 'pl' THEN 'Kasa'
         WHEN 'nl' THEN 'Kas'
         WHEN 'fr' THEN 'Caisse'
         ELSE 'Cash'
       END,
       'cash',
       o.default_currency,
       1
  FROM "organizations" o
 WHERE NOT EXISTS (
   SELECT 1 FROM "finance_accounts" a
    WHERE a.organization_id = o.id
      AND a.currency = o.default_currency
      AND a.type IN ('cash', 'bank')
      AND a.is_active);

-- ── 2. І щоб гроші лягали в НЕЇ, а не «в перший за sort_order» ──────────
--
-- `app/api/payments` читає саме `default_cash_account_id` користувача, який
-- приймає гроші. Порожня колонка не ламає нічого сьогодні (готель має одну
-- касу, запасний шлях знайде її), але щойно кас стане дві — готівка почне
-- лягати в довільну з них, і розрізнити це можна буде лише за сумами.
--
-- Ставиться ЛИШЕ тим, у кого порожньо: чужий вибір не перезаписується.
UPDATE "app_users" u
   SET "default_cash_account_id" = a.id
  FROM "finance_accounts" a
 WHERE a.organization_id = u.organization_id
   AND u.default_cash_account_id IS NULL
   AND a.type = 'cash'
   AND a.is_active
   AND a.currency = (SELECT o.default_currency FROM "organizations" o WHERE o.id = u.organization_id)
   AND a.id = (
     SELECT a2.id FROM "finance_accounts" a2
      WHERE a2.organization_id = u.organization_id
        AND a2.type = 'cash'
        AND a2.is_active
        AND a2.currency = (SELECT o.default_currency FROM "organizations" o WHERE o.id = u.organization_id)
      ORDER BY a2.sort_order, a2.created_at
      LIMIT 1);

COMMIT;
