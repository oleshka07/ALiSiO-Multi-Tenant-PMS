-- Блок 5a, п. 2.1: вид із вікна, своя мережа і свій замок — на НОМЕРІ.
--
-- Рівнів гостьової сторінки було два — обʼєкт і тип номера, — і для коду
-- замка вже був третій, недоговорений: `units.lock_code` резолвер читає, а
-- редактор номера про нього не знає. Wi-Fi такого рівня не мав узагалі, хоча
-- в апарт-готелі мережа буває саме кімнатна, а не спільна.
--
-- `view` — вільний текст, а не довідник: вид із вікна конкретного номера
-- («у двір», «на липу») готель пише словами, і код для одиничного випадку
-- вигадувати не мусить. Стандартизований вид, який їде в OTA, — це зручність
-- ТИПУ з категорії VIEW (міграція 0111), і вона довідник.
--
-- Секретність: пароль мережі й код замка — дані готелю, не наш секрет, тож
-- шифрування як у `channel_credentials` тут зайве (розшифрувати їх мусить
-- гостьова сторінка на кожен показ). Але вони не логуються і не виходять за
-- межі орендаря: політика `units` уже стоїть, а гейт `check-isolation`
-- перевіряє це живим запитом сусіда.

ALTER TABLE units ADD COLUMN IF NOT EXISTS view TEXT;
ALTER TABLE units ADD COLUMN IF NOT EXISTS wifi_network TEXT;
ALTER TABLE units ADD COLUMN IF NOT EXISTS wifi_password TEXT;
