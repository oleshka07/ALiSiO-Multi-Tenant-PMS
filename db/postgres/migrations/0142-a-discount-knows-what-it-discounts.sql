-- Знижка на рядок фоліо — ОКРЕМИЙ рядок, який знає, від чого він.
--
-- ── Чому окремим рядком, а не правкою суми ──────────────────────────────
--
-- Для проживання це вже так: `lodging_discount_percent` дає рядок
-- «Übernachtung (−10 %)», і ставка успадковується за побудовою, бо знижка
-- береться ПІСЛЯ відділення сніданку (`splitOtaAmount`). Для послуг цього не
-- було взагалі.
--
-- Зменшити суму рядка «на місці» здається простішим і є гіршим одразу двома
-- боками. Бухгалтер перестає бачити, ЩО саме коштувало повну ціну і скільки
-- відпущено — у книгах лишається одне зменшене число без сліду знижки. А
-- документ держави перестає бути перевірюваним: сума ставки більше не
-- дорівнює сумі рядків цієї ставки.
--
-- У джерелі (Winhotel) це саме так і зроблено: знижка — окрема послуга з
-- відʼємною сумою і ВЛАСНИМ `STS` (`RABATT` під 7 %, `RABATT_19` під 19 %,
-- з різними рахунками обліку).
--
-- ── Чому потрібна колонка, а не сам лише текст опису ────────────────────
--
-- «Від чого знижка» мусить бути ФАКТОМ, а не рядком тексту: сторно або
-- видалення батьківського рядка інакше лишає знижку, яка вказує в нікуди —
-- рівно той клас, що Р10.14 (`invoice-delete.check`), тільки всередині
-- фоліо. `ON DELETE CASCADE`: знижки без того, від чого вона, не буває.
--
-- Ставку знижка НЕ несе власну — вона успадковує ставку батьківського рядка,
-- і це тримає писач (`discountCharge`) зі сценою. Колонка ставки в рядку вже
-- є (`vat_rate`), другої не заводимо: два джерела ставки розійшлися б.

BEGIN;

ALTER TABLE "fin_folio_items" ADD COLUMN IF NOT EXISTS "discount_of_item_id" TEXT
  REFERENCES "fin_folio_items"("id") ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS "idx_fin_folio_items_discount_of"
  ON "fin_folio_items" ("discount_of_item_id");

COMMIT;
