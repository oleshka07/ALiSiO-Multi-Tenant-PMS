-- Збір називає, з кого він береться і чиї це гроші.
--
-- ── Що було ───────────────────────────────────────────────────────────────
--
-- `fees_taxes` мала один класифікатор — `type`: `per_night`, `per_stay`,
-- `per_person`, `per_person_per_night`, `percentage`. Це МНОЖНИК: як розмазати
-- суму по ночах і гостях. Він не відповідає на два інші питання, і обидва
-- коштують грошей, коли їх вгадують.
--
-- **З кого береться.** Курортне мито в багатьох юрисдикціях звільняє дітей.
-- Раніше це «вирішувалось» тим, що `per_person_per_night` рахував лише
-- дорослих, а сусідній `per_person` — усіх; два поля з тим самим словом
-- «person» рахували різні множини людей, і ніде не було сказано чому. Готель
-- зі збором «Сніданок, за особу за ніч» недобирав на кожній дитині й бачив це
-- аж у звіті. Арифметику вирівняли (обидва рахують усіх), а звільнення стало
-- тим, чим воно є — окремим ПРАВИЛОМ, а не мовчазною переінтерпретацією.
--
-- **Чиї це гроші.** Прибирання — виручка готелю. Турзбір готель лише збирає й
-- віддає громаді. Для квоти різниці немає: обидва додаються до суми. Для
-- фіскального документа різниця повна: перше — звичайна товарна позиція з
-- ПДВ, друге — ні.
--
-- ── Чому назви нейтральні ─────────────────────────────────────────────────
--
-- Тут напрошувався `tax_type` зі значенням `tourist_tax` — і це була б помилка
-- рівня ядра. Продукт робиться для Європи І України; поле, назване словом
-- однієї юрисдикції, робить ядро її заручником (AGENTS.md, інваріант 22).
--
-- `collected_for` каже, ЩО це за гроші, і нічого не каже про те, як їх
-- показати в чеку конкретної країни. Українське «рядок 11 без ПДВ» читає
-- модуль `fiscal_ua`, німецьке `durchlaufender Posten` — `fiscal_de`. Ядро
-- знає лише `property` проти `authority`.
--
-- ── Чому саме такі дефолти ────────────────────────────────────────────────
--
-- `applies_to = 'all'` лишає кожному наявному рядку ту саму арифметику, яку
-- він уже має. Міграція нічого не переоцінює.
--
-- `collected_for = 'property'` — свідомо консервативний бік. Немаркований
-- рядок вважається послугою готелю, тобто ПОТРАПЛЯЄ під ПДВ. Збір, який
-- забули позначити, з'явиться в чеку з податком — це видимий перебір, який
-- гість або бухгалтер помітять. Зворотний дефолт зробив би з тієї самої
-- забудькуватості тихе заниження бази оподаткування, якого не бачить ніхто.
--
-- ── Обсяг ─────────────────────────────────────────────────────────────────
--
-- Таблиця порожня в усіх реальних клієнтів: її наповнював лише demo-seed
-- (`fee_clean`, `fee_tax`), CRUD-екрана в неї досі немає. Тобто UPDATE нижче
-- на проді не зачепить жодного рядка, і саме тому це робиться зараз, а не
-- після того, як у таблиці з'являться гроші.

ALTER TABLE fees_taxes
  ADD COLUMN IF NOT EXISTS applies_to TEXT NOT NULL DEFAULT 'all';

ALTER TABLE fees_taxes
  ADD COLUMN IF NOT EXISTS collected_for TEXT NOT NULL DEFAULT 'property';

-- Окремими командами, а не в ADD COLUMN: `ADD CONSTRAINT IF NOT EXISTS` для
-- CHECK Postgres не має.
--
-- Шукаємо не за ІМЕНЕМ, а за визначенням. База, створена з `schema.sql`, уже
-- має ці CHECK — генератор їх туди виводить, — але БЕЗ імені: Postgres назве
-- їх `fees_taxes_check1`/`fees_taxes_check2`. Перевірка за іменем не знайшла
-- б їх і дописала б ДРУГЕ, дублююче обмеження на ту саму колонку. Помилки
-- не було б; була б база, що відрізняється від бази оновленого клієнта — і
-- саме це `check-fresh-schema` існує ловити.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'fees_taxes'::regclass AND contype = 'c'
       AND pg_get_constraintdef(oid) LIKE '%applies_to%'
  ) THEN
    ALTER TABLE fees_taxes ADD CONSTRAINT fees_taxes_applies_to_check
      CHECK (applies_to IN ('all', 'adults'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conrelid = 'fees_taxes'::regclass AND contype = 'c'
       AND pg_get_constraintdef(oid) LIKE '%collected_for%'
  ) THEN
    ALTER TABLE fees_taxes ADD CONSTRAINT fees_taxes_collected_for_check
      CHECK (collected_for IN ('property', 'authority'));
  END IF;
END $$;
