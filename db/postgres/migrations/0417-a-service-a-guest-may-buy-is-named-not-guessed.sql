-- Яку послугу гість може купити сам — готель НАЗИВАЄ, а не ми вгадуємо.
--
-- Довідник послуг обʼєкта це повний список НАРАХУВАНЬ, а не вітрина. У
-- живого готелю там поруч стоять «Frühstück 15», «Tiefgarage 10» — і
-- «Schlüsselverlust 30» (втрачений ключ), «Stornogebühren» (штраф за
-- скасування), «No Show», «Telefon 0,20», «Kopie 0,10», «Nachlass 10%»
-- (знижка). Усі активні, бо рецепція справді ними нараховує.
--
-- Показати цей список гостю на кроці бронювання означало б запропонувати
-- йому купити штраф за неприїзд. Тому ознака окрема й за замовчуванням
-- ПОРОЖНЯ: жодна наявна послуга не стає продажною від самої міграції, і
-- готель вмикає рівно те, що справді продає.
--
-- Те саме слово, що в номерів (`unit_types.bookable_online`), і навмисно:
-- правило одне — «на публічній поверхні продається лише назване».
ALTER TABLE additional_services
  ADD COLUMN IF NOT EXISTS bookable_online BOOLEAN NOT NULL DEFAULT FALSE;

-- Індекс частковий: питання завжди одне — «що цей обʼєкт продає онлайн», і
-- таких рядків одиниці проти всього довідника нарахувань.
CREATE INDEX IF NOT EXISTS idx_services_bookable_online
  ON additional_services (property_id) WHERE bookable_online;
