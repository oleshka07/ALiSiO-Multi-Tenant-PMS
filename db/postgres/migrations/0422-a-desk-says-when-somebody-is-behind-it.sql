-- 0422: години, коли на телефон рецепції хтось відповідає.
--
-- ── Навіщо ────────────────────────────────────────────────────────────────
--
-- Аркуш A4 з QR друкує телефон рецепції великим кеглем. Телефон без годин
-- — це обіцянка, яку ніхто не давав: гість, який дзвонить о 02:40 і слухає
-- гудки, вважає, що готель не відповідає, а не що рецепція зачинена.
-- Зразок, за яким робили аркуш, має під номером саме це:
-- «Správce / Administrator / Verwalter · 8:00 – 22:00».
--
-- ── Чому сюди, а не в `properties` ────────────────────────────────────────
--
-- Поруч уже лежать `emergency_phone` і `whatsapp_phone` — усе, чим гість
-- звʼязується з готелем, в одному рядку й на одному екрані. Колонка в
-- `properties` розвела б «кому дзвонити» і «коли дзвонити» по двох формах,
-- і друга розійшлася б із першою.
--
-- ── Чому ТЕКСТ, а не пара часів ───────────────────────────────────────────
--
-- Бо це рядок для ЛЮДИНИ, а не розклад для машини: жоден код за ним нічого
-- не вирішує, він лише друкується й показується. Пара `from`/`to` змусила б
-- готель із «8:00–12:00, 15:00–22:00» або «цілодобово» вигадувати, що
-- вписати, і вигадане значення поїхало б на папір (клас інваріанта 17).
-- Коли зʼявиться код, який за годинами ЩОСЬ вирішує, тоді й буде розклад.
--
-- Текст пишеться мовою готелю і перекладається тим самим шляхом, що решта
-- вмісту гостьової сторінки (`translateAndStore` у писачі конфігурації).

ALTER TABLE property_guest_config ADD COLUMN IF NOT EXISTS reception_hours TEXT;
