-- Довідник способів оплати є і в того, хто завівся ПІСЛЯ 0141.
--
-- ── Вікно, яке лишила 0141 ──────────────────────────────────────────────
--
-- 0141 засіяла чотири стандартні рядки КОЖНІЙ організації, яка існувала на
-- момент її накочування. Це закрило минуле — і не закрило майбутнє: міграція
-- виконується один раз, тож готель, заведений наступного дня, дістав би
-- порожній довідник.
--
-- Постійну половину полагоджено в коді: `provisionOrganization` тепер сіє ці
-- рядки кожному новому готелю (Д70). Ця міграція закриває РІВНО вікно між
-- накочуванням 0141 і тією правкою — і вона ж страхує будь-який інший шлях
-- народження організації, який колись обійде заведення.
--
-- ── Чому це помітили пізно ──────────────────────────────────────────────
--
-- Бо на SQLite розходження НЕ ВИДНО: `src/lib/db.ts` сіє ці самі чотири рядки
-- кожній організації при КОЖНОМУ старті (`WHERE NOT EXISTS`), тож у
-- розробника довідник є завжди. На Postgres того коду немає взагалі — там
-- діяла лише разова міграція. Класична пара, від якої застерігає AGENTS §7:
-- помилка виглядає не як помилка, а як «функція зникла».
--
-- ── Дзеркало Д67 ────────────────────────────────────────────────────────
--
-- Д67 був про протилежне: засів написали для НОВИХ (каса, план рахунків) і
-- не озирнулись на наявних, через що жоден живий готель не міг узяти
-- готівку. Тут навпаки — засів для наявних без продовження для нових. Один
-- клас, дві сторони, і обидві невидимі для гейтів: на свіжій базі все на
-- місці, на мігрованій теж, розходяться вони лише в часі.
--
-- Шкоди сьогодні немає: HTTP-шлях `method_id` ще не передає, тож платіж
-- проходить і без рядка довідника. Але це саме той стан, який AGENTS §3.2.1
-- називає підозрою: порожній довідник у готелі, у сусіда — повний.
--
-- Ідемпотентна, за ДАНИМИ (`WHERE NOT EXISTS`), не за іменем обмеження — той
-- самий довід, що в 0141: на свіжій базі імена обмежень свої.

BEGIN;

INSERT INTO "fin_payment_methods" (id, organization_id, code, kind, position)
SELECT encode(gen_random_bytes(16), 'hex'), o.id, k.code, k.code, k.pos
  FROM "organizations" o
  CROSS JOIN (VALUES ('cash', 0), ('card_terminal', 1), ('transfer', 2), ('voucher', 3))
       AS k(code, pos)
 WHERE NOT EXISTS (
   SELECT 1 FROM "fin_payment_methods" m
    WHERE m.organization_id = o.id AND m.code = k.code);

COMMIT;
