-- Облік стає тим, що готель вмикає, а не тим, що він отримує.
--
-- ── Що змінилось у коді ───────────────────────────────────────────────────
--
-- Зʼявився ключ фічі `accounting` із дефолтом OFF. Питає його
-- `requireFinanceUser` — одна варта, крізь яку проходить кожен хендлер обліку
-- з сесією, тож перевірку отримує і той хендлер, який напишуть завтра.
--
-- ── Навіщо ця міграція ────────────────────────────────────────────────────
--
-- Дефолт OFF без цього рядка означав би, що в день деплою КОЖЕН наявний
-- готель мовчки втрачає розділ «Фінанси»: меню зникає, маршрути відповідають
-- 403, у логах нічого — бо нічого й не ламалося. Рівно та пастка, про яку
-- попереджає коментар у `core/features.ts`: «в день додавання ключа кожен уже
-- наявний готель втратив би пʼять розділів меню мовчки — саме тому, що ніхто
-- не завів їм рядків».
--
-- Рядок у `organization_features` сильніший за дефолт (`hasFeature`: «рядок
-- сильніший за дефолт — і `enabled = 0` теж рядок»). Тому чесний дефолт для
-- НОВИХ клієнтів і збережений стан для НАЯВНИХ — це не компроміс, а те, для
-- чого механізм і зроблено.
--
-- ── Межа ──────────────────────────────────────────────────────────────────
--
-- Вмикається тим, хто існує НА ЦЕЙ МОМЕНТ. Організація, створена завтра,
-- пройде через `provisionOrganization`, який запише їй дефолт — тобто OFF, і
-- це правильно: новий клієнт вирішує сам.
--
-- `ON CONFLICT DO NOTHING`, а не `DO UPDATE`: якщо готель уже встиг вимкнути
-- облік свідомо, міграція не має вмикати його назад. Тому ж вона й
-- перезапускна.
INSERT INTO "organization_features" ("organization_id", "feature", "enabled", "updated_at")
SELECT "id", 'accounting', TRUE, now() FROM "organizations"
ON CONFLICT ("organization_id", "feature") DO NOTHING;
