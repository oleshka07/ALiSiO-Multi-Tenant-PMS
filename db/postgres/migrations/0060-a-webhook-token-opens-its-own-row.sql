-- Токен вебхука відкриває рядок свого зʼєднання — політикою, не WHERE.
--
-- ── Навіщо ────────────────────────────────────────────────────────────────
--
-- Вебхук менеджера каналів приходить без сесії: єдине, що в ньому наше, —
-- токен у адресі (`cm_connections.webhook_token`) і секрет у заголовку. Щоб
-- дізнатись орендаря, двері мусять прочитати рядок зʼєднання ДО того, як
-- орендар відомий. На Postgres із FORCE ROW LEVEL SECURITY політика
-- `cm_connections_tenant` на порожньому орендарі не збігається ні з чим:
-- запит повертає нуль рядків без помилки, двері кажуть 404 на кожен
-- справжній вебхук, і жоден лог цього не показує — саме так стрічка iCal
-- «зникла» у 0035. На SQLite політик немає, тож локально все зелене.
--
-- ── Рішення ───────────────────────────────────────────────────────────────
--
-- Той самий механізм, що в гостьового порталу, партнерського звіту і стрічки
-- iCal (інваріант 14): токен ставиться на зʼєднання (`app.public_token`), і
-- політика відкриває рівно один рядок, лише на читання. Запис — лише
-- орендарем. Список таких таблиць — `PUBLIC_TOKEN_READ` у
-- `scripts/pg-schema.mjs`; ця міграція повторює те, що генератор тепер
-- пише в schema.sql для нових клієнтів.
--
-- Токен відкриває РЯДОК, не двері: секрет у заголовку звіряється кодом
-- після читання, і без нього — 401 без жодної роботи.

DROP POLICY IF EXISTS cm_connections_tenant ON cm_connections;
CREATE POLICY cm_connections_tenant ON cm_connections
  USING ("organization_id" = current_setting('app.organization_id') OR "webhook_token" = NULLIF(current_setting('app.public_token', true), ''))
  WITH CHECK ("organization_id" = current_setting('app.organization_id'));
