-- 0063 · Тариф каже, як він рахує гостей (Блок 2.2, рішення Ц26)
--
-- У менеджера каналів режим тарифу задає набір опцій заселеності:
-- per_room — одна опція на максимальну доросла місткість, «ціна однакова
-- на будь-яку кількість гостей»; per_person — по опції на кожну кількість
-- дорослих. Ми режим не надсилали взагалі (вендор ставив per_room) і
-- клали опцію на кожну заселеність — тариф суперечив сам собі
-- (HANDOVER-2026-09-01 §7). Тепер режим обирає готель при створенні
-- тарифу і він їде у вендора явно; після заведення режим замкнений
-- (набір опцій там не переробити).
--
-- Наявні тарифи — per_person: так їх і заводили (опція на кожну заселеність,
-- ціна на кожну через priceNights). Словник закритий (docs/NAMING.md),
-- перевіряє писач; CHECK не ставиться, щоб схема нового клієнта (SQLite
-- CREATE) і мігрована збігались (як 0059).
ALTER TABLE rate_plans ADD COLUMN IF NOT EXISTS sell_mode TEXT NOT NULL DEFAULT 'per_person';
