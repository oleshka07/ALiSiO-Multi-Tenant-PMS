-- Одна адреса — один акаунт У МЕЖАХ ГОТЕЛЮ.
--
-- `login` має рівно одне, за чим шукати людину: адресу, яку вона набрала. Він
-- читав ОДИН рядок (`sql.row()`, без ORDER BY), і завжди той самий. Тож коли
-- одна адреса є в двох готелях, у другий увійти було неможливо — з правильним
-- паролем і з тим самим «Невірний email або пароль», що й на хибний.
--
-- Це не гіпотеза: на робочій базі одна адреса є власником двох готелів. У
-- старшого рядка last_login заповнений, у молодшого — порожній. Молодший не
-- «лишився без уваги»: у нього НЕ МОЖНА було увійти від дня створення, і
-- порожній last_login — слід саме цього.
--
-- Побачити свої такі пари:
--
--   SELECT u.id, u.email, o.name, u.last_login, u.created_at
--     FROM app_users u LEFT JOIN organizations o ON o.id = u.organization_id
--    WHERE lower(u.email) IN (SELECT lower(email) FROM app_users
--                             GROUP BY lower(email) HAVING count(*) > 1)
--    ORDER BY lower(u.email), u.created_at;
--
-- ── Чому не глобальна унікальність ──────────────────────────────────────────
--
-- Перша версія цієї міграції ставила UNIQUE по lower(email) на всю таблицю і
-- зупинялась, коли знаходила дубль. Вона й зупинила — вісім деплоїв прода
-- поспіль. Але «одна людина = один готель» тут неправильне правило: власник
-- справді має два готелі й хоче обидва. Забороняти йому другий акаунт, щоб
-- обійти обмеження коду, — це лікувати симптом.
--
-- Тому унікальність потенантна: (organization_id, lower(email)). Два власники
-- з однією адресою в РІЗНИХ готелях — нормально; два рядки з однією адресою в
-- ОДНОМУ готелі — помилка даних, і вона все ще неможлива.
--
-- Половина, без якої індекс нічого не означає, — у коді того ж коміту:
-- `login` тепер звіряє пароль з усіма рядками цієї адреси і, коли підходить
-- більше ніж один, повертає список готелів замість сесії. Форма питає, у який
-- саме. Без цього індекс дозволив би другий рядок, у який так само не можна
-- увійти.
--
-- Пароль звіряється ДО того, як назвати хоч один готель: інакше форма входу
-- розповідала б сторонньому, у скількох готелях є така адреса і як вони
-- звуться.

-- Дубль у межах одного готелю — це справжня помилка даних, і тут міграція
-- зупиняється й називає її. Вибір, який із двох рядків справжній, робить
-- власник, а не міграція: у неї немає для цього жодних підстав.
DO $$
DECLARE d TEXT;
BEGIN
  SELECT string_agg(t.who, ', ')
    INTO d
    FROM (SELECT lower(u."email") || ' у ' || COALESCE(o."name", u."organization_id") || ' ×' || COUNT(*) AS who
            FROM "app_users" u
            LEFT JOIN "organizations" o ON o."id" = u."organization_id"
           GROUP BY u."organization_id", o."name", lower(u."email")
          HAVING COUNT(*) > 1) t;
  IF d IS NOT NULL THEN
    RAISE EXCEPTION
      'Migration 0037 stopped: one hotel holds the same address twice (%). Only one of each pair can ever sign in. Remove or rename the extra row, then run this migration again.', d;
  END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS "idx_app_users_org_email"
  ON "app_users" ("organization_id", lower("email"));
