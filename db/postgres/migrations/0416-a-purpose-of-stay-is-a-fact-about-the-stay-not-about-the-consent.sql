-- Мета приїзду й номер візи живуть в ОДНІЙ таблиці — у книзі гостей.
--
-- ── Що було ───────────────────────────────────────────────────────────────
--
-- Ті самі два факти лежали і в `reservation_guests` (книга гостей, її читають
-- реєстр, кіоск і UbyPort), і в `guest_registrations` (журнал згоди). Копії
-- розходились ЗА ШЛЯХОМ реєстрації, і це виміряно, а не прочитано:
--
--   рецепція  → книга: 'Tourism',  журнал: NULL
--   портал    → книга: 'Tourism',  журнал: 'Tourism'
--   віджет    → книга: рядка нема, журнал: 'Tourism'
--
-- Друга копія не була сміттям: GDPR-експорт віддає `SELECT gr.*`, тобто вона
-- виходила НАЗОВНІ, гостеві, у відповідь на запит про його дані. Дві копії
-- одного факту, з яких назовні йде та, яку ніхто не редагує, — це не дублікат,
-- це друге джерело правди (той самий клас, що інваріант 16).
--
-- ── Куди воно належить ────────────────────────────────────────────────────
--
-- Мета приїзду — факт ПЕРЕБУВАННЯ: та сама людина цього тижня в відрядженні,
-- наступного на лікуванні. `guest_registrations` — журнал ЗГОДИ (коли, з якої
-- адреси, на що). Ознака перебування в журналі згоди опинилась там тому, що
-- обидві таблиці «про реєстрацію», а не тому, що так вирішили.
--
-- ── Чому 'Tourism' НЕ переноситься ────────────────────────────────────────
--
-- Це значення в журналі не писала людина: писачів було рівно три (таблиця
-- вище), і всі три ставили літерал — форми, у якій гостя питали б про мету,
-- не існувало в жодному з трьох шляхів. Переносити його означало б розносити
-- вигадану відповідь у книгу, з якої її читає поліція, — рівно те, що ця
-- зміна прибирає. Порожнє поле видно в реєстрі, і його доповнюють
-- (дія update_purpose); вигадане виглядає як відповідь гостя.
--
-- Усе інше — переноситься: значення, якого код написати не міг, написала
-- людина, і воно старше за наше рішення про те, де йому місце.
--
-- ── Чому міграція може ВІДМОВИТИ ──────────────────────────────────────────
--
-- «Писали лише три місця, і всі літералом» — це твердження про КОД. Про базу
-- воно нічого не доводить: рядок міг зʼявитися з psql або з імпорту. Тому
-- перед видаленням питаємо базу, і якщо є непорожнє значення, якому НЕМА КУДИ
-- переїхати (немає парного рядка книги), — міграція зупиняє деплой із числом у
-- повідомленні, а не викидає дані тихо (інваріант 13, зразок — 0055).

DO $$
DECLARE
  moved bigint;
  homeless bigint;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
     WHERE table_schema = 'public' AND table_name = 'guest_registrations'
       AND column_name = 'purpose_of_stay'
  ) THEN
    RETURN;   -- нова база: колонок не було й у schema.sql
  END IF;

  -- Міграції ходять власником, і RLS його не стосується — але якщо колись
  -- ходитимуть не ним, під FORCE RLS ці запити мають ВПАСТИ, а не побачити
  -- порожнечу і доповісти «переносити нічого» (інваріант 13).
  SET LOCAL row_security = off;

  -- 1. Переїзд. Тільки туди, де в книзі порожньо: значення книги старше й
  --    його редагують, значення журналу не редагує ніхто.
  EXECUTE $sql$
    UPDATE reservation_guests rg
       SET purpose_of_stay = COALESCE(rg.purpose_of_stay, NULLIF(gr.purpose_of_stay, 'Tourism')),
           visa_number     = COALESCE(rg.visa_number,     NULLIF(gr.visa_number, ''))
      FROM guest_registrations gr
     WHERE gr.reservation_id = rg.reservation_id
       AND gr.guest_id = rg.guest_id
       AND rg.guest_id IS NOT NULL
       AND (rg.purpose_of_stay IS NULL OR rg.visa_number IS NULL)
       AND (NULLIF(gr.purpose_of_stay, 'Tourism') IS NOT NULL
         OR NULLIF(gr.visa_number, '') IS NOT NULL)
  $sql$;
  GET DIAGNOSTICS moved = ROW_COUNT;

  -- 2. Кому переїхати нікуди: рядок журналу без парного рядка книги. Так буває
  --    у броні з віджета, де книгу заводить рецепція при заселенні, — але там
  --    значення саме 'Tourism', і воно не рахується.
  EXECUTE $sql$
    SELECT count(*) FROM guest_registrations gr
     WHERE (NULLIF(gr.purpose_of_stay, 'Tourism') IS NOT NULL
         OR NULLIF(gr.visa_number, '') IS NOT NULL)
       AND NOT EXISTS (
         SELECT 1 FROM reservation_guests rg
          WHERE rg.reservation_id = gr.reservation_id AND rg.guest_id = gr.guest_id)
  $sql$ INTO homeless;

  IF homeless > 0 THEN
    RAISE EXCEPTION
      'guest_registrations: % рядків мають мету приїзду або номер візи, яким немає парного рядка в reservation_guests — переносити нікуди, а видалити означало б втратити. Міграція зупинена. Ці значення написала не програма (усі три її писачі ставили літерал), тож рішення про них ухвалює людина: завести рядок книги для цих перебувань або свідомо викинути окремою міграцією.',
      homeless;
  END IF;

  RAISE NOTICE 'Мета приїзду й віза перенесені в книгу гостей: % рядків', moved;

  ALTER TABLE guest_registrations DROP COLUMN purpose_of_stay;
  ALTER TABLE guest_registrations DROP COLUMN visa_number;
END $$;

