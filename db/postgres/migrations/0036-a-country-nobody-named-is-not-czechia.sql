-- Країна, якої ніхто не назвав, — не Чехія.
--
-- `properties.country` мала `DEFAULT 'CZ'` — юрисдикцію першого клієнта,
-- зашиту в схему. Це не етикетка: саме з цієї колонки `documentLanguage()`
-- виводить ЮРИСДИКЦІЮ документа, і вона перебиває мову організації.
--
-- Ланцюг, який це давало німецькому готелю:
--
--   country = 'CZ'  →  JURISDICTION['CZ'] = 'cs'  →  локаль cs-CZ
--   →  маршрут /api/invoices/[id]/pdf не бачить de-DE
--   →  падає в чеський рендерер: «Ubytování», дати cs-CZ, без розбивки МПДВ
--      за ставками — і `convertToCzkAuto` ПЕРЕРАХОВУЄ суму в крони.
--
-- Тобто готель на євро видавав гостю чеську фактуру в кронах, без жодної
-- помилки на екрані. Саме це й побачили на пілоті.
--
-- Найгірше в цьому дефолті те, що він АКТИВНО перебиває правильну відповідь:
-- при `country IS NULL` та сама функція падає на мову організації й видає
-- `de` — тобто порожнє значення працювало б правильно, а «зручне» ні.
--
-- Наявні рядки не чіпаємо. У когось «CZ» — це справжня Чехія, і відрізнити
-- її від дефолту, який ніхто не вводив, з бази вже не можна. Файл готелю
-- (`hotels/*.json` → `property.country`) називає країну явно, і аплаєр її
-- проставляє; для готелів поза файлом країна вводиться в налаштуваннях
-- обʼєкта. Прибираємо лише мовчазне вгадування для НОВИХ рядків.
ALTER TABLE "properties" ALTER COLUMN "country" DROP DEFAULT;
