-- Номер дебітора видає готель; фоліо може належати платнику, а не броні.
--
-- Хвиля Winhotel, пункт 2 (`docs/research/winhotel/CORE-GAPS.md`). Готель, який
-- переїжджає на нас, продає ФІРМАМ: дванадцять фірм зі знижкою і дебітори в
-- діапазоні його бухгалтерії.
--
-- ── Чому `debtor_no`, коли є `business_id` ────────────────────────────────
--
-- `fin_folios.payer_debtor_no` заповнювався з `companies.business_id`, тобто
-- номер дебітора = реєстраційний номер фірми. Це дві РІЗНІ речі:
-- реєстраційний видає держава, номер дебітора видає ГОТЕЛЬ зі свого діапазону,
-- і саме він їде в бухгалтерію. Фірма без реєстраційного номера (приватна
-- особа, закордонний партнер) лишалась без номера дебітора взагалі.
--
-- ── Унікальність — НА ОРГАНІЗАЦІЮ ────────────────────────────────────────
--
-- Частковий унікальний індекс, а не `UNIQUE`: глобальна унікальність означала б,
-- що другий готель не може мати дебітора 4200, бо його зайняв перший, — тобто
-- ми ламаємо звичну нумерацію кожному, хто переїжджає до нас другим
-- (інваріант 3 читається саме так). `WHERE debtor_no IS NOT NULL` — щоб наявні
-- фірми без номера не зіштовхнулись одна з одною на NULL.
--
-- ── Старт лічильника: 1, і це навмисно ───────────────────────────────────
--
-- Діапазон 10000–12599 — це діапазон ОДНОГО клієнта, і в коді його немає
-- (інваріант 20). Готель, що переїжджає зі своєю книгою дебіторів, ставить свій
-- старт сам; для всіх інших будь-яка послідовність однаково добра.
--
-- ── `fin_folios.company_id` ──────────────────────────────────────────────
--
-- Колонка `reservation_id` тут нульова від початку, тобто схема фоліо без броні
-- дозволяла завжди — код не вмів. Одна фактура фірмі за пʼять перебувань
-- (`RECHNUNG.VERK_NR` у Winhotel) потребує фоліо, яке належить ПЛАТНИКУ, і
-- платника треба вміти назвати: `payer_name` — знімок тексту, ним не
-- порівняєш.
--
-- Перезапускна: другий прогін нічого не знаходить і нічого не робить.

BEGIN;

ALTER TABLE "organizations" ADD COLUMN IF NOT EXISTS "next_debtor_no" BIGINT NOT NULL DEFAULT 1;

ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "debtor_no" BIGINT;
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "payment_terms_days" BIGINT;

CREATE UNIQUE INDEX IF NOT EXISTS "idx_companies_debtor_no"
  ON "companies" ("organization_id", "debtor_no") WHERE "debtor_no" IS NOT NULL;

ALTER TABLE "fin_folios" ADD COLUMN IF NOT EXISTS "company_id" TEXT REFERENCES "companies"("id") ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS "idx_fin_folios_company" ON "fin_folios" ("organization_id", "company_id");

COMMIT;
