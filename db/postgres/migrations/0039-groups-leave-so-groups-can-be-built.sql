-- Групи йдуть, щоб групи можна було зробити.
--
-- `reservation_groups` — «групове бронювання»: одна шапка (гість, дати,
-- сума, статус) і броні, які на неї посилаються через `reservations.group_id`.
-- Рішення власника від 2026-08-27: видалити цілком і збудувати заново
-- окремим модулем.
--
-- Що з нею було не так, окрім віку:
--
--   1. Немає `organization_id`. Орендар діставався через `property_id`, і
--      саме на цьому проба ізоляції ловила створення групи в чужому обʼєкті:
--      `POST /api/group-bookings` брав `unitIds` з тіла запиту й записував
--      групу туди, кому належав ПЕРШИЙ із номерів.
--   2. Два механізми для однієї речі. Ще до цього видалення в коді стояло
--      «Sub-bookings (replaces group bookings)» і «legacy, буде видалено»:
--      `reservations.parent_id` + `reservation_sub_bookings` роблять те саме
--      і роблять це з орендарем. Два способи сказати «одна бронь — кілька
--      номерів» означають два місця, де рахується сума, і рано чи пізно вони
--      розходяться.
--   3. `guest_registrations.group_id` — третя копія того самого звʼязку,
--      яку не читав ніхто взагалі.
--
-- Що втрачається: шапка групи — її нотатка, `group_type`, `building_id` і
-- підсумкова сума. САМІ БРОНІ ЛИШАЮТЬСЯ: кожна тримає свого гостя, дати,
-- номер, ціну й статус у власному рядку. Зникає тільки те, що їх з'єднувало
-- на екрані, а екран цей видаляється тим самим комітом.
--
-- Порядок навмисний: спершу колонки, потім таблиця. `reservations.group_id`
-- має зовнішній ключ на `reservation_groups`, і DROP TABLE із живим FK
-- вимагав би CASCADE, а CASCADE тут прибрав би заразом і те, чого ніхто не
-- перелічував.
ALTER TABLE "reservations" DROP COLUMN IF EXISTS "group_id";
ALTER TABLE "guest_registrations" DROP COLUMN IF EXISTS "group_id";
DROP TABLE IF EXISTS "reservation_groups";
