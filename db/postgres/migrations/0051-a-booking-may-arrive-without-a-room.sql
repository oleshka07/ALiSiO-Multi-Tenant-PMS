-- Бронь може прийти без кімнати.
--
-- ── Навіщо ────────────────────────────────────────────────────────────────
--
-- CP3 інтеграції з каналами. Channex про `units` не знає нічого: він адресує
-- ТИП номера й тариф. Бронь із Booking.com чи Airbnb приходить як «двомісний
-- на ці дати», без конкретної кімнати, і рецепція призначає її потім.
--
-- `reservations.unit_type_id` зʼявився ще міграцією 0048 і був nullable —
-- тобто половина вимоги виконана давно. Друга половина — оце: `unit_id` мусить
-- уміти бути NULL, інакше бронь із каналу нікуди покласти.
--
-- ── Чому це остання зміна, а не перша ─────────────────────────────────────
--
-- Небезпека тут не в колонці, а в тому, ЯК воно ламається.
--
--     FROM reservations r
--     JOIN units u ON r.unit_id = u.id      ← INNER
--
-- INNER JOIN не падає на NULL — він ФІЛЬТРУЄ. Бронь без номера просто зникла б
-- зі списку броней, зі списку фактур, зі звіту з турзбору, з панелі й з API
-- резервацій: без помилки, без логу, без сліду. Готель відкрив би екран і не
-- побачив броні, за яку вже відповідає.
--
-- Тому 34 джойни в 15 файлах переведені на `LEFT JOIN` ОКРЕМИМ, попереднім
-- комітом — разом із ланцюжками (`JOIN categories`, `JOIN unit_types` через
-- той самий alias фільтрують так само). Тримає `check-unit-join.mjs --strict`.
-- Порядок «спершу колонка, потім читачі» дав би вікно між двома деплоями, у
-- якому система виглядає робочою і мовчки ховає броні.
--
-- Разом із цією міграцією наявність навчилася рахувати ЄМНІСТЬ: бронь без
-- номера не робить жоден номер зайнятим, але зʼїдає одну кімнату свого типу
-- (`unassignedByTypeDay()` у `modules/properties/data/availability.ts`). Без
-- цього віджет показав би тип вільним і продав ту саму кімнату вдруге —
-- овербукінг рівно через той канал, заради якого все це робиться.
--
-- ── Що НЕ змінюється ──────────────────────────────────────────────────────
--
-- `property_id` лишається `NOT NULL`: обʼєкт відомий завжди, і саме через
-- нього бронь досягає орендаря. Nullable там був би дірою в ізоляції.
--
-- `availability_blocks.unit_id` теж лишається `NOT NULL`: блокування — це
-- ремонт конкретної кімнати, «блок на тип» не має змісту.
--
-- ── Обсяг ─────────────────────────────────────────────────────────────────
--
-- Послаблення обмеження. Жоден наявний рядок не змінюється й не
-- перевіряється заново: усі вони мають номер. Зворотний накат (повернути
-- NOT NULL) можливий рівно доти, доки не зʼявилась перша бронь без кімнати.

ALTER TABLE reservations ALTER COLUMN unit_id DROP NOT NULL;

-- Індекс по типу вже є з 0048; бронь без номера шукають саме за ним —
-- і за `unit_id IS NULL` у розрахунку наявності.
CREATE INDEX IF NOT EXISTS idx_reservations_unassigned
  ON reservations (property_id, check_in)
  WHERE unit_id IS NULL;
