/**
 * The row-level policies from the generated schema, as a re-runnable script.
 *
 *   node scripts/pg-policies.mjs > /tmp/policies.sql
 *   psql … -f /tmp/policies.sql
 *
 * Why this exists: db/postgres/schema.sql creates a database from nothing, and
 * a database that already holds data cannot be created from nothing. When the
 * generator's idea of how a table reaches its organization changes — and it
 * changed for 23 tables the day unit_types turned out to be scoped through an
 * optional building_id — every existing install needs the new policies and
 * nothing else. Writing 23 of those by hand is how one gets missed.
 *
 * Only policies. No table is created, altered or dropped; no row is touched.
 * DROP POLICY IF EXISTS before each CREATE, so running it twice is the same as
 * running it once, and running it on a database that is already correct is a
 * no-op that still proves it.
 */
import fs from 'node:fs';

const schema = fs.readFileSync('db/postgres/schema.sql', 'utf8');

// Each policy in the generated file is exactly this shape — the generator
// writes it in one place, so matching it here cannot drift far.
const re = /ALTER TABLE "(\w+)" ENABLE ROW LEVEL SECURITY;\nALTER TABLE "\1" FORCE ROW LEVEL SECURITY;\nCREATE POLICY "(\w+)" ON "\1"\n(  USING \(.*\)\n  WITH CHECK \(.*\);)/g;

const out = [
  '-- Generated by scripts/pg-policies.mjs from db/postgres/schema.sql.',
  '-- Policies only: no table is created, altered or dropped, no row is touched.',
  '-- Re-runnable.',
  '',
  'BEGIN;',
  '',
];

let count = 0;
for (const [, table, policy, body] of schema.matchAll(re)) {
  count++;
  out.push(
    `ALTER TABLE "${table}" ENABLE ROW LEVEL SECURITY;`,
    `ALTER TABLE "${table}" FORCE ROW LEVEL SECURITY;`,
    `DROP POLICY IF EXISTS "${policy}" ON "${table}";`,
    `CREATE POLICY "${policy}" ON "${table}"`,
    body,
    '',
  );
}

out.push('COMMIT;', '');

if (!count) {
  console.error('no policies found in db/postgres/schema.sql — has the generator changed shape?');
  process.exit(1);
}

process.stderr.write(`${count} policies\n`);
process.stdout.write(out.join('\n'));
