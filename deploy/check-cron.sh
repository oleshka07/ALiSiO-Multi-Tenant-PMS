#!/usr/bin/env bash
#
# Розклад, який мав бути поставлений, і розклад, який СТОЇТЬ.
#
#   ./deploy/check-cron.sh prod
#   ./deploy/check-cron.sh beta
#   ./deploy/check-cron.sh prod --from /шлях/до/знімка   # для перевірки гейта
#
# ── Навіщо ──────────────────────────────────────────────────────────────────
#
# `setup-backup-cron.sh` ставить сім рядків на середовище (прод — девʼять), і
# ставить їх ДЕПЛОЙ. Це правильно рівно доти, доки деплой проходить. 19.09.2026
# у живому crontab прода рядків виявилось ТРИ: бракувало `channels-pull`,
# `channels-publish`, `guest-app-holds` і `kiosk-day`, бо прод не деплоївся з
# 10.09, а саме ті рядки додали пізніше.
#
# Наслідок мовчазний за побудовою, і він коштує грошей щодня:
#
#   channels-pull      броні з каналів не приїжджають — гість стоїть у номері,
#                      якого готель не бачить;
#   channels-publish   наявність і ціни не їдуть у канал — продаємо те, чого
#                      немає, або не продаємо те, що є;
#   guest-app-holds    холди гостьового застосунку не знімаються — номер
#                      лишається зайнятий ніким;
#   kiosk-day          доба термінала не закривається.
#
# Жодна з цих тиш не має вигляду помилки: немає ні відмови, ні рядка в логу —
# просто нічого не відбувається. Клас — той самий, що INC-050 (КІ42):
# написане не доїхало до працюючої системи.
#
# ── Що стверджується ────────────────────────────────────────────────────────
#
# Множина рядків із маркером `# alisio-backup-<env>` у живому `crontab -l`
# ДОРІВНЮЄ множині, яку друкує `setup-backup-cron.sh <env> --list`.
#
# Рівність, не входження, і обидва боки важливі:
#   бракує рядка   → робота не виконується (випадок 19.09);
#   зайвий рядок   → рядок від старої версії скрипта далі бігає з розкладу,
#                    смикаючи маршрут, якого вже немає, або з параметрами,
#                    яких уже ніхто не чекає. Це не безпечніше за відсутній —
#                    це та сама розбіжність, тільки в інший бік.
#
# Очікування НЕ дублюється тут: воно береться з самого `setup-backup-cron.sh`.
# Друга копія списку розійшлася б із першою, і перевірка порівнювала б розклад
# сама з собою — зелено й безглуздо.
#
# Сам crontab цей скрипт НЕ ЧІПАЄ. Розклад ставить деплой прода, а коли його
# запускати — рішення власника.
set -euo pipefail

ENV_NAME="${1:-}"
case "$ENV_NAME" in
  prod|beta) ;;
  *) echo "usage: $0 {prod|beta} [--from <файл>]" >&2; exit 2 ;;
esac

HERE="$(cd "$(dirname "$0")" && pwd)"
MARK="# alisio-backup-${ENV_NAME}"

# `--from <файл>` читає розклад із файла замість `crontab -l`.
#
# Не зручність і не чорний хід: у контейнері збірки crontab немає взагалі, а
# гейт, чию червоність не можна показати, нічого не тримає (AGENTS §3.2). На
# сервері прапорця не передають, і тоді читається живий crontab.
FROM=''
if [ "${2:-}" = '--from' ]; then
  FROM="${3:-}"
  [ -n "$FROM" ] && [ -f "$FROM" ] || { echo "--from: файла немає: ${FROM:-(порожньо)}" >&2; exit 2; }
fi

if [ -n "$FROM" ]; then
  CURRENT="$(cat "$FROM")"
  echo "==> cron ($ENV_NAME): зі знімка ${FROM}"
else
  command -v crontab >/dev/null || { echo "crontab не знайдено — запускати на сервері" >&2; exit 1; }
  CURRENT="$(crontab -l 2>/dev/null || true)"
  echo "==> cron ($ENV_NAME): живий crontab"
fi

WANT="$("${HERE}/setup-backup-cron.sh" "$ENV_NAME" --list)"

# Порожнеча тут нормальна (розклад ще не ставили), тож `|| true`: без нього
# grep без збігів убив би скрипт до першого рядка виводу — рівно той клас, що
# тримає check-fatal-grep.
HAVE="$(printf '%s\n' "$CURRENT" | grep -F "$MARK" || true)"

# Порівнюються МНОЖИНИ: порядок рядків у crontab нічого не означає, а пробіли
# по краях додає редактор.
norm() { sed 's/[[:space:]]\+/ /g; s/^ //; s/ $//' | sed '/^$/d' | LC_ALL=C sort; }
WANT_N="$(printf '%s\n' "$WANT" | norm)"
HAVE_N="$(printf '%s\n' "$HAVE" | norm)"

MISSING="$(comm -23 <(printf '%s\n' "$WANT_N") <(printf '%s\n' "$HAVE_N") || true)"
EXTRA="$(comm -13 <(printf '%s\n' "$WANT_N") <(printf '%s\n' "$HAVE_N") || true)"

want_count="$(printf '%s\n' "$WANT_N" | sed '/^$/d' | wc -l | tr -d ' ')"
have_count="$(printf '%s\n' "$HAVE_N" | sed '/^$/d' | wc -l | tr -d ' ')"

if [ -z "$MISSING" ] && [ -z "$EXTRA" ]; then
  echo "    ok   рядків ${have_count} з ${want_count} — розклад збігається з deploy/setup-backup-cron.sh"
  exit 0
fi

echo "!! cron ($ENV_NAME): розклад розійшовся зі скриптом (${have_count} з ${want_count})" >&2
if [ -n "$MISSING" ]; then
  echo "" >&2
  echo "   НЕ СТОЇТЬ у crontab — ця робота не виконується взагалі:" >&2
  printf '%s\n' "$MISSING" | sed 's/^/     − /' >&2
fi
if [ -n "$EXTRA" ]; then
  echo "" >&2
  echo "   СТОЇТЬ зайве — рядок від старої версії далі бігає з розкладу:" >&2
  printf '%s\n' "$EXTRA" | sed 's/^/     + /' >&2
fi
echo "" >&2
echo "   Полагодити: ./deploy/deploy.sh ${ENV_NAME} (розклад ставить деплой)" >&2
echo "   або, якщо деплой зараз недоречний: ./deploy/setup-backup-cron.sh ${ENV_NAME}" >&2
exit 1
