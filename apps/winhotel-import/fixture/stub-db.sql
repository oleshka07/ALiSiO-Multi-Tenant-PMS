--
-- Створюється `make-stub.sh` → `stub.fbk` (isql-fb + gbak, вбудований режим).
-- Таблиці — лише ті колонки, які читають `apps/winhotel-import/sql/*.sql`
-- (типи — з DDL справжньої бази, docs/research/winhotel/extract-out/main).
-- Дані вигадані, і кожен рядок — вісь, про яку стверджує гейт
-- (`src/apps/winhotel-import/winhotel-import.check.ts`, інваріант 26):
--
--   ÜF через ASCII_CHAR(220)/ASCII_CHAR(252) — байти CP1252 у charset NONE,
--     як у справжній базі; файл лишається чистим ASCII;
--   суми ×1000: 141000 → 141.00, 89500 → 89.50, -1500 → -1.50;
--   1899-12-30 — нуль Delphi → NULL;
--   TA_STATUS 1000 — видалене, не витягається (крім фактур і сторно з датою);
--   майбутня бронь із трьома адресами; минула; сторнована з STORNO_DATUM;
--   фактура Sammelrechnung (M_DEBIRECHN = 1) на дебітора.
--
-- Жодних справжніх імен, адрес чи номерів: «Gast Eins», «Musterweg 1».

