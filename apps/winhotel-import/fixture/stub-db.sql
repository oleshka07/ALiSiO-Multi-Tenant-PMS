CREATE PROCEDURE GET_OFFEN_ZAHLBETRAG (BELEGNR INTEGER)
RETURNS (OFFEN_BETRAG NUMERIC(12,3))
AS
  DECLARE L NUMERIC(15,3);
  DECLARE Z NUMERIC(15,3);
BEGIN
  SELECT COALESCE(SUM(GBETRAG), 0) / 1000.0 FROM BUCHKONT WHERE GK_LNR = :BELEGNR AND TA_STATUS < 1000 INTO :L;
  SELECT COALESCE(SUM(BETRAG), 0) / 1000.0 FROM ZAHLUNGEN WHERE LNR_GK = :BELEGNR AND TA_STATUS < 1000 INTO :Z;
  OFFEN_BETRAG = L - Z;
  SUSPEND;
END^
SET TERM ; ^

