import type { Metadata, Viewport } from 'next';
import './kiosk.css';

/**
 * Оболонка екрана в холі: без шапки адмінки, без меню, без теми оператора.
 *
 * Це не «сторінка PMS без хедера» — це інший продукт на тому самому сервері.
 * Усе, що робить адмінку адмінкою (навігація, перемикач обʼєкта, профіль),
 * тут не просто зайве: воно — двері, яких у холі бути не має.
 *
 * `userScalable: false` і фіксований масштаб: гість не мусить випадково
 * розтягнути екран двома пальцями так, що кнопка «Check-in» поїде за край, а
 * повернути її нема кому.
 */

export const metadata: Metadata = {
  title: 'Check-in',
  // Термінал не індексується: це внутрішній екран готелю, а не сторінка.
  robots: { index: false, follow: false },
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  maximumScale: 1,
  userScalable: false,
  viewportFit: 'cover',
  themeColor: '#f6f2ec',
};

/**
 * Обгортки тут НЕМАЄ навмисно.
 *
 * Раніше layout малював власний `<div className="kiosk-root">`, а сторінка —
 * ще один усередині нього. Обидва `position: fixed; inset: 0`, тобто другий
 * повністю накривав перший: видимої різниці не було, а в дереві лежали два
 * однакові корені. Перше, що це зламало, — пошук елемента за `data-step`:
 * зовнішній кореневий div цього атрибута не має, і будь-яка перевірка, яка
 * питає «на якому кроці екран», читала порожнечу при цілком робочому екрані.
 *
 * Корінь малює СТОРІНКА — вона ж і знає крок. Тут лишається те, заради чого
 * layout існує: стилі, заголовок вкладки і масштаб.
 */
export default function KioskLayout({ children }: { children: React.ReactNode }) {
  return <>{children}</>;
}
