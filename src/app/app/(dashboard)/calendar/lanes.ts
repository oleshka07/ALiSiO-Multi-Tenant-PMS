/**
 * Куди лягає бронь у планері — і чи лягає взагалі.
 *
 * Винесено з `page.tsx` не заради краси, а тому що це правило треба
 * ЗАПУСКАТИ. Клієнтський компонент імпортувати з перевірки не можна, тож
 * сусідній `grouping.check.ts` тримає КОПІЮ свого правила — і копія вже
 * розходилась із оригіналом. Тут обидва беруть один і той самий модуль.
 *
 * ── Правило, заради якого файл існує ────────────────────────────────────
 *
 * **Кожна бронь зі списку потрапляє рівно в одне місце.** Має номер — у
 * рядок цього номера. Не має — в окрему смугу «без номера».
 *
 * З CP3 бронь може прийти без кімнати: Channex адресує ТИП номера, тож
 * OTA-бронь лягає на «двомісний», а рецепція призначає кімнату потім.
 * Планер будує рядки з номерів, і така бронь не збігається з жодним із них
 * — вона просто зникає з екрана, з якого рецепція працює. Готель не
 * побачить броні, за яку вже відповідає (рішення П9).
 *
 * Друге правило, того ж кореня: **лічильник вільних відбирає й безномерні
 * броні**. Вони не займають конкретної кімнати, але зменшують те, що можна
 * продати; інакше в шапці планера стоїть число, більше за правду.
 */

/** Рівно те, що планер знає про бронь для розкладання по рядках. */
export interface LaneBooking {
  id: string;
  /** NULL = номер ще не призначено (CP3). */
  unit_id: string | null;
  check_in: string;
  check_out: string;
}

/** Блокування — ремонт, службове закриття. Завжди на конкретній кімнаті. */
export interface LaneBlock {
  unit_id: string;
  date_from: string;
  date_to: string;
}

// Функції узагальнені за формою броні, а не звужені до `LaneBooking`.
//
// Планеру потрібні всі поля (гість, статус, оплата, джерело), і функція, що
// віддає `LaneBooking[]`, змусила б його приводити тип назад — тобто
// втратити перевірку саме там, де вона потрібна. `T extends LaneBooking`
// каже рівно те, що є: нам треба три поля, решту ми не чіпаємо й повертаємо
// як прийшло.

/** Броні, що показуються в рядку цього номера. */
export function bookingsOfUnit<T extends LaneBooking>(bookings: readonly T[], unitId: string): T[] {
  return bookings.filter(b => b.unit_id === unitId);
}

/** Броні, яким номер ще не призначено. */
export function unassignedBookings<T extends LaneBooking>(bookings: readonly T[]): T[] {
  return bookings.filter(b => b.unit_id === null);
}

/**
 * Скільки номерів вільно на цю дату.
 *
 * Півінтервал [check_in, check_out): ніч належить даті заїзду, і в день
 * виїзду номер уже продається.
 */
export function freeUnitsOnDate(
  bookings: readonly LaneBooking[],
  blocks: readonly LaneBlock[],
  unitIds: readonly string[],
  dateStr: string,
): number {
  // Два різні виміри, і саме тому два лічильники.
  //
  // Було одне: `new Set(… .map(b => b.unit_id))`. Безномерна бронь клала в
  // множину `null`, який не збігається з жодним номером, — тобто вона не
  // займала нічого й нічого не зменшувала. Планер показував вільною кімнату,
  // уже продану каналом, а рецепція дізнавалась про це від гостя на порозі.
  const busy = new Set<string>();
  let unassigned = 0;
  for (const b of bookings) {
    if (!(dateStr >= b.check_in && dateStr < b.check_out)) continue;
    if (b.unit_id === null) unassigned++;
    else busy.add(b.unit_id);
  }
  for (const blk of blocks) {
    if (dateStr >= blk.date_from && dateStr < blk.date_to) busy.add(blk.unit_id);
  }
  const free = unitIds.filter(id => !busy.has(id)).length;
  // Нуль знизу: тиск більший за фонд означає овербукінг, який УЖЕ стався.
  // Відʼємне число в шапці планера — це друга помилка поверх першої.
  return Math.max(0, free - unassigned);
}

/**
 * Розкласти броні по підрядках так, щоб жодні дві не накладались.
 *
 * Смуга «без номера» — це не один рядок: з каналу цілком нормально приходять
 * дві броні на ті самі дати, бо вони на РІЗНІ кімнати одного типу, просто
 * ще не сказано які. Покласти їх в один рядок означає намалювати їх одна
 * поверх одної: смуга показує одну бронь замість двох, і виглядає це як
 * правда.
 *
 * Класичне розбиття інтервалів: жадібно в перший підрядок, де немає
 * перетину. Півінтервал той самий — бронь, що виїжджає 12-го, і бронь, що
 * заїжджає 12-го, у одному підрядку вміщаються.
 */
export function packLanes<T extends LaneBooking>(bookings: readonly T[]): T[][] {
  const rows: T[][] = [];
  // За датою заїзду: жадібний алгоритм дає мінімальну кількість підрядків
  // лише на впорядкованому вході.
  for (const b of [...bookings].sort((x, y) => x.check_in.localeCompare(y.check_in))) {
    // Перший підрядок, де остання бронь уже виїхала. `>=`, а не `>`:
    // півінтервал — виїзд 12-го і заїзд 12-го не перетинаються.
    const row = rows.find(r => b.check_in >= r[r.length - 1].check_out);
    if (row) row.push(b);
    else rows.push([b]);
  }
  return rows;
}
