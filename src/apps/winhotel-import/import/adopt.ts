/**
 * Попередня бронь воріт і кіоска — НЕ ДУБЛЮЄТЬСЯ дельтою.
 *
 * ── Що було зламано ─────────────────────────────────────────────────────
 *
 * Гість, який забронював у власному онлайн-модулі готелю і назвався нам
 * (кіоск — КІ8, ворота — КІ31), лишає по собі попередню бронь `tentative` з
 * ключем `winhotel-ob:<номер>`. Через чверть години дельта приносить ту саму
 * бронь із Winhotel — і імпортер її НЕ ВПІЗНАЄ: він шукає лише у власному
 * журналі `winhotel_refs`, а там її немає, бо завели її не ми з знімка.
 *
 * Отже створюється ДРУГА бронь на те саме перебування. Коментар у
 * `apps/kiosk/api/walkin.handlers.ts` обіцяє протилежне з дня написання, і
 * обіцянка не виконувалась ніколи.
 *
 * Дубль при цьому мовчазний, і це найгірше в ньому: попередня бронь без
 * `unit_id` ні з чим не перетинається, тож `no_double_booking` не спрацює, а
 * рецепція побачить два рядки на одне перебування і не знатиме, який правда.
 *
 * ── Чому ключ саме такий ────────────────────────────────────────────────
 *
 * У знімку є довідник посилань (`GASTKREF`), і `channelOf()` уже впізнає в
 * ньому слово `Onlinebuchung` разом із номером. Тобто ключ, за яким шукати,
 * дає сам знімок: `winhotel-ob:<номер>` — рівно те, що записали ворота з
 * того, що гість прочитав у листі готелю.
 *
 * ── Чому лише ТОЧНИЙ збіг ───────────────────────────────────────────────
 *
 * Спокуса звіряти за парою «прізвище + дата заїзду» велика, і вона хибна:
 * помилкове усиновлення зливає перебування ДВОХ різних людей — з чужим
 * іменем у документі й чужою сумою в рахунку. Ціна помилки тут вища за ціну
 * дубля, а дубль видно оком.
 *
 * Тому: збігся ключ — усиновлюємо; не збігся — робимо рівно те, що робили
 * досі. Ця функція не може зробити гірше, ніж було, за побудовою.
 */
import type { Sql } from '@core/db/async';

/** Що знайшлось під ключем — і чи можна це усиновити. */
export interface Adoptable {
  id: string;
  /** Токен гостьової сторінки: гість уже пішов за ним заселятись. */
  guestPageToken: string | null;
}

/** Роди походження, чиї попередні броні усиновлюються. Порядок не має значення. */
export const PRE_BOOKING_SOURCES = ['kiosk_walkin', 'guest_app'] as const;

/**
 * Знайти попередню бронь, яку принесла ця сама бронь Winhotel.
 *
 * `null` — усиновлювати нічого, і викликач створює нову, як робив завжди.
 *
 * Умови всі разом, і кожна потрібна:
 *   ТОЙ САМИЙ ОБʼЄКТ — той самий номер у сусідньому корпусі це інша бронь;
 *   `tentative` — підтверджена або скасована вже прожила своє життя, і
 *     переписувати її дельтою означало б скасувати чиєсь рішення;
 *   рід походження НАШ — чужий `external_ref` того ж вигляду не буває, але
 *     умова стоїть, бо ключ це рядок, і завтра його зможе писати ще хтось;
 *   ЩЕ НЕ УСИНОВЛЕНА — рядок, на який уже вказує `winhotel_refs`, належить
 *     іншій броні Winhotel, і забрати його означало б переписати ту.
 */
export async function adoptableBy(
  sql: Sql, organizationId: string, propertyId: string, ref: string,
): Promise<Adoptable | null> {
  const holes = PRE_BOOKING_SOURCES.map(() => '?').join(', ');
  const row = await sql.row<{ id: string; guest_page_token: string | null }>(
    `SELECT r.id, r.guest_page_token
       FROM reservations r
      WHERE r.organization_id = ?
        AND r.property_id = ?
        AND r.external_ref = ?
        AND r.status = 'tentative'
        AND r.source IN (${holes})
        AND NOT EXISTS (
          SELECT 1 FROM winhotel_refs w
           WHERE w.organization_id = r.organization_id
             AND w.entity = 'reservation'
             AND w.our_id = r.id)`,
    [organizationId, propertyId, ref, ...PRE_BOOKING_SOURCES]);
  return row ? { id: row.id, guestPageToken: row.guest_page_token } : null;
}

/**
 * Ключ походження з посилання знімка — або `null`.
 *
 * Лише для броней, які знімок сам називає онлайн-бронюванням готелю: номер
 * каналу Booking.com того ж вигляду означав би зовсім інше, і шукати за ним
 * нашу попередню бронь було б збігом, а не звіркою.
 */
export function preBookingRef(channel: { channel: string | null; number: string | null }): string | null {
  if (channel.channel !== 'Onlinebuchung' || !channel.number) return null;
  return `winhotel-ob:${channel.number}`;
}
