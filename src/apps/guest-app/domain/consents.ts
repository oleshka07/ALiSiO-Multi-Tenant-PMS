/**
 * Під чим гість ставить галочку, перш ніж бронювати.
 *
 * ── Чому це взагалі є ───────────────────────────────────────────────────
 *
 * На зразку, який дав власник (`reservation.one.dirs21.de`), останній екран
 * несе дві галочки — умови готелю і захист даних, — і кнопка без них не
 * працює. У нас бронь проходила без жодної: рядок зʼявлявся в базі, гість
 * нічого не приймав, і довести згоду наглядачеві не було чим.
 *
 * ── Що тут є і чого немає ───────────────────────────────────────────────
 *
 * Тут лише РОДИ і те, який із них тримає кнопку. Самих текстів немає й бути
 * не може: текст умов пише готель, він лежить у `consent_texts` з версією і
 * мовою (інваріант 20). Галочка «приймаю умови» без тексту готелю — це
 * галочка ні під чим.
 *
 * Готель, який текстів не завів, галочок не побачить, і бронювання від цього
 * не спиняється. Це свідомо: вимагати згоди на текст, якого немає, означало б
 * зупинити продаж у кожного, хто ще не дійшов до цього екрана налаштувань.
 * Те, чого немає, не можна ні прийняти, ні порушити.
 */

/** Роди, про які ворота питають готель. Порядок — порядок галочок на екрані. */
export const GUEST_APP_CONSENTS = ['terms', 'data_processing', 'marketing'] as const;

/**
 * Роди, без яких кнопка не працює.
 *
 * `marketing` сюди НЕ входить, і це не недогляд: згода на розсилку за
 * означенням добровільна, а галочка, без якої не забронювати, добровільною не
 * є. Прив'язати листи до можливості купити — це те, за що штрафують, а не
 * те, що ми будуємо.
 */
export const BLOCKING_CONSENTS: readonly string[] = ['terms', 'data_processing'];

/** Чи цей рід тримає кнопку. */
export const blocks = (kind: string): boolean => BLOCKING_CONSENTS.includes(kind);

/**
 * Чого бракує: роди, які готель вимагає, а гість не прийняв.
 *
 * Порівнюється ПАРА «рід + версія», не сам рід: галочка під старою редакцією
 * не є згодою на нову, а саме так виглядає вкладка, відкрита до того, як
 * готель оновив умови.
 */
export function missingConsents(
  required: readonly { consentKind: string; version: string }[],
  accepted: readonly { kind: string; version: string }[],
): string[] {
  return required
    .filter((r) => blocks(r.consentKind))
    .filter((r) => !accepted.some((a) => a.kind === r.consentKind && a.version === r.version))
    .map((r) => r.consentKind);
}

/**
 * Яким текстом показати редакцію ЦЬОМУ гостю.
 *
 * ── Порядок, і чому саме такий ──────────────────────────────────────────
 *
 *   1. мова ГОСТЯ — те, заради чого все це;
 *   2. мова ГОТЕЛЮ — його власне формулювання, і воно принаймні не випадкове;
 *   3. будь-яка, але детерміновано: ключі сортуються, тож той самий готель
 *      дає той самий текст на кожному рушії. «Перша, що трапилась» — це
 *      порядок рядків бази, а він у SQLite, PGlite і Postgres різний (INC-027),
 *      і саме так француз діставав два роди різними мовами.
 *
 * Редакція без жодного тексту не показується (`null`): галочка без тексту —
 * це галочка ні під чим, а вигадати текст згоди не можна тим більше
 * (інваріант 13 — не знайшли, отже відмовляємо, а не дозволяємо).
 *
 * Повертається ПАРА: мова тут не косметика, вона їде в `lang` елемента —
 * німецьке речення, підписане як чеське, читач озвучить неправильно, а гість
 * не зрозуміє, чому текст не його мовою.
 */
export function consentBody(
  edition: { bodies: Record<string, string> } | null | undefined,
  lang: string,
  hotelLang: string,
): { body: string; locale: string } | null {
  const bodies = edition?.bodies ?? {};
  const has = (code: string) => typeof bodies[code] === 'string' && bodies[code].trim() !== '';
  if (has(lang)) return { body: bodies[lang], locale: lang };
  if (has(hotelLang)) return { body: bodies[hotelLang], locale: hotelLang };
  const rest = Object.keys(bodies).filter(has).sort();
  return rest.length > 0 ? { body: bodies[rest[0]], locale: rest[0] } : null;
}
