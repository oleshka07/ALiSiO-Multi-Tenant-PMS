/**
 * Скільки часу невідтверджена бронь тримає номер — і чому строк узагалі є.
 *
 * КІ23: бронь із воріт народжується попередньою, бо справжньою її робить
 * підтвердження гостя, а не відсутність оплати. Наслідок, якого рішення не
 * називало: попередня бронь УЖЕ тримає номер — вона стоїть у вікні
 * `no_double_booking` (0133) і зникає зі списку пропозицій. Тобто гість, який
 * обрав номер і пішов пити каву, забирає кімнату назавжди: звільняти її нема
 * кому, а рецепція наступного ранку бачить бронь, за якою ніхто не приїде.
 *
 * Тридцять хвилин — те саме число, що в К8 для неспареної walk-in-броні, і з
 * тієї ж причини: більше за час, потрібний людині з валізою, щоб дописати
 * прізвище й натиснути «підтвердити», менше за час, за який кімната встигає
 * знадобитись іншому.
 *
 * Число тут, а не в писачі й не в кроні: крон, який рахує «тридцять хвилин
 * від created_at», перестає бути правдою тієї хвилини, коли комусь знадобиться
 * інший строк. Строк лежить у рядку (`reservations.hold_expires_at`), а тут —
 * лише те, яким він народжується.
 */
export const HOLD_MINUTES = 30;

/** Момент, до якого бронь тримає номер. `now` — щоб гейт міг назвати його сам. */
export function holdUntil(now: Date = new Date()): string {
  return new Date(now.getTime() + HOLD_MINUTES * 60_000).toISOString();
}
