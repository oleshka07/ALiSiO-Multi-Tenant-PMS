/**
 * Пошук своєї броні з телефона — правила, які роблять публічний пошук
 * у персональних даних прийнятним.
 *
 * ── Чому це найчутливіше місце застосунку ───────────────────────────────
 *
 * Маршрут, який стоїть за цими правилами, шукає ЖИВИХ ЛЮДЕЙ без жодної
 * автентифікації, і відкритий він для будь-кого в інтернеті — не для того,
 * хто стоїть у холі. Прийнятним його роблять не форма запиту й не гарний
 * текст помилки, а рівно чотири властивості (розбір односерверної вирви,
 * `docs/research/checkin-single-tenant/` §3):
 *
 *   1. вікно — заїзди ±1 день від сьогодні: гість фізично тут, а множина
 *      для вгадування звужується з усієї бази до кількох сьогоднішніх;
 *   2. телефон І прізвище РАЗОМ: телефон сам вгадується, пара — ні;
 *   3. у відповіді ЛИШЕ токен: ні імені, ні дат, ні суми. Хто вгадав —
 *      зайшов, хто ні — не дізнався навіть того, чи існує такий номер;
 *   4. лічильник невдалих спроб на IP.
 *
 * Перше й четверте живуть у маршруті, друге й третє — тут.
 *
 * ── Чим це відрізняється від пошуку КІОСКА ──────────────────────────────
 *
 * Кіоск на ту саму пару чинників віддає масковане імʼя і дати, і має право:
 * він стоїть у холі готелю, поруч люди, а чужий, що підійшов до екрана,
 * ризикує бути побаченим. Ця сторінка відкривається з будь-якого телефона в
 * місті. Тому правило 3 діє тут і не діє там — і саме тому це окремий файл,
 * а не прапорець у спільному.
 */

import { phoneDigits, PHONE_MIN_DIGITS } from '@/apps/kiosk/domain/search';

/**
 * Хвіст номера — останні шість цифр.
 *
 * `+420 777 123 456`, `777123456` і `00420777123456` це ОДИН номер: код
 * країни гість набирає то так, то інак, а канали привозять його втретє
 * інакше. Порівняння за повним рядком розвертало б гостя, чия бронь у базі є.
 *
 * Шість, а не всі: саме стільки лишається спільного між формами запису. І
 * менше за `PHONE_MIN_DIGITS` не приймається взагалі — три цифри звузили б
 * пошук до половини готелю, тобто перестали б бути чинником.
 */
export function phoneTail(value: unknown): string | null {
  const digits = phoneDigits(value);
  if (digits.length < PHONE_MIN_DIGITS) return null;
  return digits.slice(-6);
}

/** Імʼя до порівняння: без регістру, без країв, без подвійних пробілів. */
function plain(value: unknown): string {
  return typeof value === 'string' ? value.trim().toLowerCase().replace(/\s+/g, ' ') : '';
}

/**
 * Чи те, що набрав гість, збігається з іменем броні — У БУДЬ-ЯКОМУ порядку.
 *
 * Імʼя і прізвище ВЗАЄМОЗАМІННІ навмисно: канали привозять броні з
 * переставленими половинами достатньо часто, щоб вимога саме прізвища
 * розвертала гостя, який уже стоїть перед дверима. Ціна цієї поступки нульова
 * — другим чинником усе одно лишається телефон.
 */
export function nameMatches(typed: unknown, row: { firstName?: unknown; lastName?: unknown }): boolean {
  const want = plain(typed);
  if (!want) return false;
  return want === plain(row.lastName) || want === plain(row.firstName);
}

/**
 * Що сказати гостю.
 *
 * `no_page` — окремий рід, і це не дрібниця: бронь ЗНАЙШЛАСЬ, але гостьової
 * сторінки в неї немає (токен не виписано). Гостю це інша порада — «зверніться
 * на рецепцію», а не «перевірте номер», — і без окремого коду він шукав би
 * помилку в тому, що набрав.
 *
 * `not_found` один на обидва випадки — «нічого не знайшли» і «набрано
 * казна-що»: помилка, яка їх розрізняє, це спосіб промацати базу, а не
 * допомога. Рішення про те, що саме показати, ухвалює екран; тут — лише рід.
 */
export type LookupOutcome =
  | { kind: 'found'; token: string }
  | { kind: 'no_page' }
  | { kind: 'not_found' };

/**
 * Рід відповіді за тим, що знайшов запит.
 *
 * Збігів більше за один — це теж `found`, і береться ПЕРШИЙ: пара «телефон +
 * імʼя» у вікні ±1 день практично не дає двох, а коли дає — це та сама
 * людина двома бронями, і будь-яка з них веде на її ж гостьову сторінку.
 * Питати третій чинник тут нема чого: на відміну від кіоска, ми й так нічого
 * не показуємо, крім токена.
 */
export function lookupOutcome(matches: { guestPageToken: string | null }[]): LookupOutcome {
  if (matches.length === 0) return { kind: 'not_found' };
  const withPage = matches.find((m) => !!m.guestPageToken);
  if (!withPage?.guestPageToken) return { kind: 'no_page' };
  return { kind: 'found', token: withPage.guestPageToken };
}
