/**
 * Ключ, яким наліпка на дверях називає свій будинок.
 *
 * ── Навіщо він взагалі є ────────────────────────────────────────────────
 *
 * Гостьова сторінка публічна: гість сканує QR телефоном, і сесії там немає за
 * визначенням. Орендаря мусить назвати сама адреса — інакше публічний
 * endpoint брав би його мовчазним дефолтом, а це інваріант 8 і рівно той
 * рід вади, який не падає, а тихо віддає чужі дані.
 *
 * ── Чому не `id` обʼєкта ────────────────────────────────────────────────
 *
 * Ідентифікатор обʼєкта відомий усім, хто бачив хоч одну адресу адмінки, і
 * він не відкликається. Ключ — НЕПРОЗОРИЙ і видається окремо: якщо наліпку
 * сфотографували й почали нею зловживати, готель просить новий ключ, і стара
 * наліпка перестає вести кудись. З `id` це коштувало б зміни ідентифікатора
 * обʼєкта в усій базі.
 *
 * ── Довжина ─────────────────────────────────────────────────────────────
 *
 * 16 символів алфавіту з 30 — це ~78 біт. Ключ не є секретом у сенсі паролю
 * (він надрукований на склі, його бачить кожен перехожий), але він мусить
 * бути НЕВГАДУВАНИМ: сусідній готель на тому самому сервері не має підібрати
 * адресу чужої сторінки перебором. 80 біт закриває це з запасом.
 *
 * Алфавіт без `0`, `1`, `l`, `o`, `i`, `u`: ключ іноді диктують голосом або
 * набирають з паперу, і пара «нуль — літера O» коштує дзвінка на рецепцію.
 */

import crypto from 'node:crypto';

/** 30 символів: без `0`, `1`, `l`, `o`, `i`, `u` — їх плутають на око й на слух. */
const ALPHABET = '23456789abcdefghjkmnpqrstvwxyz';
const LENGTH = 16;

/**
 * Новий ключ.
 *
 * `randomBytes`, не `Math.random`: другий передбачуваний, а ключ, який можна
 * обчислити, знаючи час видачі, не є невгадуваним. Відкидання «хвоста»
 * діапазону (`% ALPHABET.length` без нього) робило б перші символи алфавіту
 * трохи ймовірнішими — дрібниця, але безкоштовна для виправлення.
 */
export function generateGuestAppKey(): string {
  const limit = Math.floor(256 / ALPHABET.length) * ALPHABET.length;
  let out = '';
  while (out.length < LENGTH) {
    for (const byte of crypto.randomBytes(LENGTH)) {
      if (byte >= limit) continue;
      out += ALPHABET[byte % ALPHABET.length];
      if (out.length === LENGTH) break;
    }
  }
  return out;
}

/**
 * Ключ із адреси — або `null`.
 *
 * Форма перевіряється ДО запиту в базу, і це не педантизм: сегмент адреси
 * приходить від будь-кого з інтернету, а рядок, який не може бути ключем,
 * не має права навіть спробувати стати умовою запиту. Те саме правило, що
 * `readSearchDate` у кіоску: те, що не є значенням, не стає чинником.
 */
export function readGuestAppKey(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const v = raw.trim().toLowerCase();
  if (v.length !== LENGTH) return null;
  for (const ch of v) if (!ALPHABET.includes(ch)) return null;
  return v;
}
