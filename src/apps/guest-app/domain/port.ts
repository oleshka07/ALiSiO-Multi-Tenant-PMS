/**
 * Звідки застосунок бере вільні номери й ціни — і чому це ПОРТ.
 *
 * ── Задача, яку він вирішує ─────────────────────────────────────────────
 *
 * Застосунок не робиться під один готель. Для готелю, який уже живе в нас,
 * наявність і ціну знає наше ядро. Для готелю, який ще на своїй системі
 * (Winhotel + власний Onlinebuchung), єдина правда про вільні номери лежить
 * ТАМ, і питати її в нас означало б продавати кімнати, яких немає.
 *
 * Тому джерело — окремий шов, а не `if` у хендлері. Той самий взірець, що
 * `modules/channels/port.ts`: інтерфейс тут, реалізації поруч, вибір — за
 * `properties.system_of_record` (`alisio` → `core`, `external` → `handoff`).
 *
 * ── Що порт НЕ робить ───────────────────────────────────────────────────
 *
 * Не рахує ціну. Ціну рахує `priceNights()` через `calculateQuote` — одне
 * джерело на весь продукт (інваріант 16), і адаптер `core` його КЛИЧЕ, а не
 * повторює. Адаптер `handoff` ціни не називає взагалі: її знає чужа система,
 * і вигадане тут число — це бронювання за ціною, якої готель не називав
 * (інваріант 17).
 */

/**
 * Що показати гостю на кроці вибору.
 *
 * Рівень — ТИП номера, не окрема кімната: гість обирає «двомісний із
 * балконом», а яка саме кімната — справа готелю (і `assignUnit` при заїзді).
 * Показувати список кімнат означало б обіцяти конкретну, а потім давати іншу.
 */
export interface StayOffer {
  unitTypeId: string;
  /** Назва типу так, як її бачить гість. */
  name: string;
  /** Скільки таких кімнат вільні на ці дати — не показується числом, але
   *  вирішує, чи є що показувати взагалі. */
  free: number;
  /** Сума за все перебування, уже з правилами цін. */
  total: number;
  currency: string;
  /** Ночей у пропозиції — щоб екран міг сказати «3 ночі», не рахуючи сам. */
  nights: number;
}

export interface StayQuery {
  organizationId: string;
  propertyId: string;
  /** `YYYY-MM-DD`, заїзд. */
  from: string;
  /** `YYYY-MM-DD`, виїзд. */
  to: string;
  adults: number;
}

/**
 * Джерело правди про наявність і ціну для ОДНОГО обʼєкта.
 *
 * `offers` віддає лише те, що справді можна продати: тип, у якого є вільна
 * кімната І повна ціна на всі ночі. Тип, якому бракує ціни хоч на одну ніч,
 * не потрапляє в список — «уточнюйте на рецепції» на екрані бронювання це не
 * ціна, а відмова (інваріант 17).
 */
export interface StaySource {
  readonly kind: 'core' | 'handoff';
  offers(query: StayQuery): Promise<StayOffer[]>;
}
