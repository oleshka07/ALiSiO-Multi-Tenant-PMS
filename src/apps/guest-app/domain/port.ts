/**
 * Звідки застосунок бере вільні номери й ціни — і чому це ПОРТ.
 *
 * ── Задача, яку він вирішує ─────────────────────────────────────────────
 *
 * Застосунок не робиться під один готель. Для готелю, який уже живе в нас,
 * наявність і ціну знає наше ядро. Для готелю, який ще на своїй системі
 * (Winhotel + власний Onlinebuchung), єдина правда про вільні номери лежить
 * ТАМ, і питати її в нас означало б продавати кімнати, яких немає.
 *
 * Тому джерело — окремий шов, а не `if` у хендлері. Той самий взірець, що
 * `modules/channels/port.ts`: інтерфейс тут, реалізації поруч, вибір — за
 * `properties.system_of_record` (`alisio` → `core`, `external` → `handoff`).
 *
 * ── Що порт НЕ робить ───────────────────────────────────────────────────
 *
 * Не рахує ціну. Ціну рахує `priceNights()` через `calculateQuote` — одне
 * джерело на весь продукт (інваріант 16), і адаптер `core` його КЛИЧЕ, а не
 * повторює. Адаптер `handoff` ціни не називає взагалі: її знає чужа система,
 * і вигадане тут число — це бронювання за ціною, якої готель не називав
 * (інваріант 17).
 */

/**
 * Що показати гостю на кроці вибору.
 *
 * ── Рівень: ПАРА «тип номера × тариф», а не тип ─────────────────────────
 *
 * Кімнату гість не обирає: він обирає «двомісний із балконом», а яка саме —
 * справа готелю (і `assignUnit` при заїзді). Показувати список кімнат
 * означало б обіцяти конкретну, а потім дати іншу.
 *
 * А от ТАРИФ обирає саме гість, і це не косметика. Та сама кімната на ті
 * самі дати продається за кількома умовами — «невідмінна, дешевше» проти
 * «зі сніданком і відміною до 14:00 напередодні», — і різниця між ними це
 * різні гроші й різні права. Одна картка на тип змусила б застосунок
 * ВИБРАТИ тариф за гостя: або завжди найдешевший (і готель не продасть
 * сніданок), або завжди базовий (і гість не побачить, що дешевше буває).
 *
 * Ця вісь у продукті вже є: ціна лежить у `price_calendar` парою
 * `(unit_type_id, rate_plan_id)`, а бронь памʼятає тариф у
 * `reservations.rate_plan_id`. Застосунок її не вигадує — він перестає її
 * ховати.
 *
 * Готель без жодного видимого тарифу дістає одну картку на тип із
 * `ratePlanId = null` — це базова ціна типу, рівно те, що лежить у
 * `price_calendar` з порожнім тарифом.
 */
export interface StayOffer {
  unitTypeId: string;
  /** Назва типу так, як її бачить гість. */
  name: string;
  /** Тариф, за яким названа ця сума. `null` — базова ціна типу. */
  ratePlanId: string | null;
  /** Назва тарифу для гостя; `null` разом із `ratePlanId`. */
  ratePlanName: string | null;
  /**
   * Умови тарифу — дослівно з довідника готелю, без переказу своїми словами.
   * Порожні там, де готель їх не заповнив: вигадане «безкоштовне скасування»
   * коштує дорожче, ніж жодного рядка про скасування.
   */
  mealPlan: string | null;
  cancellationPolicy: string | null;
  /** Скільки таких кімнат вільні на ці дати — не показується числом, але
   *  вирішує, чи є що показувати взагалі. */
  free: number;
  /** Сума за все перебування, уже з правилами цін. */
  total: number;
  /**
   * Та сама сума в перерахунку на ніч — для рядка «від X за ніч» у списку.
   *
   * Це ПОДАННЯ вже порахованої суми, а не друге джерело ціни: жодна ніч тут
   * не оцінюється, `total` ділиться на `nights` і округлюється `money()`
   * (інваріант 9). Списують завжди `total`.
   */
  perNight: number;
  currency: string;
  /** Ночей у пропозиції — щоб екран міг сказати «3 ночі», не рахуючи сам. */
  nights: number;
}

export interface StayQuery {
  organizationId: string;
  propertyId: string;
  /** `YYYY-MM-DD`, заїзд. */
  from: string;
  /** `YYYY-MM-DD`, виїзд. */
  to: string;
  adults: number;
}

/**
 * Джерело правди про наявність і ціну для ОДНОГО обʼєкта.
 *
 * `offers` віддає лише те, що справді можна продати: пару «тип × тариф», у
 * якої є вільна кімната І повна ціна на всі ночі. Пара, якій бракує ціни хоч
 * на одну ніч, не потрапляє в список — «уточнюйте на рецепції» на екрані
 * бронювання це не ціна, а відмова (інваріант 17).
 */
export interface StaySource {
  readonly kind: 'core' | 'handoff';
  offers(query: StayQuery): Promise<StayOffer[]>;
}
