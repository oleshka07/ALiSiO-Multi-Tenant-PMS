export function seedStagePrompts(): number {
  const db = getDb();
  
  // Get org ID
  const org = db.prepare('SELECT id FROM organizations LIMIT 1').get() as any;
  if (!org) {
    console.log('[Seed Prompts] No organization found — skipping');
    return 0;
  }

  let seeded = 0;

  for (const prompt of STAGE_PROMPTS) {
    // Check if already exists for this stage
    const existing = db.prepare(
      'SELECT id FROM crm_prompt_configs WHERE stage = ? AND organization_id = ? LIMIT 1'
    ).get(prompt.stage, org.id) as any;

    if (existing) {
      continue; // Don't overwrite existing user-configured prompts
    }

    db.prepare(`
      INSERT INTO crm_prompt_configs 
      (organization_id, name, stage, trigger_type, system_prompt, context_instructions, temperature, model, is_active)
      VALUES (?, ?, ?, 'auto', ?, ?, 0.7, 'gpt-4o', 1)
    `).run(org.id, prompt.name, prompt.stage, prompt.system_prompt, prompt.context_instructions);

    seeded++;
    console.log(`[Seed Prompts] ✅ Created prompt for stage: ${prompt.stage}`);
  }

  if (seeded > 0) {
    console.log(`[Seed Prompts] Seeded ${seeded} stage prompts`);
  }

  return seeded;
}
