/**
 * Строк оплати: ОДНЕ місце, де живе арифметика і одне, де живе число.
 *
 * ── Що зламалось до цього ───────────────────────────────────────────────
 *
 * «14 днів» для вільної фактури рахувалися в ТРЬОХ місцях: екран документів
 * рахував їх двічі (значення поля і тіло запиту), маршрут — утретє, як
 * запасний варіант. Три обчислення одного факту не «майже однакові» — вони
 * розійдуться на першій же правці, і розійдуться тихо: оператор побачить у
 * полі одну дату, а в документі опиниться інша, і жодна перевірка про це не
 * скаже, бо кожне з трьох окремо правильне.
 *
 * Тому число тут одне (`DEFAULT_PAYMENT_TERMS_DAYS`), арифметика одна
 * (`dueDateFrom`), і рішення «чий строк переможе» теж одне
 * (`customInvoiceDue`). `dueDateFor()` у `data/folio.repo.ts` рахує тією
 * самою `dueDateFrom` — тобто фактура фоліо і вільна фактура не можуть
 * розійтися в тому, що таке «плюс N днів».
 *
 * Чистий модуль, без бази: його читає і сервер, і екран (через вузькі двері
 * `@invoicing/terms`).
 */

/**
 * Скільки днів дає вільна фактура, коли строку не назвали ні в запиті, ні на
 * фірмі.
 *
 * Це НЕ мовчазний дефолт у сенсі інваріанта 8: екран показує це число в полі
 * строку, оператор його бачить і міняє одним кліком. Мовчазним він був би,
 * якби документ дістав дату, якої ніхто не бачив, — а саме так і сталося б,
 * якби екран рахував своє, а маршрут своє.
 *
 * Строк ФІРМИ, коли фірма названа, завжди сильніший за це число: домовленість
 * із конкретним платником не має програвати сталій (Д58).
 */
export const DEFAULT_PAYMENT_TERMS_DAYS = 14;

/**
 * Дата виписки плюс N днів, у календарних датах UTC.
 *
 * Саме датами, а не мітками часу: `due_date` це день, і додавання через
 * місцевий час дало б зсув на добу в поясі за Гринвічем — тобто фактуру,
 * прострочену на день раніше, ніж домовлено.
 */
export function dueDateFrom(issueDate: string, days: number): string {
  const d = new Date(`${issueDate.slice(0, 10)}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + Number(days));
  return d.toISOString().slice(0, 10);
}

/**
 * Строк ВІЛЬНОЇ фактури: названий у запиті → строк фірми → дефолт.
 *
 * Порядок не переставляється. Названий вручну строк — це те, що оператор
 * щойно ввів, дивлячись на екран; строк фірми — домовленість, записана на
 * самій фірмі; дефолт — те, що лишається, коли не сказано нічого.
 *
 * `companyTermsDays` приходить від `companies.payment_terms_days` тоді і
 * тільки тоді, коли покупця названо ІДЕНТИФІКАТОРОМ фірми з довідника.
 * Покупець, введений текстом, фірмою не є — зіставляти його з довідником за
 * назвою чи реєстраційним номером не можна (Д60: привʼязати не до тієї фірми
 * гірше, ніж не привʼязати зовсім).
 */
export function customInvoiceDue(
  namedDueDate: string | null | undefined,
  issueDate: string,
  companyTermsDays?: number | null,
): string {
  const named = (namedDueDate ?? '').trim();
  if (named) return named.slice(0, 10);
  const days = companyTermsDays === null || companyTermsDays === undefined
    ? DEFAULT_PAYMENT_TERMS_DAYS
    : Number(companyTermsDays);
  return dueDateFrom(issueDate, days);
}
