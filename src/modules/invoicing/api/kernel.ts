/**
 * @invoicing/kernel — те саме фактурування, але без HTTP.
 *
 * ── Навіщо друга адреса ─────────────────────────────────────────────────
 *
 * `api/index.ts` — двері для маршрутів: кожен експорт там уже обгорнутий у
 * `withModule`, а той тягне `@core/auth/session`, а той — `next/server`.
 * Для маршруту це правильно й нічого не коштує: він і так усередині Next.
 *
 * Для іншого МОДУЛЯ — ні. `@events` кладе оренду залу у фоліо; йому потрібні
 * дві чисті функції, а не варта (особу вже встановила варта його власного
 * маршруту). Коли він імпортував їх через `index.ts`, разом із ними
 * приїжджав `next/server` — і `events.repo.check.ts`, який біжить під голим
 * node, перестав запускатися. Перевірка впала не тому, що логіка зламалась,
 * а тому, що двері виявились завеликі.
 *
 * Тому їх двоє. Обидві — під `api/`, тобто обидві є фасадом у сенсі
 * `check-boundaries`: модуль лишається закритим, просто має вхід для людей
 * (із вартою) і вхід для сусідніх модулів (без неї).
 *
 * Тут не має бути нічого, що приймає `Request` або повертає `Response`.
 */

