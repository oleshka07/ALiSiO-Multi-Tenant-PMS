/**
 * Єдині двері, якими фактура видаляється (Р10.14).
 *
 * `fin_invoice_lines` і `fin_invoice_tax_totals` тримають `invoice_id` як
 * `TEXT NOT NULL` БЕЗ зовнішнього ключа на `invoices`. Обидві пишуться однією
 * транзакцією разом із фактурою (`folio.repo.ts`), тож значення завжди вказує
 * на `invoices.id` — але база про це не знає й нічого за собою не прибирає.
 *
 * Два маршрути видаляли фактури і жоден не чіпав рядків:
 * `/api/invoices/[id]` (одна) і `/api/accounting/invoice-batch` (оптом по
 * організації, каналу й місяцю). Рядки лишались вказувати в нікуди — числа не
 * псується, бо читачі ходять від живої фактури, але книги розходяться мовчки.
 *
 * Чому двері, а не по рядку `DELETE` у кожному маршруті: третій маршрут
 * зʼявиться і про рядки забуде — рівно так зʼявились ці два. Предикат
 * передається ззовні, бо він у маршрутів різний, а порядок видалення —
 * тутешній і однаковий: діти по `invoice_id`, потім самі фактури.
 *
 * Орендар при цьому НЕ додається сюди підпудру: виклик іде вже в контексті
 * орендаря (`runWithOrganization`), а предикат маршруту сам називає
 * `organization_id`. Двері, які тихо дописували б своє звуження, ховали б від
 * читача те, що насправді видаляється.
 */
import { getSql } from '@core/db/async';

/** Те, чим двері виконують запити: пул або дескриптор транзакції. */
type Runner = { run(sql: string, params?: unknown[]): Promise<{ changes: number }> };

/**
 * Видалити фактури, що підпадають під `where`, разом із їхніми рядками.
 *
 * `where` — предикат ДЛЯ `invoices` (без слова `WHERE`), `params` — його
 * параметри. Ті самі параметри йдуть у підзапит для дітей, тому предикат має
 * бути придатним до повторного застосування — звичайний `AND`-ланцюжок.
 *
 * `on` — необовʼязковий виконавець: маршрут оптового видалення робить усе в
 * одній транзакції й передає сюди її дескриптор. Без нього три `DELETE` пішли
 * б поза транзакцією, і збій посередині лишив би фактури без рядків — тобто
 * той самий хвіст, тільки з іншого кінця.
 *
 * Повертає, скільки фактур видалено.
 */
export async function deleteInvoicesWhere(where: string, params: unknown[], on?: Runner): Promise<number> {
  const run = on ?? getSql();

  // Діти першими й ОБИДВОЄ: пропущена таблиця лишає такий самий хвіст, як
  // раніше лишали обидві.
  for (const table of ['fin_invoice_tax_totals', 'fin_invoice_lines']) {
    await run.run(
      `DELETE FROM ${table}
        WHERE invoice_id IN (SELECT id FROM invoices WHERE ${where})`,
      params,
    );
  }

  const res = await run.run(`DELETE FROM invoices WHERE ${where}`, params);
  return res.changes;
}
