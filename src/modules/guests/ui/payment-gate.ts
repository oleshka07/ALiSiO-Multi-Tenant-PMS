/**
 * Чи стоїть перед гостем платіжний шлагбаум — і за ЧИЇМ словом.
 *
 * ── Що було зламано (INC-211) ───────────────────────────────────────────
 *
 * Гість пройшов бронювання в гостьовому застосунку, побачив на екрані
 * «Bezahlt wird an der Rezeption — bei der Anreise oder bei der Abreise»,
 * підтвердив бронь — і наступна ж сторінка показала йому стіну «Zahlung
 * abschließen für vollständigen Zugang» з кнопкою «попросити рахунок».
 * Зареєструватися й заселитися він не міг.
 *
 * Правило шлагбаума стояло числом у тілі сторінки:
 *
 *     if (!isPaid && paymentsSectionOn) → PaymentGateScreen
 *
 * тобто «до оплати нічого не показуємо» було властивістю КОДУ, однаковою для
 * всіх готелів. Готель, який бере гроші на стійці, вимкнути це міг лише
 * прибравши секцію `payments` цілком — разом із залишком до сплати, який
 * гостю показувати якраз треба.
 *
 * ── Слово в обʼєкта вже було ────────────────────────────────────────────
 *
 * `properties.checkin_payment_policy` (міграція 0410): `prepaid` — як було,
 * `allow_pay_later` — пускають без оплати. Кіоск і рецепційний PATCH його
 * поважають з дня заведення; гостьова сторінка — ні. Тобто той самий готель
 * відповідав «можна» терміналу в холі і «не можна» власній сторінці на ту
 * саму бронь — рівно та розбіжність, заради якої 0410 і заводила колонку
 * замість прапорця пристрою.
 *
 * Тому тут не заводиться нове налаштування. Тут читається наявне, і читається
 * ТИМ САМИМ `readCheckinPolicy`: другий нормалізатор розійшовся б із першим
 * у тижні, коли ніхто не дивиться.
 *
 * ── Що шлагбаум НЕ вимикає ──────────────────────────────────────────────
 *
 * Секцію `payments`. Готель на `allow_pay_later` далі показує, скільки
 * лишилось до сплати, — просто як рядок, а не як двері. Різниця між
 * «показати суму» і «не пустити далі» тут єдина, яку ми міняємо.
 *
 * ── Чому `ui/`, а не `domain/` ──────────────────────────────────────────
 *
 * Питання «чи показувати цей екран» — рішення ПОВЕРХНІ, і читає його
 * сторінка, яка живе поза модулем. `modules/guests/domain` ззовні не
 * відкривається (`check-boundaries`), а правильні двері — фасад `@guests` або
 * `modules/guests/ui/`. Фасад тут не підходить: він тягне `next/server`, а
 * сторінка гостя — клієнтський компонент.
 *
 * Тож функція стоїть рівно там, де `PaymentGateScreen.tsx`, яким вона керує.
 * Це не обхід гейта: рішення і екран, яким воно керує, в одній теці — це
 * ближче до правди, ніж рішення в домені й екран за три поверхи від нього.
 */
import { readCheckinPolicy } from '@bookings/checkin-policy';

export interface PaymentGateFacts {
  /** Нічого не винен: сплачено, передоплачено або залишок ≤ 0. */
  isPaid: boolean;
  /** Чи показує цей готель секцію `payments` узагалі. */
  paymentsSectionOn: boolean;
  /** `properties.checkin_payment_policy` як його віддала база — сире. */
  checkinPaymentPolicy: unknown;
}

/**
 * Чи закрити гостю сторінку до оплати.
 *
 * Три умови, і всі три мусять справдитись: винен, готель узагалі говорить
 * про оплату на сторінці, і готель вимагає оплати ДО заселення.
 *
 * Невідоме слово обʼєкта (порожньо, `null`, чуже значення) → `prepaid`, тобто
 * шлагбаум стоїть. Це інваріант 13, а не обережність: порожній контекст
 * орендаря на Postgres віддає нуль рядків, і мʼякший дефолт відчинив би двері
 * саме там, де ми не знаємо, чий це готель.
 */
export function paymentGateStands(facts: PaymentGateFacts): boolean {
  if (facts.isPaid) return false;
  if (!facts.paymentsSectionOn) return false;
  return readCheckinPolicy(facts.checkinPaymentPolicy) === 'prepaid';
}
