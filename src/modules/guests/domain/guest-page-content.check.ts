/**
 * Те, що готель ввів, гість бачить. Те, чого готель не вводив, гість не читає.
 *
 *   node src/modules/guests/domain/guest-page-content.check.ts
 *
 * ── Звідки цей гейт ─────────────────────────────────────────────────────
 *
 * Готель заповнив у налаштуваннях умови паркінгу: підземний гараж, 10 € за
 * ніч, в'їзд з іншої вулиці, висота 2 м, квиток на рецепції. Текст зберігся
 * в `parking_info`, доїхав до браузера — і не рендерився. Замість нього шіт
 * «Parken» показував захардкожений рядок «Kostenloser Parkplatz am Eingang».
 *
 * Тобто система взяла введений готелем текст про платний гараж, викинула його
 * і написала гостю протилежне. Гість читає «безкоштовно», на виїзді платить.
 *
 * Того самого дня знайшлося ще два таких поля: `emergency_phone` (номер
 * рецепції — введений, невидимий) і `territory_map_url`. І дзеркальна
 * помилка: у порожніх полях сторінка стверджувала те, чого готель не казав —
 * «🎥 відео-гід останніх 500 м» без жодного відео, чотири кроки самозаїзду з
 * «…» замість коду замка, англійська плашка «Photo of entrance / lockbox».
 *
 * ── Чому саме такі перевірки ────────────────────────────────────────────
 *
 * Прив'язатись до `parking_info` означало б ловити рівно ту помилку, яку вже
 * виправлено. Помилка ж не в полі, а у формі: репозиторій віддає клієнту
 * поле, ніхто його не малює, і збірка мовчить — для TypeScript зайвий ключ в
 * об'єкті не помилка. Тому перша перевірка перебирає ВСІ поля, які
 * `guest-portal.repo.ts` кладе в конфіг, і вимагає, щоб кожне десь читалось.
 * Наступне поле, додане й забуте, впаде тут, а не на демо.
 *
 * Друга половина — про зворотний бік: службові заглушки й вигадані факти в
 * гілці «даних немає». Вони перелічені поіменно, бо це рядки, а не структура.
 */
import assert from 'node:assert';
import fs from 'node:fs';

const REPO = 'src/modules/guests/data/guest-portal.repo.ts';
const PAGE = 'src/app/guest/[token]/page.tsx';
const DICT = 'src/app/guest/[token]/translations.ts';

const repoSrc = fs.readFileSync(REPO, 'utf8');
const pageSrc = fs.readFileSync(PAGE, 'utf8');
const dictSrc = fs.readFileSync(DICT, 'utf8');

// Коментарі пояснюють рядки, яких БІЛЬШЕ немає. Гейт, який не відрізняє
// пояснення від коду, падав би на власній документації — уже було.
const pageCode = pageSrc.replace(/\{?\/\*[\s\S]*?\*\/\}?/g, '').replace(/^\s*\/\/.*$/gm, '');

// ── Кожне поле конфігу десь малюється ────────────────────────────────
//
// Беремо саме той об'єкт, який репозиторій повертає клієнту: це і є контракт
// «готель ввів → гість бачить».
const merged = repoSrc.slice(
  repoSrc.indexOf('const merged'),
  repoSrc.indexOf('return merged'),
);
assert.ok(merged.length > 200, 'не знайшов об’єкт merged — гейт дивиться не туди');

const fields = [...new Set([...merged.matchAll(/^\s{4}([a-z_]+):/gm)].map((m) => m[1]))];
assert.ok(fields.length >= 20, `полів мало (${fields.length}) — розбір зламався`);

// `wifi_password` малюється, `weather_lat` іде в мапу — усі до одного мають
// слід на сторінці. Порожній список винятків тут навмисно: щойно поле
// справді не потрібне гостю, його місце — не в цьому об'єкті.
const invisible = fields.filter((f) => !pageCode.includes(f));
assert.deepStrictEqual(invisible, [],
  `готель заповнює ці поля, вони їдуть у браузер і ніде не малюються: ${invisible.join(', ')}`);
console.log(`  ok  усі ${fields.length} полів гостьового конфігу доходять до екрана`);

// ── Паркінг: текст готелю, а не наш ──────────────────────────────────
assert.ok(/cfg\??\.parking_info/.test(pageCode),
  'шіт «Паркінг» мусить малювати введений готелем parking_info');
assert.ok(!/parkingFree/.test(pageCode) && !/parkingFree/.test(dictSrc),
  'рядок «безкоштовна парковка біля входу» — твердження, якого жоден готель не робив');
for (const claim of ['Kostenloser Parkplatz', 'Free parking', 'Безкоштовна парковка',
  'Bezplatné parkování', 'Bezpłatny parking', 'Gratis parkeren', 'Parking gratuit']) {
  assert.ok(!dictSrc.includes(claim),
    `«${claim}» — ціна паркінгу, вигадана за готель; вона мусить приходити з parking_info`);
}
console.log('  ok  про парковку говорить готель, а не словник');

// ── Порожнє поле нічого не обіцяє ────────────────────────────────────
//
// Кожен із трьох рядків нижче гість справді бачив.
assert.ok(!/lock_code\s*\|\|\s*['"]…['"]/.test(pageCode),
  '«…» замість коду замка — інструкція ввести код, якого немає');
assert.ok(!/Photo of entrance/.test(pageCode),
  'службова плашка англійською показувалась гостю в усіх семи мовах');
// Підказка про відео існує рівно тоді, коли за нею є посилання: раніше гілка
// `else` малювала ту саму підказку без URL.
const videoTips = [...pageCode.matchAll(/t\.videoGuide/g)].length;
assert.strictEqual(videoTips, 1,
  'підказка про відео-гід мусить бути одна — усередині перевірки video_guide_url');
console.log('  ok  сторінка не обіцяє того, чого готель не вводив');

console.log('гостьова сторінка: показує введене, не вигадує відсутнє');
