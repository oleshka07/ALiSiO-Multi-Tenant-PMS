/**
 * Що таке «персональні дані» — визначенням у КОДІ, а не в голові (INC-306).
 *
 * ── Навіщо визначення, а не список таблиць ──────────────────────────────
 *
 * Перший реєстр ретенції (INC-305) стеріг таблиці з `guest_id`. Це вже краще
 * за нічого, але вужче за правду: персональні дані живуть і там, де на гостя
 * не посилаються зовсім — незакінчена бронь, заявка з сайту, лист очікування,
 * ваучер із поштою отримувача. Виміряно: таблиць із персональними КОЛОНКАМИ
 * двадцять, а з `guest_id` — пʼять.
 *
 * Тому властивість розширено: не «таблиці з `guest_id`», а «таблиці з
 * персональними даними». Ширше і чесніше — але воно потребує сказати, що таке
 * «персональні», інакше наступний читач вирішить це по-своєму.
 *
 * ── Дивимось на КОЛОНКИ, а не на назви таблиць ──────────────────────────
 *
 * Саме назва підвела минулого разу: `guest_consents` виглядала «новою
 * таблицею гостя», а в реєстр не потрапила, бо реєстру не існувало. Назва
 * таблиці нічого не гарантує — `waitlist` і `site_incoming_leads` не мають у
 * назві слова «гість», а тримають пошту й телефон живої людини.
 *
 * ── Межа визначення, названа прямо ──────────────────────────────────────
 *
 * Це визначення НЕ вирішує, чи дані підлягають знеособленню: пошта готелю в
 * `organizations` — теж пошта, але вона про юридичну особу, а не про гостя.
 * Визначення каже лише «тут може лежати щось про людину, тож мовчати про цю
 * таблицю не можна». Рішення — у реєстрі `retention-tables.ts`, і кожне з
 * причиною.
 */

export interface PersonalColumnRule {
  /** Як це називається в звіті гейта. */
  label: string;
  /** Візерунок імені колонки. */
  match: RegExp;
  /** Чому це персональне — речення для людини. */
  why: string;
}

/**
 * Ознаки персональних даних за іменем колонки.
 *
 * Список навмисно короткий і буквальний: кожен рядок — те, чим людину можна
 * впізнати або з нею звʼязатись. Розширювати його дозволено; звужувати —
 * лише разом із рядком у звіті, бо звуження робить гейт сліпим тихо.
 */
export const PERSONAL_COLUMN_RULES: readonly PersonalColumnRule[] = [
  { label: 'пошта', match: /(^|_)e?mail(_|$)/,
    why: 'адреса, на яку можна написати конкретній людині' },
  { label: 'телефон', match: /(^|_)(phone|whatsapp|mobile)(_|$)/,
    why: 'номер, за яким можна подзвонити конкретній людині' },
  { label: 'документ', match: /(^|_)(document_number|document_type|passport|visa_number)(_|$)/,
    why: 'ідентифікатор особи, виданий державою' },
  { label: 'адреса', match: /(^|_)(address|street|zip|postcode)(_|$)/,
    why: 'де людина живе' },
  { label: 'IP', match: /(^|_)ip(_|$)/,
    why: 'мережева адреса, за якою людину впізнають' },
  { label: 'дата народження', match: /(^|_)(date_of_birth|birth_date)(_|$)/,
    why: 'у парі з іменем — майже завжди унікальна ознака' },
  { label: 'імʼя особи', match: /^(first_name|last_name|guest_name|full_name)$/,
    why: 'як людину звати' },
];

/** Які персональні ознаки має ця колонка (порожньо — жодної). */
export function personalKindOf(column: string): PersonalColumnRule | null {
  for (const rule of PERSONAL_COLUMN_RULES) {
    if (rule.match.test(column)) return rule;
  }
  return null;
}
