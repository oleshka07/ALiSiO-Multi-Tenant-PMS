/**
 * Двоє не в'їжджають в один номер на одну ніч — і тримає це БАЗА (INC-045).
 *
 * ── Що ламалося ─────────────────────────────────────────────────────────
 *
 * Скрізь стояв один візерунок: прочитали, подумали, записали. У
 * `reservations.handlers.ts` між перевіркою (`:84-92`) і вставкою стоять
 * дедуплікація гостя і запит комісії — кілька походів у базу, і транзакції
 * немає взагалі. Писачів у `reservations` щонайменше шість. Два одночасні
 * запити на останній номер — віджет і OTA, або два гості у віджеті —
 * проходили ОБИДВА.
 *
 * Це К18 ще раз: правило, яке має тримати база, не можна лишати уважності
 * коду.
 *
 * ── Перевірка ДО запису лишається ───────────────────────────────────────
 *
 * Вона дає людський текст у 99 % випадків: «номер зайнято з 3 по 5 березня»
 * замість коду помилки. Обмеження бази — не заміна їй, а те, що тримає
 * останній відсоток, у якому й живуть гроші.
 *
 * ── Що робить ця обгортка ───────────────────────────────────────────────
 *
 * Перетворює порушення обмеження на ОДНУ названу відмову, `UnitOverlap`, щоб
 * кожен викликач вирішував сам:
 *
 *   оператор і віджет — 409 з ТИМ САМИМ текстом, що дає перевірка до запису
 *     (гість не має бачити двох різних відмов на одну причину);
 *   канал — не відмова: `unit_id` у `null`, бронь лягає у смугу «Без номера»,
 *     рядок у журнал синхронізації. Канал не питає дозволу, він повідомляє
 *     факт.
 *
 * ── Два двигуни, одна обіцянка ──────────────────────────────────────────
 *
 * На Postgres обмеження — `EXCLUDE USING gist`, і воно кидає SQLSTATE `23P01`.
 * SQLite `EXCLUDE` не має взагалі; там запис серіалізується — і це ОДНЕ місце,
 * а не шість, бо шість місць серіалізації розійдуться так само, як розійшлися
 * шість перевірок.
 *
 * ── Серіалізація САМА ПО СОБІ не забороняє нічого ───────────────────────
 *
 * Це коштувало першої червоної сцени, і воно не очевидне: черга лише не пускає
 * двох писачів одночасно, а другий писач після неї спокійно вставляє другу
 * бронь у той самий номер. Двоє прошли ОБИДВА — рівно те, що ми лагодимо.
 *
 * Тому на SQLite всередині черги стоїть ще й ПЕРЕВІРКА, і саме її серіалізація
 * робить чесною: «прочитали, вільно» і «записали» стають одним неподільним
 * кроком, тобто зникає вікно, у якому й живе вада. Запит для неї — не свій, а
 * `stayOverlapsExisting` із `../data/conflicts.repo`: другий такий запит
 * розійшовся б з обмеженням бази так само, як розійшлися б два списки статусів.
 */
import { getSql } from '@core/db/async';
import { stayOverlapsExisting } from '../data/conflicts.repo';

/** Номер уже зайнято на ці ночі — і сказала це БАЗА, а не наша перевірка. */
export class UnitOverlap extends Error {
  readonly unitId: string;
  readonly checkIn: string;
  readonly checkOut: string;

  constructor(unitId: string, checkIn: string, checkOut: string) {
    super(`Номер уже зайнято на ці дати (${checkIn} — ${checkOut})`);
    this.name = 'UnitOverlap';
    this.unitId = unitId;
    this.checkIn = checkIn;
    this.checkOut = checkOut;
  }
}

/**
 * Код, за яким Postgres каже «порушено обмеження виключення».
 *
 * Ловиться саме він, а не текст: текст залежить від локалі сервера й від імені
 * обмеження, і звірка за текстом — це той самий клас, що `db-names.check`
 * (Ц49), де рід відмови судили за «does not exist» і назвали вигадану причину.
 */
const EXCLUSION_VIOLATION = '23P01';

/** Ім'я обмеження — щоб не переплутати наше виключення з чиїмось чужим. */
const CONSTRAINT = 'no_double_booking';

function isOverlapViolation(err: unknown): boolean {
  const e = err as { code?: unknown; constraint?: unknown };
  if (e?.code !== EXCLUSION_VIOLATION) return false;
  // `constraint` Postgres віддає в тому ж полі помилки. Якщо колись зʼявиться
  // друге виключення на іншій таблиці, ця перевірка не дасть видати його за
  // зайнятий номер.
  return e.constraint === undefined || e.constraint === CONSTRAINT;
}

/**
 * Серіалізація запису на SQLite — ОДНА на всіх писачів.
 *
 * `EXCLUDE` тут немає й не буде, тож єдине, що лишається, — не пускати двох
 * писачів одночасно. Черга проста навмисно: на SQLite ми не обслуговуємо
 * клієнтів, це дев і стенди, і складніший замок був би кодом, який ніхто
 * ніколи не перевірить під навантаженням.
 */
let sqliteQueue: Promise<unknown> = Promise.resolve();

/**
 * Виконати запис і перетворити порушення обмеження бази на `UnitOverlap`.
 *
 * `ctx.unitId === null` — бронь без номера (смуга «Без номера»): перетинатися
 * їй нема з чим, обмеження її не стосується, і серіалізувати теж нема чого.
 */
export async function insertingStay<T>(
  run: () => Promise<T>,
  ctx: {
    unitId: string | null;
    checkIn: string;
    checkOut: string;
    /**
     * Бронь, яку ПЕРЕНОСЯТЬ, — сама собі не заважає.
     *
     * Поля немає в контракті задачі, і воно навмисно НЕобовʼязкове: місця
     * виклику, написані проти опублікованого контракту, лишаються робочими.
     * Без нього ж `UPDATE`, що зсуває дати наявної броні, знайшов би в базі
     * сам себе і відмовив — на Postgres такого не буває (рядок не
     * перетинається сам із собою), і SQLite почав би забороняти те, чого
     * Postgres не забороняє.
     */
    reservationId?: string | null;
  },
): Promise<T> {
  if (ctx.unitId === null) return run();

  const sql = getSql();
  const attempt = async (): Promise<T> => {
    try {
      return await run();
    } catch (err) {
      if (isOverlapViolation(err)) {
        throw new UnitOverlap(ctx.unitId as string, ctx.checkIn, ctx.checkOut);
      }
      throw err;
    }
  };

  // Postgres: тримає обмеження, серіалізувати нема чого — писачі йдуть
  // паралельно, і відмовляє база.
  if (sql.dialect.name !== 'sqlite') return attempt();

  const guarded = async (): Promise<T> => {
    const taken = await stayOverlapsExisting(sql, {
      unitId: ctx.unitId as string,
      checkIn: ctx.checkIn,
      checkOut: ctx.checkOut,
      excludeReservationId: ctx.reservationId ?? null,
    });
    if (taken) throw new UnitOverlap(ctx.unitId as string, ctx.checkIn, ctx.checkOut);
    return attempt();
  };

  // Черга: наступна пара «перевірка + запис» починається лише після
  // попередньої. `catch` на хвості — щоб відмова одного писача не отруїла
  // чергу для наступних.
  const mine = sqliteQueue.then(guarded, guarded);
  sqliteQueue = mine.catch(() => undefined);
  return mine;
}
