/**
 * Фільтри списку броней, які не зводяться до однієї колонки (Блок 4 §2.5).
 *
 * Джерело форми — Hoteliera, «Reservations · Filter»: «Show conflicting
 * reservations», «Reservations canceled by the client», «Sort by».
 *
 * Чому окремий файл, а не ще три рядки в хендлері: обидва фільтри — це
 * ТВЕРДЖЕННЯ про дані, а не звуження по значенню. «Конфліктна» означає
 * «двом бронням продано одну кімнату на одну ніч», «скасована клієнтом» —
 * «скасування прийшло не з нашої стійки». Обидва можна порахувати
 * неправильно так, що це нічого не зламає й нічого не скаже: список просто
 * покаже інші рядки. Тому вони живуть тут і мають запускну сцену
 * (`list-filters.check.ts`).
 *
 * Фрагменти самодостатні: усе, що їм треба, вони беруть підзапитом від
 * `r`. Сцена підставляє їх у власний `SELECT` дослівно — інакше перевірявся
 * б не той SQL, що працює в проді.
 */

/**
 * «Показати конфліктні» живе НЕ тут, а в `conflicts.repo.ts`, поруч із
 * вартою перенесення: обидва питання — «чи можна сюди стати» і «хто вже
 * стоїть удвох» — це одне знання (півінтервал і статуси, що звільняють
 * кімнату), і два його описи розійшлися б мовчки. Саме це ловить
 * `check-availability-source`, і саме тому цей файл до `reservations` із
 * перетином дат не ходить.
 */
export { CONFLICTING_SQL } from './conflicts.repo';

/**
 * Скасована НЕ нашою стійкою.
 *
 * Хто скасував — уже записано: журнал броні (`booking_activity_log`) від
 * 03.09.2026 називає автора кожної зміни, і скасування з каналу лягає
 * окремою дією `channel_cancelled` (гість натиснув «скасувати» в OTA), тоді
 * як скасування рецепцією — це `status_change` від людини з сесією. Тому
 * колонки `cancelled_by` тут немає: вона дублювала б журнал і розійшлася б
 * із ним при першому ж писачі, який про неї забуде.
 *
 * Межа чесності: скасування з каналу ДО 03.09.2026 сліду не лишили, і цей
 * фільтр їх не покаже. Це «ми не знаємо», а не «скасував готель».
 */
export const CANCELLED_BY_CLIENT_SQL = `
  r.status = 'cancelled'
  AND EXISTS (
    SELECT 1 FROM booking_activity_log l
     WHERE l.reservation_id = r.id AND l.action = 'channel_cancelled'
  )`;

/**
 * Сортування списку: за чим і в який бік.
 *
 * Білий список, а не рядок із запиту: `ORDER BY` не приймає параметра, тож
 * значення з URL, підставлене в SQL, — це ін'єкція з парадного входу.
 * Невідоме поле — дефолт, а не помилка: посилання зі старим параметром має
 * показати список, а не 400.
 */
export const RESERVATION_SORTS = {
  check_in: 'r.check_in',
  check_out: 'r.check_out',
  created_at: 'r.created_at',
} as const;

export type ReservationSort = keyof typeof RESERVATION_SORTS;

export function orderByClause(sort: string | null | undefined, dir: string | null | undefined): string {
  const column = RESERVATION_SORTS[(sort ?? '') as ReservationSort] ?? RESERVATION_SORTS.check_in;
  const direction = String(dir ?? '').toLowerCase() === 'desc' ? 'DESC' : 'ASC';
  // Друга колонка — щоб порядок був відтворюваним: без неї дві броні з
  // однією датою міняються місцями від запиту до запиту, і рецепція бачить,
  // як рядок «стрибає» після кожного оновлення.
  return ` ORDER BY ${column} ${direction}, r.id ASC`;
}
