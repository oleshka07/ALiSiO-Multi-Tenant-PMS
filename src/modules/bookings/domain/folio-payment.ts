/**
 * Оплата з фоліо і бронь: коли рахунок закриває бронь і коли старий
 * (legacy) документ НЕ виписується (рецензія 07.09, п.1).
 *
 * Два шляхи документа жили поруч: оплата з фоліо ставила
 * `payment_status = 'paid'`, а генеричний PATCH на це слово виписував
 * legacy-фактуру серії HOUSE на `total_price`; потім «Виставити документ» з
 * фоліо давав другий номер на ту саму суму. Правило тут одне для обох сторін
 * PATCH-у й перевіряється без бази.
 */

/** Способи оплати, які означають «гроші прийшли через фоліо». */
export const FOLIO_PAYMENT_METHODS = ['folio', 'folio_cash'] as const;

/**
 * Чи має PATCH зі статусом `paid` виписати legacy-документ.
 * Оплата з фоліо — ні: документ виставляє фоліо, і він там рівно один.
 */
export function legacyInvoiceWanted(body: { payment_status?: unknown; payment_method?: unknown }): boolean {
  if (body.payment_status !== 'paid') return false;
  return !(FOLIO_PAYMENT_METHODS as readonly string[]).includes(String(body.payment_method ?? ''));
}

export interface SettleSummary {
  totals?: {
    charged?: number | string | null;
    paid?: number | string | null;
    balance?: number | string | null;
  } | null;
  folios?: {
    items?: { kind?: string | null }[];
    /** Рядки оплат, включно зі зустрічними (відʼємними). */
    payments?: unknown[];
  }[] | null;
}

/**
 * Чи закриває фоліо бронь як оплачену.
 *
 * Не лише «залишок ≤ 0»: без рядка проживання (`lodging`) оплата за воду
 * закрила б бронь як `paid` — і варта заселення пустила б гостя, який за
 * ніч не платив. Отже: є що платити, є нарахування проживання, і борг нуль.
 */
export function folioSettlesStay(summary: SettleSummary | null | undefined): boolean {
  return statusFromFolio(summary) === 'paid';
}

/**
 * Статус оплати броні З ФОЛІО — одна функція для всіх, хто його рахує (В3).
 *
 * Фоліо — єдина книга проживання: скільки за бронь заплачено, знає воно, а не
 * слово в `reservations.payment_status` і не сума `fin_operations` поруч. Дві
 * книги, які не знають одна про одну, вже дали видиму розбіжність: бронь,
 * оплачена половиною через фоліо, у фільтр «частково» не потрапляла взагалі,
 * а бронь зі станом `partial` показувала на виселенні ПОВНИЙ борг.
 *
 * Три відповіді, і `null` — теж відповідь:
 *   - `paid`    — нараховано ПРОЖИВАННЯ і борг закритий;
 *   - `partial` — гроші прийшли, а бронь не закрита (нарахування при цьому
 *                 може ще й не бути: завдаток до «нарахувати проживання» —
 *                 найчастіший потік, і саме він раніше мовчав);
 *   - `unpaid`  — гроші в книзі БУЛИ і їх не стало: зустрічний рядок зняв
 *                 помилковий платіж, а нарахування лишилось;
 *   - `null`    — книга нічого не каже, і слово броні лишається як стояло.
 *
 * Умова про проживання лишається ЛИШЕ на `paid`, і це не симетрія заради
 * симетрії: сплачена вода не має закривати бронь, бо варта заселення пустила
 * б гостя, який за ніч не платив. А от «частково» від сплаченої води —
 * правда.
 *
 * `null` НЕ означає «не оплачено»: він означає «фоліо не має що сказати», і
 * писач лишає слово, яке стояло.
 */
export function statusFromFolio(summary: SettleSummary | null | undefined): 'paid' | 'partial' | 'unpaid' | null {
  const charged = Number(summary?.totals?.charged ?? 0);
  const balance = Number(summary?.totals?.balance ?? 0);
  const paid = Number(summary?.totals?.paid ?? 0);
  if (!(paid > 0)) {
    // Гроші в книзі БУЛИ і їх не стало — це «не оплачено», не мовчання.
    // Мовчання тут лишало застаріле слово: видалення платежу писало у фоліо
    // зустрічний рядок, книга обнулялась, а бронь далі стояла `paid` (Р8.7) —
    // гроші зникли з обох книг, а слово про них лишилось.
    //
    // Але саме нарахування такого права не дає (Р10.9). Нараховане проживання
    // без жодного рядка оплати — це нормальний стан половини системи: бронь,
    // якій виставили рахунок і чекають переказу, має слово `payment_requested`,
    // поставлене людиною; готель на DE без TSE не тримає у фоліо готівки
    // ВЗАГАЛІ, тож там це стан ПОСТІЙНИЙ. Перерахунок, який у цих випадках
    // ставить `unpaid`, не виводить слово з книги — він стирає те, що людина
    // сказала, і робить це на кожному дотику до броні.
    //
    // Отже: рахуються не гроші, а РУХ. Є рядки оплат, а сума їх нуль чи менше —
    // рух був і його скасовано, слово `unpaid` правдиве. Рядків немає — книга
    // про оплату не каже нічого.
    const everMoved = (summary?.folios ?? []).some((f) => (f.payments ?? []).length > 0);
    return (charged > 0 && everMoved) ? 'unpaid' : null;
  }
  const hasLodging = (summary?.folios ?? []).some((f) => (f.items ?? []).some((i) => i.kind === 'lodging'));
  // «Оплачено» вимагає нарахованого ПРОЖИВАННЯ і закритого боргу. Без нього
  // сплачена вода закрила б бронь, і варта заселення пустила б гостя, який за
  // ніч не платив.
  if (hasLodging && balance <= 0) return 'paid';
  // Гроші прийшли, а бронь не закрита — «частково». Умови про нарахування тут
  // НЕМАЄ навмисно: рецепція, що взяла завдаток і не натискала «нарахувати
  // проживання», — найчастіший потік, і саме він мовчав. Бронь не потрапляла у
  // фільтр «частково» взагалі, тобто головна обіцянка В3 не виконувалась там,
  // де вона потрібна найбільше.
  return 'partial';
}
