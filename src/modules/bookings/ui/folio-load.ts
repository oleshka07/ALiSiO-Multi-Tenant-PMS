/**
 * Чому фоліо не завантажилось — одне рішення на всі екрани.
 *
 * ── Звідки правило ──────────────────────────────────────────────────────
 *
 * Вкладка «Фінанси» картки броні показувала на місці рахунку гостя червону
 * картку «Не вдалося завантажити · Спробувати ще раз». Код був такий:
 *
 *   const res = await fetch('/api/finance/folios?…&summary=1');
 *   if (!res.ok) { setFailed(true); return; }
 *
 * `res.status` не згадано ніде. А відмов у цього маршруту ТРИ, і вони про
 * зовсім різні речі:
 *
 *   403 + code FEATURE_DISABLED — у готелю ВИМКНЕНО модуль фактурування;
 *   403 + code FORBIDDEN        — у цієї ролі немає права `manage_documents`;
 *   401                          — сесія скінчилась;
 *   решта                        — справді поломка.
 *
 * Перші три — це НАЗВАНІ відмови, кожна зі своєю дією для людини: увімкнути
 * модуль, попросити право, увійти знову. Показувати їх як «щось зламалось,
 * спробуйте ще раз» — це порада, яка ніколи не спрацює: кнопка «ще раз»
 * повторить те саме 403 стільки разів, скільки її натиснуть.
 *
 * Той самий клас, що `payment-outcome` поруч: сервер склав правильну
 * відповідь, екран її викинув.
 *
 * ── Межа модуля ─────────────────────────────────────────────────────────
 *
 * Тут КЛАСИФІКАЦІЯ, не текст: речення пишуться на екрані під `tUi()`,
 * інакше модуль почав би вирішувати ще й мову. І класифікація питає КОД
 * відповіді, а не її речення: «Feature "invoicing" is not enabled» —
 * англійський рядок для розробника, і будувати на ньому розгалуження
 * означало б стерегти візерунок замість властивості (AGENTS §3.2.1).
 */

/** Чим закінчилось читання фоліо — для ока портьє, не для логіки грошей. */
export type FolioLoadOutcome =
  /** Відповідь є, її можна показувати. */
  | { kind: 'ok' }
  /** Модуль фактурування вимкнений цьому готелю. Дія — увімкнути, не «ще раз». */
  | { kind: 'module_off'; feature: string | null }
  /** Роль без права `manage_documents`. Дія — попросити право. */
  | { kind: 'denied' }
  /** Сесія скінчилась. Дія — увійти знову. */
  | { kind: 'signed_out' }
  /** Усе інше: це справді поломка, і «спробувати ще раз» тут доречно. */
  | { kind: 'error'; status: number };

/** Те, що маршрут кладе в тіло. Усі поля необовʼязкові навмисно. */
export interface FolioLoadBody {
  code?: unknown;
  feature?: unknown;
  error?: unknown;
}

const str = (v: unknown): string | null =>
  typeof v === 'string' && v.trim() ? v.trim() : null;

/**
 * `status` — код відповіді, `body` — розібране тіло (або `null`, якщо тіла
 * немає чи воно не JSON: відмова без тіла лишається відмовою).
 */
export function folioLoadOutcome(status: number, body: FolioLoadBody | null): FolioLoadOutcome {
  if (status >= 200 && status < 300) return { kind: 'ok' };
  if (status === 401) return { kind: 'signed_out' };
  if (status === 403) {
    // Код, а не речення. `featureDisabled` називає ще й КЛЮЧ модуля — його
    // видно оператору, бо «вимкнено фактурування» і «вимкнено облік» це різні
    // розмови з різними людьми.
    if (str(body?.code) === 'FEATURE_DISABLED') {
      return { kind: 'module_off', feature: str(body?.feature) };
    }
    return { kind: 'denied' };
  }
  return { kind: 'error', status };
}
