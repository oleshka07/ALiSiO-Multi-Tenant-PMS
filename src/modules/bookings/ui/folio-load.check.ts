/**
 * Три різні відмови фоліо не зливаються в одну.
 *
 *   node src/modules/bookings/ui/folio-load.check.ts
 *
 * ── Дефект, проти якого це написано ─────────────────────────────────────
 *
 * `if (!res.ok) { setFailed(true); return; }` — і рахунок гостя показував
 * «Не вдалося завантажити · Спробувати ще раз» однаково на вимкненому
 * модулі, на браку права і на справжній поломці. Кнопка «ще раз» на 403
 * повторює те саме 403 нескінченно.
 *
 * ── Осі, по яких фікстура не вироджена (інваріант 26) ───────────────────
 *
 * 1. ДВА різні 403 — з кодом модуля і без нього. З одним 403 твердження
 *    зелене й на читачі, який каже «будь-яке 403 — немає прав»: саме таким
 *    був перший варіант цього модуля, і саме на цій парі він почервонів.
 * 2. 401 окремо від 403: «увійдіть знову» і «попросіть право» — різні дії.
 * 3. Успіх і поломка на кінцях: 200 не вважається відмовою, 500 не
 *    вважається названою.
 * 4. Тіло, якого немає (відмова проксі без JSON) — не має валити класифікацію.
 */
import assert from 'node:assert';
import { folioLoadOutcome } from './folio-load.ts';

const fails: string[] = [];
const say = (cond: boolean, what: string) => {
  if (cond) console.log(`  ok  ${what}`);
  else { fails.push(what); console.log(`  ЧЕРВОНЕ  ${what}`); }
};

// ── 1. Успіх ─────────────────────────────────────────────────────────────
say(folioLoadOutcome(200, null).kind === 'ok', '200 — це відповідь, а не відмова');

// ── 2. Вимкнений модуль ──────────────────────────────────────────────────
const off = folioLoadOutcome(403, { code: 'FEATURE_DISABLED', feature: 'invoicing' });
say(off.kind === 'module_off', `вимкнений модуль названо своїм родом (${off.kind})`);
say(off.kind === 'module_off' && off.feature === 'invoicing',
  'і сказано ЯКИЙ модуль — «вимкнено фактурування» та «вимкнено облік» це різні розмови');

// ── 3. Немає права — ІНШИЙ рід при тому самому коді відповіді ────────────
//
// Пара, задля якої існує цей гейт: обидві відмови 403, і читач, який дивиться
// лише на статус, зіллє їх в одну.
const denied = folioLoadOutcome(403, { code: 'FORBIDDEN', error: 'Недостатньо прав' });
say(denied.kind === 'denied', `брак права — окремий рід (${denied.kind})`);
say(off.kind !== denied.kind,
  'два різні 403 дають РІЗНІ роди — інакше екран порадить «спробувати ще раз» там, де треба увімкнути модуль');

// ── 4. Сесія скінчилась ──────────────────────────────────────────────────
say(folioLoadOutcome(401, null).kind === 'signed_out', '401 — увійти знову, а не «немає прав»');

// ── 5. Справжня поломка ──────────────────────────────────────────────────
const broken = folioLoadOutcome(500, { error: 'Failed' });
say(broken.kind === 'error', `500 — поломка (${broken.kind})`);
say(broken.kind === 'error' && broken.status === 500,
  'і код відповіді доїжджає до екрана: «спробувати ще раз» доречне лише тут');

// ── 6. Відмова без тіла ──────────────────────────────────────────────────
//
// Проксі або мережа можуть віддати 403 узагалі без JSON. Це все ще відмова
// доступу, а не поломка, і класифікація не має падати на розборі.
say(folioLoadOutcome(403, null).kind === 'denied', '403 без тіла — усе одно відмова доступу');
say(folioLoadOutcome(403, { code: 42 as never }).kind === 'denied',
  'код не-рядком не приймається за назву модуля');

// Тип відповіді — не «щось із kind»: помилка в написанні роду має падати тут,
// а не мовчки малювати порожню картку.
assert.ok(['ok', 'module_off', 'denied', 'signed_out', 'error']
  .includes(folioLoadOutcome(418, null).kind), 'невідомий статус дав рід поза переліком');

if (fails.length) { console.error(`\nfolio-load: ${fails.length} червоних`); process.exit(1); }
console.log('folio-load: три відмови фоліо різні, і «спробувати ще раз» лишається тільки поломці');
