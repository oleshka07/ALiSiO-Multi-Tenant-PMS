/**
 * Чим САМЕ закінчився прийом оплати — одне рішення на всі екрани.
 *
 * ── Звідки правило ──────────────────────────────────────────────────────
 *
 * Портьє на беті взяв 200 EUR готівкою, натиснув «Прийняти оплату», побачив
 * «Платіж додано!» — і нічого не змінилось: вартість 200, сплачено 0. Сервер
 * при цьому відповів 409 і бездоганним реченням: «У готелю немає активного
 * рахунку в EUR, тож готівку нема куди записати. Додайте касу: Фінанси →
 * Рахунки…». Екран це речення викинув.
 *
 * Код був такий, і він однаковий у двох файлах:
 *
 *   const data = await res.json().catch(() => ({}));
 *   const msg = data?.kind === 'marker' ? '…позначка…' : 'Платіж додано!';
 *
 * `res.ok` не згадано ніде. Тобто ЄДИНИЙ спосіб не побачити «Платіж додано!»
 * — щоб сервер назвався маркером. Відмова, помилка, частковий запис — усе це
 * зводилось до підтвердження. Гроші з рук гостя взято, у системі нуль рядків,
 * на екрані успіх.
 *
 * `check-unread-write-response` це пропускає, і чесно каже чому у власній
 * шапці: «бачить „результат звʼязано“, а не „результат осмислено прочитано“».
 * Тут результат справді звʼязано — прочитано лише не той бік.
 *
 * ── Чому окремим модулем, а не двома правками на місці ──────────────────
 *
 * Екранів два (`BookingViewModal`, `MobileBookingDetail`), і вони вже мали
 * ОДНАКОВУ ваду слово в слово: портьє з планшета і портьє з телефона бачили
 * одну й ту саму неправду. Дві правки на місці означали б два рішення, які
 * розійдуться при першій же новій формі відповіді. Тут воно одне, і його
 * можна ПЕРЕВІРИТИ — інваріант 16 у своєму дусі: питає один.
 *
 * ── Межа модуля ─────────────────────────────────────────────────────────
 *
 * Тут КЛАСИФІКАЦІЯ, не текст. Речення, які пишемо ми, лишаються на екрані під
 * `tUi()` — інакше модуль почав би вирішувати ще й мову. Речення, які пише
 * СЕРВЕР (названа відмова, попередження про фоліо), їдуть полем `message`
 * дослівно: їх уже склали там, де відома причина.
 */

/** Чим закінчився POST /api/payments — для ока портьє, не для логіки грошей. */
export type PaymentOutcome =
  /** Сервер відмовив. `message` — його власне речення, показати дослівно. */
  | { kind: 'refused'; message: string | null }
  /** Не готівка: позначка статусу, грошей не рухали. */
  | { kind: 'marker' }
  /** Гроші лягли і в касу, і в рахунок гостя. */
  | { kind: 'recorded' }
  /**
   * Гроші в касі, у рахунку гостя — НІ. Це не збій запиту, а факт, який
   * мусить дійти до людини: німецький обʼєкт без `fiscal_de` не пускає
   * готівку у фоліо навмисно, і для цілого сегмента це постійний стан.
   * Мовчазне розходження двох книг — саме те, чого не можна (інваріант 13).
   */
  | { kind: 'recorded_not_in_folio'; message: string | null; reason: string | null };

/** Те, що маршрут кладе в тіло відповіді. Усі поля необовʼязкові навмисно. */
export interface PaymentResponseBody {
  kind?: unknown;
  error?: unknown;
  message?: unknown;
  folioRecorded?: unknown;
  folioRefusal?: unknown;
}

/** Рядок або `null` — щоб число, обʼєкт чи `undefined` не поїхали в тост. */
function text(v: unknown): string | null {
  return typeof v === 'string' && v.trim() !== '' ? v : null;
}

/**
 * Судити за ВІДПОВІДДЮ, а не за здогадом.
 *
 * `ok` — це `res.ok`, і він тут перший аргумент саме тому, що забути його не
 * можна: без нього функцію не викликати.
 *
 * Тіло може бути будь-чим (`res.json()` на 502 від проксі кидає, і виклична
 * сторона віддає `{}`), тож жодне поле не вважається наявним.
 */
export function paymentOutcome(ok: boolean, body: PaymentResponseBody | null): PaymentOutcome {
  const b = body ?? {};

  // Відмова — ПЕРШОЮ і за статусом, а не за вмістом тіла. Названа відмова
  // (`refuse`) кладе своє речення в `error`; якщо тіла немає взагалі,
  // `message: null` каже екрану показати власне запасне речення.
  if (!ok) return { kind: 'refused', message: text(b.error) };

  if (b.kind === 'marker') return { kind: 'marker' };

  // `=== false`, не `!b.folioRecorded`: поля може не бути (старий клієнт,
  // маркерний шлях), і відсутність — це не «фоліо відмовило».
  if (b.folioRecorded === false) {
    return {
      kind: 'recorded_not_in_folio',
      message: text(b.message),
      reason: text(b.folioRefusal),
    };
  }

  return { kind: 'recorded' };
}
