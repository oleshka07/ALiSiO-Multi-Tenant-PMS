/**
 * Гроші, зняті з фінансової книги, знімаються і з книги гостя (Р8.7) —
 * але тільки ті, які ця операція туди й поклала (Р10.6).
 *
 * Фоліо — єдина книга проживання (В3), але каса пише в обидві: рядок
 * `fin_operations` і платіж у фоліо. Видалення чистило лише першу, і
 * «видалено» переставало означати «повернено»:
 *
 *   рецепція видаляє помилковий платіж → рядок `fin_operations` зник →
 *   спільний перерахунок читає ФОЛІО, бачить там ті самі гроші → бронь
 *   лишається `paid`, виселення відчинене, а грошей уже ніде немає.
 *
 * Помилки не буває ніде: обидві книги «працюють», просто кажуть різне.
 *
 * ЗВОРОТНА ДІРА, яку відкрила перша редакція цього файла: реверс знімав із
 * фоліо будь-який дохід із `reservation_id`, а відрізнити свій платіж від
 * чужого не міг — `source` не розрізняє, місток теж пише `'manual'`. Гість
 * платить 5000 готівкою, бухгалтер заводить у Фінансах помилкові 1200 по цій
 * броні (у книгу гостя вони, за Д21, не лягають), видаляє їх — і реверс
 * забирає 1200 З ГРОШЕЙ ГОСТЯ. Пара була асиметрична: створення у фоліо не
 * додає, видалення знімає.
 *
 * Тепер операція НЕСЕ посилання на рядок, який поклала (`folio_payment_id`,
 * міграція 0096). Немає посилання — у книзі гостя ця операція нічого не
 * робила, і видалення її звідти нічого не знімає.
 *
 * Файл навмисно ЛИСТКОВИЙ — лише двері фасадів, жодного імпорту з
 * `operations.handlers` чи `payment-bridge`. Обидва кличуть його, і якби
 * правило жило в одному з них, другий отримав би цикл імпортів; а копія
 * правила у двох місцях — це рівно те, з чого почався В3.
 *
 * Тримає `scripts/check-payment-delete.mjs --strict`.
 */
import { reverseFolioPayment } from '@invoicing/kernel';
import { recalcPaymentStatusFromFolio } from '@bookings/kernel';

/** Те, що треба знати про видалену операцію, і нічого більше. */
export interface DeletedOperation {
  reservation_id?: string | null;
  /** Рядок книги гостя, який створила ЦЯ операція; порожньо — не створювала. */
  folio_payment_id?: string | null;
  op_type?: string | null;
}

/**
 * Зняти з книги гостя рядок видаленої операції і перерахувати слово броні.
 *
 * Кличеться ПІСЛЯ видалення операції: зустрічний рядок обмежений тим, що
 * книга справді тримає, тож повторний виклик не знімає вдруге.
 *
 * Операція без броні (звичайна витрата у Фінансах) не має книги гостя, а
 * операція без `folio_payment_id` у ній нічого не клала — обидві тихо
 * проходять повз реверс. Це не пропущені випадки: у першої немає гостя, у
 * другої немає що знімати.
 *
 * Свідомо не зроблено: видалення ПОВЕРНЕННЯ (`op_type = 'expense'`) не
 * повертає гроші у фоліо назад. Зустрічний рядок уміє лише зменшувати
 * сплачене, а додати позитивний платіж «бо колись було повернення» означало б
 * вигадати гроші, яких у книзі може вже не бути. Слово броні при цьому
 * перераховується — фоліо лишається джерелом, і розбіжність видно.
 */
export async function reverseOperationInFolio(op: DeletedOperation | null | undefined): Promise<void> {
  const reservationId = op?.reservation_id;
  if (!reservationId) return;
  const folioPaymentId = op?.folio_payment_id;
  if (folioPaymentId && op?.op_type === 'income') {
    await reverseFolioPayment(String(folioPaymentId)).catch((e: unknown) => {
      // Книга гостя могла відмовити законно (німецький обʼєкт без `fiscal_de`
      // не тримає там готівки взагалі). Мовчати не можна — інваріант 13, — але
      // й валити видалення вже видаленого рядка теж.
      console.warn(`[folio-reversal] фоліо не прийняло зустрічний рядок за ${String(reservationId)}: ${(e as Error)?.message}`);
    });
  }
  await recalcPaymentStatusFromFolio(String(reservationId));
}
