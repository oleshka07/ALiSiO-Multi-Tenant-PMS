/**
 * Рід житла — вісь рахунку вендора. Дві групи РОЗБИВАЮТЬ множину.
 *
 *   node src/modules/channels/channex/property-type.check.ts
 *
 * ── Що стережеться і чому саме це ───────────────────────────────────────
 *
 * Лист вендора 09.09.2026 (`docs/vendor/channex/billing-2026-09-09.md`):
 * рахунок іде за `property_type` — готельна група за обʼєкт, оренда за
 * юніт. Тобто рід житла це гроші готелю, а не косметика каталогу, і
 * помилка тут МОВЧИТЬ: неправильний рід дає неправильний рахунок доти,
 * доки хтось не звірить виписку з переліком (інваріант 29 — строгість
 * пропорційна ціні помилки).
 *
 * ── Властивість, а не перелік (AGENTS §3.2.1) ───────────────────────────
 *
 * Спокуса тут — переписати 22 рядки з листа і звірити рівність. Такий гейт
 * стереже ВІЗЕРУНОК: він ловить лише те, що автор уже уявив, а насправді
 * оберігає копію листа від самої себе. Тому твердження — про РОЗБИТТЯ:
 *
 *   1. кожен рід житла з ядра має групу (жодного без);
 *   2. жоден не має двох (наслідок `Record`, але перевіряється значенням:
 *      група мусить бути ОДНИМ із двох відомих імен, а не будь-чим);
 *   3. обʼєднання груп = рівно множина `TO_CHANNEX`, ні більше ні менше;
 *   4. групи НЕ ПОРОЖНІ й не збігаються — інакше «розбиття» задовольнялось
 *      би тим, що всі 22 в одній групі, а це рівно та помилка, яка коштує
 *      рахунку.
 *
 * Числа 14 і 8 звіряються ОКРЕМИМ твердженням і саме як число з листа —
 * не як «скільки вийшло». Це друга вісь: розбиття лишається розбиттям,
 * навіть якщо перенести `camping` з готельної групи в оренду, а таке
 * перенесення — зміна рахунку кожного кемпінгу.
 */
import assert from 'node:assert';
// Аліаси й розширення для голого node — як у сусідніх гейтах теки.
import '../../../../scripts/lib/module-aliases.mjs';

const { LODGING_KINDS } = await import('@core/lodging-kinds');
const {
  channexBillingGroup,
  lodgingKindsInBillingGroup,
  channexPropertyType,
} = await import('./property-type.ts');

const GROUPS = ['hotel', 'vacation_rental'] as const;

// ── 1. Кожен рід має групу, і вона одна з двох відомих ───────────────────
const ungrouped = LODGING_KINDS.filter((k) => channexBillingGroup(k) === null);
assert.deepStrictEqual(
  ungrouped, [],
  `рід житла без групи тарифікації: ${ungrouped.join(', ')} — вендор виставить за нього рахунок, `
  + 'а за яким тарифом, не знає ніхто',
);

const strange = LODGING_KINDS.filter((k) => !GROUPS.includes(channexBillingGroup(k) as never));
assert.deepStrictEqual(
  strange, [],
  `рід житла з невідомою групою: ${strange.join(', ')}`,
);
console.log('  ok  кожен рід житла має рівно одну групу, і вона з відомих двох');

// ── 2. Обʼєднання груп = множина, яку приймає вендор ─────────────────────
//
// Звіряється проти `channexPropertyType`, а не проти власного списку: якщо
// колись рід перестане мапитись у вендорське значення, розбиття мусить це
// помітити, а не лишитись правдою про порожнечу.
const union = [...GROUPS.flatMap((g) => lodgingKindsInBillingGroup(g))].sort();
const mapped = LODGING_KINDS.filter((k) => channexPropertyType(k) !== null).sort();
assert.deepStrictEqual(
  union, [...mapped],
  'обʼєднання груп не збігається з тим, що вендор приймає — хтось із двох переліків відстав',
);
assert.strictEqual(
  new Set(union).size, union.length,
  'рід житла потрапив у ОБИДВІ групи — рахунок за нього неоднозначний',
);
console.log(`  ok  обʼєднання груп = ${union.length} родів, які вендор приймає, без перетину`);

// ── 3. Розбиття НЕ вироджене ─────────────────────────────────────────────
//
// Без цього «всі 22 в готельній групі» задовольнило б усе вище — і саме це
// найдорожча з можливих помилок: кожен апартамент рахувався б як готель.
for (const g of GROUPS) {
  assert.ok(
    lodgingKindsInBillingGroup(g).length > 0,
    `група ${g} порожня — розбиття вироджене, і одна зі сторін рахунку зникла`,
  );
}
console.log('  ok  жодна з двох груп не порожня');

// ── 4. Числа з листа, поіменно ───────────────────────────────────────────
//
// Друга вісь: розбиття лишається розбиттям і після переносу роду з групи в
// групу, а такий перенос — зміна рахунку кожного готелю цього роду.
assert.strictEqual(
  lodgingKindsInBillingGroup('hotel').length, 14,
  'у готельній групі не 14 родів — звірте з листом вендора 09.09.2026',
);
assert.strictEqual(
  lodgingKindsInBillingGroup('vacation_rental').length, 8,
  'у групі оренди не 8 родів — звірте з листом вендора 09.09.2026',
);
// Два роди, які лист називає рекомендованими, — по одному з кожної групи.
// Якщо переставити саме їх, числа вище лишаться правильними.
assert.strictEqual(channexBillingGroup('hotel'), 'hotel');
assert.strictEqual(channexBillingGroup('apartment'), 'vacation_rental');
assert.strictEqual(channexBillingGroup('camping'), 'hotel', 'кемпінг рахується як обʼєкт, не як юніт');
assert.strictEqual(channexBillingGroup('villa'), 'vacation_rental', 'вілла рахується за юніт');
console.log('  ok  14 і 8 як у листі, і рекомендовані роди в тих групах, що названі');

// ── 5. Рід поза переліком вендора групи не має ───────────────────────────
assert.strictEqual(
  channexBillingGroup('igloo'), null,
  'вигаданий рід дістав групу тарифікації — отже група вгадується, а не читається',
);
console.log('  ok  рід поза переліком вендора групи не має');

console.log('property-type: дві групи тарифікації розбивають множину родів житла, і жодна не порожня');
