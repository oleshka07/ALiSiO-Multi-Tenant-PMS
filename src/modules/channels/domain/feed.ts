/**
 * Бронювання з каналу в тому вигляді, як його бачить ДОМЕН.
 *
 * Це шов між адаптером і циклом. Адаптер (`../channex/`) читає чужий формат
 * і віддає ці типи; цикл (`../data/pull-bookings.ts`) працює лише з ними і
 * не знає імені вендора — інваріант И1.
 *
 * Шов саме тут, а не в циклі, з однієї причини: цикл — це порядок дій
 * (транзакція → коміт → підтвердження), і він однаковий для будь-якого
 * менеджера каналів. Переклад чужих полів однаковим не буває ніколи. Коли
 * ці двоє лежали в одному файлі, цикл імпортував адаптер — тобто домен
 * залежав від вендора, і гейт це справедливо назвав.
 *
 * ── Чому відмова — це теж запис стрічки ─────────────────────────────────
 *
 * `FeedEntry` — це або перекладене бронювання, або НАЗВАНА відмова. Не
 * виняток: виняток посеред стрічки лишив би решту необробленою, тобто одна
 * крива ревізія сховала б усі наступні броні. І не мовчазний пропуск:
 * пропущене без причини бронювання нікому не видно — ні в звіті, ні в
 * логах, ні оператору.
 */

/** Календарна дата, `YYYY-MM-DD`. */
export type DateStr = string;

/**
 * Одна кімната бронювання.
 *
 * Кімнат буває кілька: одне бронювання каналу з двома кімнатами — це дві
 * НАШІ броні, бо `reservations` це рядок на кімнату. Тому список, а не
 * перше значення: мовчки загублена друга кімната — це гість, який приїде в
 * готель, що про нього не знає.
 */
export interface FeedRoom {
  /** НАШ тип номера, або `null`, якщо тип не змаплено. */
  unitTypeId: string | null;
  checkIn?: DateStr;
  checkOut?: DateStr;
  adults: number;
  children: number;
  amount: number;
  /**
   * Ідентифікатор кімнати на боці OTA — якщо вона його взагалі дає.
   *
   * Це ЄДИНЕ, чим кімнату можна впізнати між редакціями, і дає його не кожен
   * канал: у менеджера каналів у кімнати бронювання власного `id` немає, а
   * редакція — знімок, який нічого не успадковує від попередньої. Тобто без
   * цього поля «та сама кімната» доводиться визначати позицією в списку.
   *
   * Порожньо там, де OTA його не дала. Тоді ключ групи будується позиційно —
   * див. `groupRoomKeys()`.
   */
  otaUniqueId?: string;
}

/**
 * Бронювання каналу, доставлене однією редакцією.
 *
 * Домен знає, що бронювання приїжджає редакціями і що редакції треба
 * розрізняти. Він НЕ знає, як вендор називає свій ендпоінт, які там поля і
 * яким запитом підтверджується прийом — це все за швом.
 */
export interface FeedRevision {
  /** Змінюється з кожною редакцією. За ним відсікаємо повтори (CP4). */
  remoteRevisionId: string;
  /**
   * Чим підтверджується прийом ЦІЄЇ редакції.
   *
   * Окреме поле, а не `remoteRevisionId`, і це не надмірність. У менеджера
   * каналів на одну редакцію припадає два ідентифікатори: один він називає
   * ключем розпізнавання повторів, другим адресує саму редакцію. Обидва
   * унікальні на редакцію, тож обидва «працюють» — доки не доходить до
   * підтвердження, де правильний рівно один.
   *
   * Ціна підміни несиметрична й тиха з нашого боку: підтвердження летить у
   * нікуди (404), редакція НІКОЛИ не зникає зі стрічки, застосовується
   * щоразу заново — від дубля рятує тільки журнал — а готель кожні 30 хвилин
   * отримує лист про непідтверджену броню.
   *
   * Для домену це непрозорий рядок: він його не читає й не розбирає, а лише
   * повертає назад тому, хто його видав.
   */
  ackToken: string;
  /** Стабільний між редакціями. За ним шукаємо СВОЮ бронь. */
  remoteBookingId: string;
  status: 'new' | 'modified' | 'cancelled';
  /** Код брони в самій OTA — те, що гість називає по телефону. */
  otaReservationCode?: string;
  otaName?: string;
  currency?: string;
  totalAmount: number;
  /**
   * Хоча б одна кімната без змапленого типу.
   *
   * Таке бронювання все одно приймається: гість уже заплатив, воно фізично
   * існує, і відкинути його — значить створити овербукінг власноруч. Ознака
   * потрібна, щоб оператор побачив і домапив.
   */
  unmapped: boolean;
  rooms: FeedRoom[];
  /**
   * Гості БРОНЮВАННЯ, а не кімнати.
   *
   * У бронювання на кілька кімнат є власна заселеність поруч із заселеністю
   * кожної кімнати, і вони різні: три дорослі в двох кімнатах це `2 + 1`
   * усередині і `3` зверху. Батьківська бронь групи описує бронювання, тож
   * бере саме ці числа (К1); кімнати беруть свої.
   *
   * Порожньо, якщо менеджер каналів заселеності бронювання не назвав — тоді
   * її складають із кімнат.
   */
  adults?: number;
  children?: number;
  guestFirstName?: string;
  guestLastName?: string;
  guestEmail?: string;
  /** Сира відповідь менеджера каналів — доказ у суперечці. */
  raw: unknown;
}

/** Запис стрічки: перекладене бронювання або названа причина відмови. */
export type FeedEntry = { ok: true; revision: FeedRevision } | { ok: false; reason: string };

/**
 * Ключі кімнат редакції — чим кімната впізнається в НАСТУПНІЙ редакції.
 *
 * ── Чому це окрема функція, а не поле ───────────────────────────────────
 *
 * Редакція — повний знімок: «These snapshots do not inherit data from
 * previous revisions». Стабільного ідентифікатора в кімнати немає — є лише
 * `ota_unique_id`, і його дає не кожен OTA («right now only Booking.com
 * supported»). Тобто ключ виводиться з редакції ЦІЛКОМ, а не з кімнати
 * поодинці, і саме тому він тут.
 *
 * ── Пастка, виміряна живим 06.09.2026 ───────────────────────────────────
 *
 * У живій відповіді стрічки в кімнати Є поле `booking_room_id` — UUID,
 * якого немає в документації вендора взагалі. Виглядає воно рівно як той
 * стабільний ідентифікатор, якого тут бракує, і взяти його спокусливо.
 *
 * Воно НЕ стабільне. Контрольований дослід на власному обʼєкті staging —
 * одне бронювання, чотири редакції — дав чотири різні набори:
 *
 *   створення  `a8be62fa…`, `32bef75d…`
 *   зміна дат  `ecf4db0c…`, `98d64e87…`
 *   мінус одна `2517d4bb…`
 *   скасування `430a34f6…`
 *
 * Тобто `booking_room_id` іменує кімнату ВСЕРЕДИНІ редакції, а не саму
 * кімнату. Ключ із нього означав би нову дочірню бронь на кожну редакцію:
 * після трьох змін готель мав би вісім кімнат замість двох, і кожна зайняла
 * б номер. Мовчки — бо помилки не було б ніде.
 *
 * Там само виміряно, що `is_cancelled` кімнати завжди `false`: прибрана
 * кімната просто зникає зі списку, а не позначається. І що `ota_unique_id`
 * у броней Booking CRS порожній — тобто позиційна гілка нижче не рідкість,
 * а звичайний випадок усього, що не Booking.com.
 *
 * ── Правило: або всі, або позиції ───────────────────────────────────────
 *
 * Якщо `ota_unique_id` є в КОЖНОЇ кімнати — ключі з нього. Якщо бракує хоч
 * одній — позиції для ВСІХ. Мішанина заборонена навмисно: у редакції з
 * кімнатами `[u:49, i:1]` додавання третьої кімнати посередині зсуває `i:1`,
 * і дві кімнати обміняються рядками, поки третя виглядатиме новою.
 *
 * Префікс `u:`/`i:` — не косметика: `ota_unique_id` цілком може бути рядком
 * `"0"`, і без префікса він зіткнувся б із позицією нуль.
 *
 * ── Ціна позиційного ключа названа чесно ────────────────────────────────
 *
 * Коли кімнати впізнаються позицією, видалення ПЕРШОЇ з двох виглядає як
 * «друга зникла»: та, що лишилась, приїде на позиції нуль і ляже в рядок
 * першої. Тобто скасується не той рядок, який людина назвала б. Стан групи
 * при цьому правильний — типи, дати й суми беруться з редакції-знімка, —
 * неправильна лише спадковість рядка. Кращого з тим, що дає вендор, немає:
 * альтернатива — вгадувати за збігом типу й дат, а це неправда там, де дві
 * кімнати однакові.
 */
export function groupRoomKeys(rooms: readonly FeedRoom[]): string[] {
  const allNamed = rooms.length > 0 && rooms.every((r) => (r.otaUniqueId ?? '').trim() !== '');
  return rooms.map((r, i) => (allNamed ? `u:${(r.otaUniqueId ?? '').trim()}` : `i:${i}`));
}
