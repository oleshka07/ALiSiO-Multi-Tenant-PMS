'use client';

import { useT } from '@core/i18n/client';
import { billingBasisOf } from './billing-group';

/**
 * Що обраний рід житла означає для рахунку менеджера каналів.
 *
 * ── Навіщо це на екрані ─────────────────────────────────────────────────
 *
 * До листа вендора 09.09.2026 рід житла був «коректністю каталогу»: не
 * назвав — каталог не поїхав. Тепер він **вісь рахунку**: готельна група
 * тарифікується за обʼєкт, оренда — за юніт
 * (`docs/vendor/channex/billing-2026-09-09.md`). Помилка тут мовчить —
 * неправильний рід дає неправильний рахунок доти, доки хтось не звірить
 * виписку. Тому наслідок показується ДО того, як оператор натисне, а не
 * зʼясовується першого числа.
 *
 * ── Чому без сум ────────────────────────────────────────────────────────
 *
 * $7 і $0.50 змінюються без нас, а число на екрані застаріває мовчки — і
 * саме там, де людина ухвалює рішення про гроші. Тому називається ОСНОВА
 * («за обʼєкт» / «за кожен юніт»), а за сумою — до сторінки цін вендора.
 *
 * ── Чому компонент модуля, а не рядок на сторінці ───────────────────────
 *
 * Готель, який каналів не купував, не мусить бачити нічого про чужі тарифи.
 * Сторінка малює це лише під увімкненим модулем (`features.channels`), а сам
 * текст живе тут — у модулі, який його продає. Ядро про тарифи вендора не
 * знає й не має знати (`check-boundaries --strict`, друга вісь).
 */
export function LodgingBillingHint({ kind }: { kind: string | null | undefined }) {
  const t = useT();
  const basis = billingBasisOf(kind);

  // Рід не обрано або він поза переліком — сказати нічого, і вигадувати теж
  // нічого. Порожнечу тут пояснює підказка самого поля.
  if (!basis) return null;

  return (
    <div className="form-hint">
      {basis === 'per_property'
        ? t('Тарифікація каналу: за обʼєкт — один рахунок незалежно від кількості номерів.')
        : t('Тарифікація каналу: за кожен юніт — рахунок зростає з кількістю зданих одиниць.')}
    </div>
  );
}
