/**
 * Про що саме попереджає банер над списком броней.
 *
 * ── Чому список кодів, а не готові рядки ────────────────────────────────
 *
 * `/api/alerts` складав повідомлення сам: «Прострочений заїзд …», «Сьогодні
 * заїзд, оплата не завершена — …». Українською, у SQL-хендлері, без жодного
 * `t()`. Німецький портьє відкривав /app/bookings і бачив стіну українського
 * тексту — на першому ж екрані, який він відкриває сам.
 *
 * Перекласти це на місці не можна, і не з ліні: `check-i18n-leak` забороняє
 * `t()` під `src/app/api` навмисно. Мова оператора не сміє вирішувати, якою
 * мовою вийде документ чи лист гостю, а один `t()` у спільному хендлері —
 * саме той шлях, яким вона туди потрапляє.
 *
 * Тому API віддає КОД події й дані до неї, а рядок складає екран — там, де
 * мова оператора вже відома й де вона нікуди далі не тече. Назва номера й
 * дата не перекладаються: це дані готелю, а не текст.
 *
 * Список тут, а не в кожному з двох файлів, щоб сторона, яка додала новий
 * код, не могла тихо розійтися з тією, що його малює: за це відповідає
 * alerts.check.ts.
 */

export const ALERT_TYPES = [
  /** Заїзд у минулому, а бронь досі `confirmed`. Сім днів, далі — авто-no_show. */
  'overdue_arrival',
  /** Заїзд сьогодні, ціна нульова — промо, бартер або помилка; хтось має підтвердити. */
  'zero_price_arrival',
  /** Заїзд сьогодні, оплата не завершена. */
  'unpaid_arrival',
  /** Заїзд сьогодні, реєстрація не пройдена. */
  'unregistered_arrival',
  /** Уже заселений, а реєстрації немає — у DE/CZ це не дрібниця. */
  'checked_in_no_reg',
  /** Виїзд сьогодні, гість ще заселений. */
  'today_departure',
] as const;

export type AlertType = (typeof ALERT_TYPES)[number];

export type AlertSeverity = 'warning' | 'danger' | 'info';

export interface DashboardAlert {
  type: AlertType;
  severity: AlertSeverity;
  bookingId: string;
  guestName: string;
  /** Назва номера. Дані готелю — не перекладається. */
  unitName: string;
  /** Тільки для `overdue_arrival`: дата, якою заїзд мав відбутися. */
  checkIn?: string;
}
