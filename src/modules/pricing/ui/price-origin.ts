/**
 * Підписи джерел ціни — те, що оператор читає під числом.
 *
 * Живе в `ui/` навмисно: екран цін бере це через дозволені двері модуля
 * (`modules/<x>/ui/`), а не імпортом нутрощів — так само, як `day-edit.ts`.
 * Ключ рахує сервер (`monthOrigins` → `priceNights`); тут лише переклад
 * ключа в слово, без жодної логіки про те, яке джерело виграє.
 */
import type { PriceOrigin } from '../domain/day-price';

export type { PriceOrigin };

export const ORIGIN_LABELS: Record<PriceOrigin, string> = {
  rate_plan: 'ціна тарифу',
  rate_plan_weekend: 'ціна вихідних тарифу',
  matrix: 'матриця заселеності',
  unit_type: 'базова ціна',
  unit_type_weekend: 'ціна вихідних',
};

/** День сітки в тому вигляді, у якому його віддає `GET /api/pricing`. */
export interface PricingDayCell {
  /** Число рядка календаря — те, що редагує модалка дня. */
  effective_price: number | null;
  /**
   * Скільки коштує ця ніч гостю і звідки це число — з `priceNights`, одним
   * обʼєктом. Разом навмисно: див. нижче.
   */
  guest?: { price: number; origin: PriceOrigin } | null;
}

/**
 * Що показує клітинка: число І підпис, завжди з ОДНОГО розрахунку.
 *
 * Рецензія раунду 9 (Р9.2, блокер) знайшла тут два різні резолвери на одну
 * клітинку: число малювалось із `getPriceMonth` (SQL по рядках календаря), а
 * підпис — із `priceNights`, де матриця заселеності перекриває календар. На
 * живій базі це дало клітинку «100 · матриця заселеності», тоді як матриця
 * каже 120 — стільки й платить гість. Підпис виправив половину проблеми й
 * зробив другу гіршою: число дістало неправдиве пояснення, а неправдиве
 * пояснення гірше за відсутнє.
 *
 * Тому рішення тут одне і воно нерозривне: є ціна гостя — показуємо ЇЇ і її
 * підпис; немає (ніч закрита або жодне джерело її не цінує) — показуємо
 * число рядка календаря БЕЗ підпису, бо сказати, скільки заплатить гість, ми
 * не можемо. Функція існує заради того, щоб цього вибору не було в JSX: поки
 * він був там, гейт міг стверджувати лише форму виразу (той самий урок, що
 * `buildDayPayload`, рецензія раунду 5 правка 5.2).
 */
export function cellPrice(day: PricingDayCell): { price: number | null; origin: PriceOrigin | null } {
  if (day.guest) return { price: day.guest.price, origin: day.guest.origin };
  return { price: day.effective_price, origin: null };
}
