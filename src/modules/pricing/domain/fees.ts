/**
 * Збори й мито поверх ціни за проживання.
 *
 * ── Чому цей файл узагалі є ─────────────────────────────────────────────
 *
 * `fees_taxes` існує від початку, квота її читає й додає до підсумку — але
 * наповнював таблицю лише demo-seed. Ні екрана, ні CRUD-хендлера. Тобто в
 * кожного реального клієнта міське мито й прибирання в квоті **завжди нуль**,
 * і виглядає це не як помилка, а як «цей готель таких зборів не має».
 *
 * Секція у файлі готелю відтоді зʼявилася — `scripts/apply-hotel.mjs`, «збори
 * й мито», — тож завести збір уже є чим. Екрана й далі немає.
 *
 * Портьє називає гостю суму з цього екрана. Якщо мито не додалось, готель
 * або доплачує його з власної кишені, або догадується на виїзді — і те, й
 * інше гість дізнається вже після того, як почув ціну.
 *
 * Арифметика винесена сюди чистою, щоб її фіксував гейт без бази: це гроші,
 * і кожен із пʼяти типів помиляється по-своєму.
 *
 * ── Одне рішення, яке варто назвати вголос ──────────────────────────────
 *
 * `per_person_per_night` рахувався як `amount * adults * nights`, а сусідній
 * `per_person` — як `amount * (adults + children)`. Тобто два поля з тим
 * самим словом «person» рахували різні множини людей, і ніде не було
 * сказано чому.
 *
 * Тепер обидва рахують усіх гостей — те, що написано на етикетці. Це не
 * дрібниця смаку: готель, який заводить «Сніданок, за особу за ніч», отримав
 * би недобір на кожній дитині, і побачив би це аж у звіті.
 *
 * Курортне мито в багатьох юрисдикціях дітей звільняє — але це ПРАВИЛО
 * звільнення, а не інше значення слова «особа». Коли воно знадобиться, це
 * буде окреме поле (`applies_to`), а не мовчазна переінтерпретація. Міняти
 * це зараз безпечно рівно тому, що таблиця в усіх реальних клієнтів порожня:
 * виправити арифметику до того, як у ній зʼявляться гроші, — єдиний момент,
 * коли це нічого не коштує.
 *
 * ── Обіцянку виконано: `applies_to` (міграція 0050) ──────────────────────
 *
 * `all` — усі гості, це дефолт і поведінка кожного наявного рядка. `adults`
 * — лише дорослі, тобто те саме звільнення дітей, але СКАЗАНЕ. Готель, який
 * його хоче, вмикає його полем; готель, який не хоче, отримує число, що
 * збігається з етикеткою.
 *
 * Поле має сенс лише для двох типів із «person» у назві. Для `per_stay`,
 * `per_night` і `percentage` воно ні на що не множиться — і це не помилка,
 * яку варто кричати: «прибирання, лише з дорослих» — просто беззмістовне
 * уточнення, а не зіпсовані дані.
 *
 * Чого тут навмисно НЕМАЄ: віку. `applies_to` розрізняє дві множини, які
 * квота реально знає — `adults` і `children`. Скільки років у цьому готелі
 * означає «дитина», вирішує сам готель тим, як він рахує гостей у броні.
 * Поле `exempt_below_age` не додано свідомо: жоден шлях до `applyFees()` не
 * приносить вік окремого гостя, тож колонка була б числом, яке ніхто не
 * читає. Персональне звільнення вже існує в іншому місці й на іншому шарі —
 * `reservation_guests.fee_exempt`, на реєстрації, де людина відома поіменно.
 *
 * ── Чиї це гроші: `collected_for` ───────────────────────────────────────
 *
 * `property` — виручка готелю (прибирання, сніданок). `authority` — гроші,
 * які готель лише збирає для громади й віддає (турзбір, Kurtaxe).
 *
 * Для суми в квоті різниці немає, і саме тому це поле НЕ бере участі в
 * арифметиці нижче: обидва додаються до підсумку, гість платить те саме.
 * Різниця вмикається на документі — і читає її модуль юрисдикції
 * (`fiscal_ua`, `fiscal_de`), не цей файл (AGENTS.md, інваріант 22).
 *
 * ── `is_included_in_price`: контракт був написаний і не виконувався ──────
 *
 * `scripts/apply-hotel.mjs` описує це поле словами: «збір, який уже сидить у
 * ціні за ніч: він показується гостю в розбивці, але **не додається
 * вдруге**». Файл готелю вміє його виставити, схема має колонку від початку
 * — а `applyFees()` її не читав. Тобто готель, який чесно позначив «мито вже
 * в ціні», отримував це мито в підсумку ЩЕ РАЗ, і портьє називав гостю суму,
 * більшу за справжню.
 *
 * Не спрацювало досі лише тому, що `fees_taxes` порожня в усіх реальних
 * клієнтів. Це не «не баг» — це баг, який чекав на першого, хто заповнить
 * таблицю.
 *
 * Тому збори тепер розходяться на два списки:
 *
 *   feeBreakdown  — те, що ДОДАЄТЬСЯ до проживання. `feesTotal` — його сума,
 *                   і вона й далі точно дорівнює сумі своїх рядків.
 *   includedFees  — те, що вже всередині ціни ночі. Показується («у тому
 *                   числі»), не додається. Рядок потрібен: гість і податкова
 *                   мають бачити, скільки з цієї суми — мито.
 *
 * Не один список із прапорцем: тоді будь-який споживач, який просто складе
 * рядки розбивки, отримає число, більше за підсумок. Список, який не можна
 * скласти, — пастка; два списки, кожен зі своїм змістом, — ні.
 */

// Відносний шлях із розширенням, а не аліас: цей файл читає ще й гейт, який
// запускають голим node, а `@core/…` знає лише бандлер.
import { money, percentOf, sumMoney } from '../../../core/money.ts';

export type FeeType =
  | 'per_stay'
  | 'per_night'
  | 'per_person'
  | 'per_person_per_night'
  | 'percentage';

/** Кого рахувати. `all` — усіх гостей, `adults` — лише дорослих. */
export type FeeAppliesTo = 'all' | 'adults';

/** Чиї це гроші: виручка готелю чи збір для громади. */
export type FeeCollectedFor = 'property' | 'authority';

export interface Fee {
  name: string;
  type: FeeType | string;
  amount: number | string;
  /** Дефолт `all`. Рядки, старші за міграцію 0050, приходять без цього поля. */
  applies_to?: FeeAppliesTo | string | null;
  /** Дефолт `property`. Арифметики не змінює — див. шапку файла. */
  collected_for?: FeeCollectedFor | string | null;
  /**
   * Збір уже сидить у ціні ночі. Показується в розбивці, до підсумку НЕ
   * додається. З бази приходить BOOLEAN (Postgres) або 0/1 (SQLite).
   */
  is_included_in_price?: boolean | number | null;
}

export interface FeeContext {
  nights: number;
  adults: number;
  children: number;
  accommodationTotal: number;
}

export interface FeeLine {
  name: string;
  amount: number;
  /**
   * Класифікація їде разом із сумою, а не лишається в базі: документ
   * будується з розбивки, і саме там модуль юрисдикції вирішує, чи цей рядок
   * оподатковується. Поле, яке не доїхало до споживача, — мертва колонка.
   */
  collectedFor: FeeCollectedFor;
}

/**
 * Скільки додає кожен збір і скільки вони дають разом.
 *
 * Нуль і відʼємне не потрапляють у розбивку: рядок «Прибирання 0» у квоті
 * для гостя — шум, а відʼємний збір — це знижка, і вона живе в іншому місці.
 *
 * `feesTotal` — сума ЛИШЕ `feeBreakdown`. `includedFees` показуються окремо
 * і не додаються: вони вже в ціні ночі.
 */
export function applyFees(
  fees: readonly Fee[],
  ctx: FeeContext,
): { feeBreakdown: FeeLine[]; includedFees: FeeLine[]; feesTotal: number } {
  const nights = Math.max(0, Math.trunc(Number(ctx.nights) || 0));
  const adults = Math.max(0, Math.trunc(Number(ctx.adults) || 0));
  const children = Math.max(0, Math.trunc(Number(ctx.children) || 0));
  const guests = adults + children;
  const accommodation = Number(ctx.accommodationTotal) || 0;

  const feeBreakdown: FeeLine[] = [];
  const includedFees: FeeLine[] = [];

  for (const fee of fees || []) {
    const amount = Number(fee?.amount);
    if (!Number.isFinite(amount)) continue;

    // Порожнє поле — це рядок, старший за міграцію 0050, і його дефолт
    // збігається з поведінкою, яку він уже мав. Значення, якого цей файл не
    // знає, — не дефолт: це база, що пішла вперед без коду.
    //
    // Такий рядок пропускається зі скаргою, як і невідомий `type` нижче.
    // Напрямок обраний свідомо: збір, який зник із квоти, портьє бачить
    // одразу — підсумок не сходиться. Збір, порахований за вгаданим
    // правилом, не бачить ніхто, доки не прийде перевірка.
    const appliesToRaw = fee.applies_to ?? 'all';
    if (appliesToRaw !== 'all' && appliesToRaw !== 'adults') {
      console.error(`[fees] невідоме applies_to «${appliesToRaw}» (${fee.name}) — не враховано`);
      continue;
    }
    const collectedForRaw = fee.collected_for ?? 'property';
    if (collectedForRaw !== 'property' && collectedForRaw !== 'authority') {
      console.error(`[fees] невідоме collected_for «${collectedForRaw}» (${fee.name}) — не враховано`);
      continue;
    }

    // Кого рахує цей збір. Для типів без «person» у назві множник нижче на
    // це число не дивиться — і це не помилка, а беззмістовне уточнення.
    const payers = appliesToRaw === 'adults' ? adults : guests;

    let line = 0;
    switch (fee.type) {
      // `money()` на кожному множенні, бо double не має 0.10: мито 0,10 € на
      // трьох гостей дає 0.30000000000000004, і це число їде в квоту й далі
      // в базу. Округлення на виході не рятує — там уже неправильне значення.
      case 'per_stay': line = money(amount); break;
      case 'per_night': line = money(amount * nights); break;
      case 'per_person': line = money(amount * payers); break;
      case 'per_person_per_night': line = money(amount * payers * nights); break;
      // Відсоток рахується від проживання, а не від проміжного підсумку:
      // інакше порядок зборів у таблиці міняв би суму, і два готелі з
      // однаковими правилами отримували б різні числа.
      //
      // `percentOf`, а не `Math.round(x / 100)`: друге округлювало до цілого,
      // тобто 10 % від 119 € давало 12 € замість 11,90 €. У кронах ця втрата
      // непомітна, в євро це центи в кожній квоті — і саме той інваріант 9,
      // заради якого money.ts існує.
      case 'percentage': line = percentOf(accommodation, amount); break;
      // Тип поза CHECK-обмеженням схеми означає, що база змінилась, а цей
      // файл — ні. Тихо додати нуль — значить недорахувати гроші й нічого
      // про це не сказати.
      default:
        console.error(`[fees] невідомий тип збору «${fee.type}» (${fee.name}) — не враховано`);
        continue;
    }

    if (line > 0) {
      // `is_included_in_price` приходить BOOLEAN із Postgres і 0/1 із SQLite,
      // тож перевірка на істинність, а не `=== true`: одиниця це теж «так».
      const target = fee.is_included_in_price ? includedFees : feeBreakdown;
      target.push({
        name: String(fee.name ?? ''),
        amount: line,
        collectedFor: collectedForRaw,
      });
    }
  }

  // Одне округлення на підсумку, а не накопичення `+=`: інакше хвости кожного
  // рядка складаються, і сума зборів у квоті не дорівнює сумі своїх же рядків.
  return {
    feeBreakdown,
    includedFees,
    feesTotal: sumMoney(feeBreakdown.map((f) => f.amount)),
  };
}
