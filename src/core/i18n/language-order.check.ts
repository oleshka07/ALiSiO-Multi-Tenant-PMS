/**
 * Порядок мов на екрані — це порядок РЕЄСТРУ, і перша в ньому є базовою.
 *
 *   node src/core/i18n/language-order.check.ts
 *
 * ── Чому окремий гейт, коли вже є `guest-languages.check` ───────────────
 *
 * Той стереже МНОЖИНУ: поверхня говорить усіма мовами продукту. Це рівно
 * половина, і саме друга половина тут була зламана: множини збігались, а
 * порядки — ні. КІ38 заводився щоб список був ОДИН; на день цієї правки
 * списків із власним ПОРЯДКОМ було девʼять, і три з них ставили українську
 * першою, хоч продукт продається німецькому готелю.
 *
 * Множина нічого не каже про порядок за побудовою. Тому це окреме
 * твердження, а не рядок у сусідньому гейті.
 *
 * ── Що саме стверджується ───────────────────────────────────────────────
 *
 *   1. ПЕРША мова реєстру і `DEFAULT_LANGUAGE` — одна й та сама. Інакше
 *      перша кнопка перемикача каже одне, а система без вибору робить інше,
 *      і розбіжність видно лише тому, хто нічого не обирав;
 *   2. `UI_SOURCE_LANGUAGE` при цьому НЕ мусить збігатися з першою: це мова,
 *      якою написані літерали в JSX, тобто властивість нашого коду, а не
 *      вибір продукту. Змішати їх — зламати запасний шлях каталогу;
 *   3. кожен список мов, який БАЧИТЬ людина, впорядкований як реєстр. Для
 *      повних списків це рівність, для підмножин (віджет знає чотири мови з
 *      семи) — порядок, що лишається після викидання решти.
 *
 * ── Чому це властивість, а не візерунок ─────────────────────────────────
 *
 * Не «у файлі немає масиву з літералами мов» — такий гейт обходиться одним
 * `.concat()`. Списки читаються ВИКОНАННЯМ і звіряються з реєстром: список,
 * зібраний як завгодно, але в тому самому порядку, проходить; список,
 * переписаний руками в іншому порядку, — ні.
 */
import assert from 'node:assert';
import '../../../scripts/lib/module-aliases.mjs';

const { LANGUAGE_CODES, DEFAULT_LANGUAGE, UI_SOURCE_LANGUAGE, LANGUAGES } =
  await import('./languages.ts');

let ok = 0;
const say = (what: string) => { console.log(`  ok  ${what}`); ok += 1; };

// ── 1. Перша мова реєстру = базова мова продукту ────────────────────────
assert.strictEqual(LANGUAGE_CODES[0], DEFAULT_LANGUAGE,
  `реєстр починається з «${LANGUAGE_CODES[0]}», а базова мова продукту — «${DEFAULT_LANGUAGE}». `
  + 'Перша кнопка перемикача каже одне, а система без вибору робить інше');
say(`перша мова реєстру (${LANGUAGE_CODES[0]}) і є базовою мовою продукту`);

// ── 2. Мова ЛІТЕРАЛІВ — окрема річ, і плутати їх не можна ───────────────
//
// Твердження про РІЗНИЦЮ ролей, а не про конкретний код: `UI_SOURCE_LANGUAGE`
// це мова, якою написані рядки в JSX (ключі каталогу). Вона змінюється лише
// разом із перекладом усього каталогу, а базова мова продукту — коли завгодно.
assert.ok(LANGUAGE_CODES.includes(UI_SOURCE_LANGUAGE),
  'мова літералів має бути мовою реєстру');
assert.ok(LANGUAGE_CODES.includes(DEFAULT_LANGUAGE),
  'базова мова має бути мовою реєстру');
say(`мова літералів (${UI_SOURCE_LANGUAGE}) і базова мова (${DEFAULT_LANGUAGE}) — окремі ролі`);

// ── 3. Кожна мова реєстру має рідну назву ───────────────────────────────
for (const code of LANGUAGE_CODES) {
  const native = LANGUAGES[code]?.native ?? '';
  assert.ok(native.length > 2,
    `мова «${code}» підписана як «${native}» — це схоже на код, а не на назву`);
}
say(`${LANGUAGE_CODES.length} мов, кожна підписана рідною назвою`);

/**
 * Порядок реєстру, звужений до цієї множини.
 *
 * Саме так має виглядати будь-який список мов на екрані: підмножина реєстру
 * БЕЗ перестановок. Віджет знає чотири мови з семи — це не привід
 * упорядкувати їх по-своєму.
 */
const asRegistry = (codes: readonly string[]) =>
  LANGUAGE_CODES.filter((c) => codes.includes(c));

// ── 4. Поверхні, які бачить людина ──────────────────────────────────────
//
// Кожна читається ВИКОНАННЯМ. Список, зібраний із реєстру будь-яким способом,
// проходить; переписаний руками в іншому порядку — ні.
const guestApp = await import('../../apps/guest-app/ui/translations.ts');
const kiosk = await import('../../apps/kiosk/ui/translations.ts');
const guestPage = await import('../../app/guest/[token]/translations.ts');
const widget = await import('../../modules/widget/ui/widget-language.ts');
const contentField = await import('./content-field.ts');

const SURFACES: Array<{ what: string; codes: readonly string[] }> = [
  { what: 'гостьовий застосунок', codes: guestApp.GUEST_LANGS },
  { what: 'кіоск', codes: kiosk.KIOSK_LANGS },
  { what: 'гостьова сторінка', codes: guestPage.GUEST_PAGE_LANGS },
  { what: 'віджет бронювання', codes: widget.WIDGET_LANGUAGES },
  { what: 'колонки перекладу вмісту', codes: contentField.CONTENT_COLUMN_LANGS },
];

for (const surface of SURFACES) {
  const have = [...surface.codes];
  assert.ok(have.length > 0, `${surface.what}: список порожній`);
  for (const code of have) {
    assert.ok(LANGUAGE_CODES.includes(code as never),
      `${surface.what}: мова «${code}», якої немає в реєстрі`);
  }
  assert.deepStrictEqual(have, asRegistry(have),
    `${surface.what}: порядок [${have}], а реєстр велить [${asRegistry(have)}] — `
    + 'це власний порядок, а не порядок продукту');
}
say(`${SURFACES.length} поверхонь, і жодна не переставляє мови по-своєму`);

// ── 5. Повні списки — саме повні ────────────────────────────────────────
//
// Підмножина дозволена лише там, де словника справді менше (віджет — чотири
// мови, колонки вмісту — шість, бо базова лежить у самій колонці). Решта
// мусить знати ВСІ мови продукту, інакше «підмножина» це просто забули
// доповнити (КІ38).
// Каталог зручностей сюди НЕ входить: власного списку в нього більше немає —
// він питає реєстр напряму, тож стерегти нічого (один список замість двох).
const FULL = ['гостьовий застосунок', 'кіоск', 'гостьова сторінка'];
for (const surface of SURFACES.filter((s) => FULL.includes(s.what))) {
  assert.deepStrictEqual([...surface.codes], [...LANGUAGE_CODES],
    `${surface.what}: [${surface.codes}] проти реєстру [${LANGUAGE_CODES}]`);
}
say(`${FULL.length} поверхні знають УСІ мови продукту, не підмножину`);

// ── 6. Підмножини не вироджені ──────────────────────────────────────────
//
// Твердження 4 на списку з однієї мови зелене завжди. Тут перевіряється, що
// підмножини справді щось із себе являють, — інакше гейт стеріг би порожнечу.
for (const surface of SURFACES.filter((s) => !FULL.includes(s.what))) {
  assert.ok(surface.codes.length >= 3,
    `${surface.what}: у списку ${surface.codes.length} мов — на такому порядок недоказовий`);
  assert.ok(surface.codes.length < LANGUAGE_CODES.length,
    `${surface.what} знає всі мови продукту — тоді це повний список, і йому місце вище`);
}
say('підмножини мають щонайменше три мови — порядок на них видно');

console.log(`language-order: порядок мов один на весь продукт, ${ok} тверджень`);
