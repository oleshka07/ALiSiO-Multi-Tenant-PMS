/**
 * Одні двері до тексту, який написав ГОТЕЛЬ, приведеного до мови ГОСТЯ.
 *
 * ── Що це за текст і чим він відрізняється від `t()` ────────────────────
 *
 * `t()` перекладає наші власні слова — підписи кнопок, заголовки, відмови.
 * Їх пише продукт, вони живуть у каталозі, і покриття рахує гейт.
 *
 * Тут інше: назва послуги, її опис, одиниця («за особу/добу»), зручність,
 * пункт правил. Це дані клієнта (інваріант 20), вони лежать у базі з
 * `organization_id`, і жодного каталогу в них немає й бути не може. Готель
 * у Грайці пише `Frühstück`, готель у Празі — `Snídaně`, і продукт не знає
 * наперед ні слова, ні мови.
 *
 * ── Чому ДВЕРІ, а не по функції на екран ────────────────────────────────
 *
 * Бо їх уже було півтори. Гостьова СТОРІНКА мала приватний `svcField` із
 * трирівневим порядком; гостьовий ЗАСТОСУНОК не мав нічого — він читав
 * `s.name` і віддавав його як є, при тому що шість колонок `name_<мова>` у
 * таблиці стоять із 0060-х. Гість, який ішов з наліпки на дверях у застосунок
 * і далі на сторінку свого перебування, читав ту саму послугу двома різними
 * мовами на двох сусідніх екранах.
 *
 * Порядок джерел — це ТВЕРДЖЕННЯ про те, чия думка важливіша, і воно має
 * бути одне. Два порядки розходяться так само, як розходяться два списки
 * мов (КІ38), і розходяться в той бік, який видно лише гостю.
 *
 * ── Порядок, і чому саме такий ──────────────────────────────────────────
 *
 *   1. КОЛОНКА `<поле>_<мова>`. Це те, що людина набрала руками для цієї
 *      мови. Людина, яка відкрила форму і вписала `Snídaně`, знає про свій
 *      готель більше за будь-яку машину, і її слово не переграється нічим.
 *
 *   2. МОВА САМОГО ГОТЕЛЮ → базова колонка, і крапка. Перекладати німецький
 *      текст німецькою нема сенсу, а шукати його в словнику — шкідливо:
 *      збіг там означав би підміну слова готелю чужим. Раніше тут стояло
 *      `lang === 'uk'` літералом — тобто припущення, що вміст будь-якого
 *      готелю написаний українською. Для Грайця це неправда з першого дня.
 *
 *   3. СТАТИЧНИЙ СЛОВНИК (`content-translations.ts`). Рукописний, вивірений,
 *      без мережі. Ключ у нього український, тож для німецького готелю він
 *      мовчить — і це нормально: він не для нього.
 *
 *   4. `content_translations` — те, що колись переклала модель і що приїхало
 *      з відповіддю сервера. Нижче словника навмисно: рукописне краще за
 *      машинне, і саме так стояло на гостьовій сторінці до цих дверей.
 *      Міняти порядок тут означало б тихо змінити вигляд сторінок, які вже
 *      працюють, — а це не те, про що просили.
 *
 *   5. ТЕКСТ ГОТЕЛЮ як є. Не третя мова, не порожньо, не вигадка.
 *
 * ── Останній пункт важливіший, ніж виглядає ─────────────────────────────
 *
 * Двері, які на невідомій мові віддають «перший непорожній переклад», дають
 * нідерландському гостю чеську назву — і виглядає це як робочий переклад.
 * Тому сцена гейта тримає рядок, у якого ОДНА мова заповнена, і питає про
 * ІНШУ: двері мусять віддати мову готелю, а не сусідній переклад.
 */
import { translateContent } from './content-translations.ts';
import { type Language } from './languages.ts';

/** Те, що віддає `getStoredTranslations`: текст → мова → переклад. */
export type StoredTranslations = Record<string, Record<string, string>>;

export interface ContentOrigin {
  /**
   * Мова, якою написані БАЗОВІ колонки, — мова готелю
   * (`organizations.language`), ніколи не константа.
   */
  sourceLang: Language;
  /** Кеш перекладів, якщо поверхня його везе. Немає — просто пропускається. */
  stored?: StoredTranslations | null;
}

/** Рядок бази з базовою колонкою і, можливо, колонками мов. */
export type ContentRow = Record<string, unknown> | null | undefined;

const text = (v: unknown): string => (typeof v === 'string' ? v : '');

/**
 * Значення поля `field` рядка `row` мовою `lang`.
 *
 * `field` — імʼя БАЗОВОЇ колонки (`name`, `description`, `unit_label`);
 * колонки мов шукаються як `${field}_${lang}`. Порожній рядок у колонці — це
 * «не заповнено», а не відповідь: форма шле `''` за кожне поле, якого не
 * торкались, і саме так `name_pl = ''` опинялось у половини рядків.
 */
export function localisedContent(row: ContentRow, field: string, lang: Language, origin: ContentOrigin): string {
  if (!row) return '';
  const base = text(row[field]);

  // 1. Колонка мови — слово людини.
  const typed = text(row[`${field}_${lang}`]).trim();
  if (typed) return typed;

  // 2. Мова готелю — базова колонка, без жодних пошуків.
  if (lang === origin.sourceLang) return base;

  const trimmed = base.trim();
  if (!trimmed) return base;

  // 3. Статичний словник. Він віддає ВХІДНИЙ текст, коли не знає, тож
  //    «не знає» відрізняється від «переклав» саме порівнянням, а не null.
  const fromDict = translateContent(trimmed, lang);
  if (fromDict !== trimmed) return fromDict;

  // 4. Те, що переклала модель.
  const fromStore = text(origin.stored?.[trimmed]?.[lang]).trim();
  if (fromStore) return fromStore;

  // 5. Текст готелю. Не третя мова.
  return base;
}

/**
 * Те саме для ОДИНОКОГО тексту, у якого колонок мов немає й бути не може:
 * пункт правил, питання FAQ, назва зручності — усе, що лежить у JSON-полі
 * конфігурації, а не окремою колонкою.
 *
 * Порядок той самий, мінус перший крок, і це не окремий алгоритм: гостьова
 * сторінка тримала два приватні прочитання поруч (`tc` і `svcField`), і саме
 * так порядок джерел роздвоюється — тихо, у сусідніх рядках одного файла.
 */
export function localisedText(value: unknown, lang: Language, origin: ContentOrigin): string {
  return localisedContent({ value }, 'value', lang, origin);
}

/**
 * Колонки мов одного поля — рівно те, що треба вибрати запитом і покласти в
 * тіло відповіді, щоб екран міг перемкнути мову без походу в мережу.
 *
 * Список береться з РЕЄСТРУ мов, а не пишеться поруч, — і саме тому він тут,
 * а не в кожному репозиторії окремо: власний список знову розійшовся б із
 * продуктом (КІ38). Мови, у якої немає колонки в таблиці, у списку теж не
 * буде: колонки заведені під шість мов перекладу, українська — базова.
 */
export const CONTENT_COLUMN_LANGS: readonly Language[] = ['en', 'de', 'cs', 'pl', 'nl', 'fr'];

/** `name` → `name_en, name_de, …` — для `SELECT`. */
export function contentColumns(prefix: string, field: string): string {
  return CONTENT_COLUMN_LANGS.map((code) => `${prefix}.${field}_${code}`).join(', ');
}

/** Витягти колонки мов одного поля з рядка бази у плаский обʼєкт відповіді. */
export function pickContentColumns(row: Record<string, unknown>, field: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const code of CONTENT_COLUMN_LANGS) {
    const value = text(row[`${field}_${code}`]).trim();
    if (value) out[`${field}_${code}`] = value;
  }
  return out;
}
