/**
 * Двері до тексту готелю: порядок джерел, і що на невідомій мові вони НЕ
 * віддають чужу.
 *
 *   node src/core/i18n/content-field.check.ts
 *
 * ── Чому фікстура саме така ─────────────────────────────────────────────
 *
 * Інваріант 26: для кожної осі, про яку тут щось стверджується, у фікстурі
 * мусить бути щонайменше ДВА значення, що на цій осі різняться.
 *
 * Осей три, і кожна має свою пару:
 *
 *   МОВА — рядок має заповнену `cs` і порожню `nl`. Двері, які віддають
 *     «перший непорожній переклад», на `nl` віддали б чеську, і це головний
 *     злом, який тут ловиться. З рядком, у якого заповнено все, вони були б
 *     зелені;
 *   ДЖЕРЕЛО — для одного тексту є і колонка, і словник, і кеш, і всі три
 *     кажуть РІЗНЕ. З однаковими значеннями порядок був би недоказовий;
 *   МОВА ГОТЕЛЮ — у сцені два готелі, німецький і український, і те саме
 *     твердження перевіряється з обох боків. Один готель лишив би `lang ===
 *     'uk'` літералом і сцену зеленою — саме так це й стояло.
 *
 * Числа несумісні з альтернативним прочитанням: усі значення різні рядки,
 * тож будь-яке «взяв не те джерело» видно в діфі, а не вгадується.
 */
import assert from 'node:assert';
import '../../../scripts/lib/module-aliases.mjs';

const { localisedContent, contentColumns, pickContentColumns, CONTENT_COLUMN_LANGS } =
  await import('./content-field.ts');
const { LANGUAGE_CODES } = await import('./languages.ts');

let ok = 0;
const say = (what: string) => { console.log(`  ok  ${what}`); ok += 1; };

// ── Німецький готель ────────────────────────────────────────────────────
const DE = { sourceLang: 'de' as const, stored: {
  // Кеш каже СВОЄ, відмінне і від колонки, і від словника: інакше не видно,
  // яке з трьох джерел відповіло.
  'Frühstück': { cs: 'z-кешу', pl: 'Śniadanie', nl: 'Ontbijt-з-кешу', de: 'НЕ-БРАТИ' },
} };

const svc = {
  name: 'Frühstück',
  name_cs: 'Snídaně',
  name_en: 'Breakfast',
  // Порожній рядок — це «не заповнено», і саме так форма шле кожне поле,
  // якого не торкались.
  name_pl: '',
  description: 'Reichhaltiges Buffet',
  unit_label: 'pro Person/Nacht',
};

assert.strictEqual(localisedContent(svc, 'name', 'cs', DE), 'Snídaně',
  'колонка мови мусить перемагати кеш — це слово людини, а не машини');
assert.strictEqual(localisedContent(svc, 'name', 'en', DE), 'Breakfast',
  'друга заповнена колонка дала не своє значення');
assert.notStrictEqual(localisedContent(svc, 'name', 'cs', DE), localisedContent(svc, 'name', 'en', DE),
  'дві різні заповнені колонки дали одне — вісь мови відсутня');
say('колонка мови перемагає кеш і словник');

assert.strictEqual(localisedContent(svc, 'name', 'de', DE), 'Frühstück',
  'мовою ГОТЕЛЮ мусить читатись базова колонка, не кеш');
say('мова готелю → базова колонка, кеш не читається');

// ГОЛОВНЕ твердження: мова, якої ніде немає, дає текст ГОТЕЛЮ.
//
// `fr` немає ні колонкою, ні в кеші, ні в словнику — а `cs` і `en` у рядка
// заповнені. Двері, які віддають перший непорожній переклад, тут червоніють.
assert.strictEqual(localisedContent(svc, 'name', 'fr', DE), 'Frühstück',
  'мова, якої немає, дала ЧУЖИЙ переклад замість тексту готелю');
say('невідома мова → текст готелю, ніколи не третя мова');

// Порожня колонка — не відповідь: `pl` заповнена рядком '', і відповісти має кеш.
assert.strictEqual(localisedContent(svc, 'name', 'pl', DE), 'Śniadanie',
  'порожня колонка мови була зарахована за відповідь — на екрані це підпис, якого немає');
say("колонка з порожнім рядком читається як «не заповнено»");

// Кеш відповідає там, де колонки немає взагалі.
assert.strictEqual(localisedContent(svc, 'name', 'nl', DE), 'Ontbijt-з-кешу',
  'кеш перекладів не читається');
say('кеш відповідає, коли колонки немає');

// Поля, відмінні від `name`, ходять тими самими дверима.
assert.strictEqual(localisedContent(svc, 'unit_label', 'cs', DE), 'pro Person/Nacht',
  'одиниця без перекладу мусить лишитись мовою готелю');
assert.strictEqual(localisedContent(svc, 'description', 'de', DE), 'Reichhaltiges Buffet');
say('опис і одиниця ходять тими самими дверима');

// ── Український готель: та сама сцена з іншого боку ─────────────────────
//
// Словник (`content-translations.ts`) заведений під українську, тож саме тут
// видно рівень 3. `Душ` у ньому є: en «Shower», cs «Sprcha».
const UA = { sourceLang: 'uk' as const, stored: {
  'Душ': { cs: 'з-кешу-НЕ-брати', fr: 'Douche-з-кешу' },
} };
const room = { name: 'Душ' };

assert.strictEqual(localisedContent(room, 'name', 'uk', UA), 'Душ',
  'мовою готелю має читатись базова колонка');
assert.strictEqual(localisedContent(room, 'name', 'cs', UA), 'Sprcha',
  'рукописний словник мусить перемагати машинний кеш');
assert.strictEqual(localisedContent(room, 'name', 'en', UA), 'Shower',
  'словник не відповів там, де він точно знає');
say('український готель: словник вище за кеш, мова готелю — базова колонка');

// І те саме твердження з іншого боку осі «мова готелю»: якби всередину був
// зашитий `lang === 'uk'`, ця пара була б зелена, а німецька сцена вище — ні.
assert.strictEqual(localisedContent({ name: 'Душ' }, 'name', 'uk', DE), 'Душ',
  'німецький готель із українським рядком: мова, не рівна мові готелю, і без джерел — текст як є');
say("вісь «мова готелю» не вироджена: два готелі, два різні результати");

// ── Порожньо, сміття, відсутній рядок ───────────────────────────────────
assert.strictEqual(localisedContent(null, 'name', 'cs', DE), '');
assert.strictEqual(localisedContent(undefined, 'name', 'cs', DE), '');
assert.strictEqual(localisedContent({ name: 42 }, 'name', 'cs', DE), '',
  'нерядок у колонці мусить дати порожньо, а не «42»');
assert.strictEqual(localisedContent({ name: '' }, 'name', 'cs', { sourceLang: 'de' }), '',
  'порожній базовий текст без кешу мусить лишитись порожнім, а не шукатись у словнику');
say('немає рядка або немає тексту — порожньо, без вигадок');

// ── Пробіли ─────────────────────────────────────────────────────────────
//
// Кеш і словник ключовані ОБРІЗАНИМ текстом (так їх наповнює `textHash`), а
// в колонці цілком може лежати рядок із пробілом на кінці — саме так їх
// набирають руками.
//
// Твердження про КЕШ, а не про словник, і це не дрібниця. Перша редакція
// питала словник — і лишалась зеленою, коли обрізання з дверей прибирали
// зовсім: `translateContent` обрізає ВСЕРЕДИНІ себе, тож стерегла вона чужу
// властивість. Кеш читаємо ми самі, і обрізання тут єдине. Злом «прибрати
// .trim()» проходив повз гейт — п'ятий із п'яти, і єдиний зелений (§3.2.1).
assert.strictEqual(localisedContent({ name: '  Frühstück ' }, 'name', 'nl', DE), 'Ontbijt-з-кешу',
  'пробіл навколо тексту сховав його від КЕШУ — ключ там обрізаний, а ми шукали з пробілами');
assert.strictEqual(localisedContent({ name: '  Душ ' }, 'name', 'cs', UA), 'Sprcha',
  'пробіл навколо тексту сховав його від словника');
say('пробіли не ховають текст ні від кешу, ні від словника');

// ── Список колонок береться з реєстру, а не пишеться поруч ──────────────
for (const code of CONTENT_COLUMN_LANGS) {
  assert.ok(LANGUAGE_CODES.includes(code),
    `колонка заведена під мову «${code}», якої немає в реєстрі мов`);
}
assert.ok(CONTENT_COLUMN_LANGS.length >= LANGUAGE_CODES.length - 1,
  `колонок ${CONTENT_COLUMN_LANGS.length} на ${LANGUAGE_CODES.length} мов реєстру — `
  + 'мова, у якої немає колонки, перекладається лише кешем, і мовчки');
say(`колонки заведені під ${CONTENT_COLUMN_LANGS.length} мов реєстру`);

assert.strictEqual(contentColumns('s', 'name'),
  's.name_en, s.name_de, s.name_cs, s.name_pl, s.name_nl, s.name_fr',
  'список колонок для SELECT зібрано не так');
assert.deepStrictEqual(pickContentColumns(svc, 'name'),
  { name_en: 'Breakfast', name_cs: 'Snídaně' },
  'у відповідь мусять потрапити лише ЗАПОВНЕНІ колонки: порожні роздули б тіло й читались би як відповідь');
say('SELECT і тіло відповіді збираються з того самого списку');

console.log(`content-field: один порядок джерел на всі поверхні, ${ok} тверджень`);
