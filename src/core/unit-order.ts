/**
 * Порядок номерів такий, як їх називає готель: 2, 10, 102 — не 10, 102, 2.
 *
 * ── Навіщо окремий модуль ───────────────────────────────────────────────
 *
 * Порядок рядків потрібен двом календарям (десктоп і телефон), і копія в
 * кожному означала б два порядки, які розійдуться: портьє з планшета і
 * портьє з телефона бачили б різні списки й називали б різні номери. Тут
 * немає React, тож перевірка імпортує ЦЕЙ файл, а не свою копію логіки —
 * на відміну від групування, яке живе всередині клієнтського компонента.
 *
 * ── Чому не ORDER BY в базі ─────────────────────────────────────────────
 *
 * `units.sort_order` — ручний порядок, і запит сортує
 * `c.sort_order, ut.sort_order, u.sort_order`, тобто спершу за категорією,
 * потім за ТИПОМ. У готелі з трьома типами ліва колонка виглядала так:
 *
 *   213 210 207 204 201 110 107 104 101 211 208 205 202 …
 *
 * Це не порядок, це шум: людина шукає «102» очима зверху вниз. Сортувати в
 * SQL природним порядком теж не можна однаково на обох двигунах — SQLite не
 * має `NATURALSORT`, а `regexp_replace` у Postgres дав би різний результат.
 * Тому це робиться там, де малюється список.
 */

/**
 * Два номери за їхніми назвами. `code` — другий ключ.
 *
 * Порівнюємо `name`, а не `code`: у списку людина бачить саме назву, і
 * порядок, який не збігається з видимим, читається як зламаний. `code`
 * додається другим, бо при однакових назвах порядок мусить бути стабільним —
 * інакше React перемішує рядки між перемальовуваннями.
 */
export function compareUnitNames(
  a: { name?: string | null; code?: string | null },
  b: { name?: string | null; code?: string | null },
): number {
  const byName = naturalCompare(a.name || '', b.name || '');
  return byName !== 0 ? byName : naturalCompare(a.code || '', b.code || '');
}

/**
 * Порівняння, у якому число всередині рядка важить як число.
 *
 * Звичайний `localeCompare` йде посимвольно, тож «10» стає раніше за «2», а
 * «102» — раніше за «11». Для готелю на 9 номерів це непомітно; на 25 список
 * читається як випадковий.
 *
 * Назви бувають різні — «102», «A12», «Люкс 3», «12-б», — тому рядок ріжеться
 * на шматки: цифри порівнюються числом, решта текстом. `localeCompare` для
 * тексту потрібен, бо порядок «Ї» після «И» знає лише він.
 */
export function naturalCompare(a: string, b: string): number {
  // `\d+`, а не «число»: мінус і крапка в назві номера — роздільники
  // («12-б», «2.5»), а не знак і не дробова частина.
  const ap = a.match(/\d+|\D+/g) ?? [];
  const bp = b.match(/\d+|\D+/g) ?? [];
  for (let i = 0; i < Math.min(ap.length, bp.length); i++) {
    const x = ap[i], y = bp[i];
    if (/^\d/.test(x) && /^\d/.test(y)) {
      // Number(), а не parseInt(): «007» і «7» — один номер, провідні нулі не
      // мають ставити його в інший кінець списку. Довжина розсуджує рівні
      // числа, щоб порядок був стабільним.
      const d = Number(x) - Number(y);
      if (d !== 0) return d;
      if (x.length !== y.length) return x.length - y.length;
    } else {
      const d = x.localeCompare(y);
      if (d !== 0) return d;
    }
  }
  return ap.length - bp.length;
}
