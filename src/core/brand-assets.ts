/**
 * Зображення обʼєкта, названі РОЛЯМИ, — реєстр.
 *
 * ── Навіщо ролі, а не просто галерея ────────────────────────────────────
 *
 * Галерея — це список: застосунок, якому потрібне «щось для шапки», бере
 * перше-ліпше й сподівається. Роль — це домовленість: екран просить
 * `logo`, і дістає лого, а не фото сніданку. Саме тому «три-пʼять зображень,
 * які потім підтягнуть інші застосунки» мусять мати імена: без імен їх може
 * підтягнути лише той, хто бачив, у якому порядку їх завантажили.
 *
 * ── Попередження, куплене дорого ────────────────────────────────────────
 *
 * Типізовані фото обʼєкта в цьому проєкті ВЖЕ робили. `property_photos`
 * мала колонку `photo_type` із CHECK на `building / territory / common /
 * aerial` — і зараз її немає: вона потрапила в `DEAD_COLUMNS` у `db.ts`,
 * тобто її знесли як мертву. Писач був, читача не було ЖОДНОГО.
 *
 * Звідси правило цього реєстру, і воно тут головне:
 *
 *   **РОЛЬ ЗАВОДИТЬСЯ РАЗОМ ІЗ ЧИТАЧЕМ.**
 *
 * Кожен запис нижче називає, хто його читає, і `brand-assets.check`
 * стверджує, що названий читач існує й справді згадує цю роль. Роль без
 * читача — це колонка, яку через півроку знесе прибиральник мертвих даних,
 * і оператор, який завантажив туди картинку, ніколи не дізнається чому.
 *
 * Тому ролей ТРИ, а не пʼять. Четверта й пʼята заводяться тоді, коли
 * зʼявиться екран, якому вони потрібні, — це зміна В ОДНОМУ файлі, без
 * міграції: рядки лежать у `property_brand_assets` із колонкою `role`.
 *
 * ── Чому окрема таблиця, а не колонки на `properties` ───────────────────
 *
 * Бо саме це й дає «додати роль без міграції». Колонковий варіант
 * (`brand_logo_url`, `brand_cover_url`, …) вимагав би міграції на кожну
 * нову роль — тобто рівно те, чого просили уникнути.
 *
 * І чому не `property_photos`: та таблиця — ГАЛЕРЕЯ (багато рядків, порядок,
 * підпис), її читає гостьовий портал запитом без фільтра. Лого, покладене
 * туди, зʼявилось би серед фотографій готелю на екрані гостя. Різна форма —
 * різні таблиці: тут рівно один рядок на роль (UNIQUE), без порядку й
 * підпису.
 */
import { readBrandLogoUrl } from './brand-palettes.ts';

export interface BrandAssetRole {
  /** Як роль лежить у `property_brand_assets.role`. */
  key: string;
  /**
   * Хто це читає. Не документація: `brand-assets.check` відкриває ці файли
   * і вимагає, щоб ключ ролі в них згадувався.
   */
  readBy: readonly string[];
}

export const BRAND_ASSET_ROLES: readonly BrandAssetRole[] = [
  {
    // Основне лого: темний знак на світлому тлі. Найчастіше те, що готель
    // уже має у форматі для бланка.
    key: 'logo',
    readBy: [
      'src/apps/guest-app/data/property.repo.ts',
      'src/modules/properties/domain/a4-sheet.ts',
      // Гостьовий портал `/guest/<токен>` — ДРУГА поверхня, яку бачить гість.
      // Доти лого їхало їй з `properties.brand_logo_url`, і 0421 ту колонку
      // очистив: читач, який лишився на ній, віддавав `null`, сторінка малювала
      // назву текстом і виглядала як готель без лого. Тримає `guest-portal.check`.
      'src/modules/guests/api/portal.handlers.ts',
    ],
  },
  {
    // Лого для ТЕМНОГО тла. Не примха: палітри `forest_stone` та `ink_amber`
    // (0419) дають темну шапку, і темний знак на ній зникає. Порожньо —
    // беремо основне, тобто готель, у якого одне лого, нічого не втрачає.
    key: 'logo_light',
    readBy: [
      'src/apps/guest-app/data/property.repo.ts',
      // Обидві гостьові поверхні обирають знак за яскравістю тла ОДНИМ
      // правилом — `paletteBackground` із реєстру палітр.
      'src/modules/guests/api/portal.handlers.ts',
    ],
  },
  {
    // Обкладинка: фасад або загальний вигляд. Те, що робить аркуш A4
    // впізнаваним іздалеку, а домашній екран застосунку — не порожнім.
    key: 'cover',
    readBy: ['src/modules/properties/domain/a4-sheet.ts'],
  },
] as const;

export const BRAND_ASSET_ROLE_KEYS: readonly string[] = BRAND_ASSET_ROLES.map((r) => r.key);

/** Роль із бази або з форми, приведена до відомої. Невідома → `null`. */
export function readBrandAssetRole(raw: unknown): string | null {
  return typeof raw === 'string' && BRAND_ASSET_ROLE_KEYS.includes(raw) ? raw : null;
}

/** Рядки з бази → «роль → адреса», з тією ж перевіркою адреси, що в 0419. */
export type BrandAssets = Record<string, string>;

export function readBrandAssets(rows: readonly { role: unknown; url: unknown }[]): BrandAssets {
  const out: BrandAssets = {};
  for (const row of rows) {
    const role = readBrandAssetRole(row.role);
    const url = readBrandLogoUrl(row.url);
    // Обидві перевірки потрібні: роль, якої ми не знаємо, не має потрапити на
    // екран під чужим іменем, а адреса, яку не можна дати в `img src`
    // (`http:`, `data:`), дала б гостю порожній прямокутник замість знака.
    if (role && url) out[role] = url;
  }
  return out;
}

/**
 * Лого для тла названої яскравості.
 *
 * `logo_light` порожнє → основне. Готель, який завантажив одне лого, має
 * бачити його скрізь; вибір тут — покращення для тих, хто дав два, а не
 * умова для решти (інваріант 13 навпаки: тут «не знайшли» коштує вигляду,
 * а не даних, тож відмовляти нема чого).
 */
export function logoFor(assets: BrandAssets, background: 'light' | 'dark'): string | null {
  if (background === 'dark' && assets.logo_light) return assets.logo_light;
  return assets.logo ?? assets.logo_light ?? null;
}
