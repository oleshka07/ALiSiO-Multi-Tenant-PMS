/**
 * Гостьова поверхня говорить КОЖНОЮ мовою, яку знає продукт — і говорить нею.
 *
 * ── Що було зламано ─────────────────────────────────────────────────────
 *
 * Мов у продукті сім (`core/i18n/languages.ts`). Гостьова СТОРІНКА знала всі
 * сім. Гостьовий ЗАСТОСУНОК і КІОСК — дві, бо кожен завів власний список:
 * `['de', 'en']` у словнику застосунку, такий самий у словнику кіоска, і
 * третій такий самий у тілі відповіді `deviceSession`. Разом із чотирма, які
 * перелічує шапка реєстру, це були списки пʼятий, шостий і сьомий — при
 * тому, що реєстр заведений рівно щоб список був ОДИН.
 *
 * Помилка мовчала й коштувала гостю: чех, який відсканував наліпку на дверях,
 * діставав німецький екран, бо його мови в списку не було, — і поруч, на
 * гостьовій сторінці того самого готелю, чеська була.
 *
 * ── Чому цього не тримає тип ────────────────────────────────────────────
 *
 * Тримає, але лише половину. `Record<GuestLang, GuestStrings>` не дає забути
 * КЛЮЧ у мові — це TypeScript і це безкоштовно. Чого він не бачить, три речі,
 * і кожна мовчить:
 *
 *   1. `GuestLang`, оголошений власним списком. Тип знову сходиться — сам із
 *      собою, — і мов знову дві. Саме так це й стояло;
 *   2. рядок НА МІСЦІ, але чужою мовою: блок скопійовано з німецького й
 *      перейменовано константу. Найтихіше з трьох: покриття 100 %, екран
 *      німецький (той самий випадок, що шостий у AGENTS §3.2.1);
 *   3. втрачена підстановка. `heldFor` без `{minutes}` дає «Тримаємо номер
 *      хвилин» — речення, яке читається як недороблене, і жоден тип про
 *      фігурні дужки не знає.
 *
 * ── Що стверджується ────────────────────────────────────────────────────
 *
 * Не «є словник», а рівність множин і три властивості кожного блоку. Мапи
 * читаються ВИКОНАННЯМ, а не грепом по тексту: власний список, підставлений
 * замість реєстру, у тексті виглядає так само правильно.
 */
import assert from 'node:assert';
import '../../scripts/lib/module-aliases.mjs';

const { LANGUAGE_CODES } = await import('@core/i18n/languages.ts');
const guestApp = await import('../apps/guest-app/ui/translations.ts');
const kiosk = await import('../apps/kiosk/ui/translations.ts');

let ok = 0;
const say = (what: string) => { console.log(`  ok  ${what}`); ok += 1; };

const codes = [...LANGUAGE_CODES].sort();
assert.ok(codes.length >= 5,
  `у реєстрі лише ${codes.length} мов — перевірка майже нічого не стереже`);

/**
 * Поверхні, які читає ГІСТЬ.
 *
 * Три, а не дві: відмови заселення — окрема мапа `Record<KioskLang, …>` у
 * тому ж файлі, і саме такі «другі мапи поруч» лишаються двомовними, коли
 * головну доповнили. Тип їх теж не звʼязує між собою.
 *
 * Гостьова СТОРІНКА (`/guest/<токен>`) сюди не входить: її словник має іншу
 * форму (вкладені обʼєкти на секцію) і сім мов у ньому були з самого початку.
 * Додати її — окрема правка з власним розбором, і поки її немає, це чесніше
 * сказати тут, ніж мовчки лишити враження, що гейт стереже всі три поверхні.
 */
const SURFACES: { what: string; dict: Record<string, Record<string, string>> }[] = [
  { what: 'гостьовий застосунок', dict: guestApp.GUEST_STRINGS as never },
  { what: 'кіоск', dict: kiosk.KIOSK_STRINGS as never },
  { what: 'кіоск: відмови заселення', dict: kiosk.KIOSK_REFUSALS as never },
];

for (const surface of SURFACES) {
  // ── 1. Рівність множин ────────────────────────────────────────────────
  const have = Object.keys(surface.dict).sort();
  assert.deepStrictEqual(have, codes,
    `${surface.what}: говорить мовами [${have}], а продукт знає [${codes}] — це власний список замість реєстру`);
  say(`${surface.what}: усі ${codes.length} мов реєстру`);

  const keys = Object.keys(surface.dict[codes[0]]);
  assert.ok(keys.length > 0, `${surface.what}: словник порожній`);

  // ── 2. Жодного порожнього рядка ───────────────────────────────────────
  //
  // Тип вимагає, щоб ключ БУВ; порожній рядок йому підходить, а на екрані це
  // кнопка без підпису.
  for (const lang of codes) {
    const block = surface.dict[lang];
    for (const key of keys) {
      assert.ok(typeof block[key] === 'string' && block[key].trim() !== '',
        `${surface.what}: ${lang}.${key} порожній — на екрані це підпис, якого немає`);
    }
  }
  say(`${surface.what}: ${keys.length} рядків × ${codes.length} мов, жодного порожнього`);

  // ── 3. Жоден блок не є копією іншого ──────────────────────────────────
  //
  // Рахуємо частку ОДНАКОВИХ рядків між парою мов. Кілька збігів нормальні й
  // неминучі: «WhatsApp», «Wi-Fi», «Extras», «Total» справді пишуться однаково
  // в кількох мовах. Копія цілого блоку дає не кілька, а майже все.
  //
  // Межа — половина, і вона ВИМІРЯНА, а не вгадана. На день заведення гейта
  // найбільший чесний збіг: застосунок de/en 3 % (`guestName` = «Name»,
  // `extrasLabel` = «Extras»), кіоск de/en 7 % («Check-in», «Check-out»,
  // «Info», «WhatsApp», «Extras»), відмови 0 %. Копія блоку дає 100 %.
  //
  // Тобто між найбільшою правдою і найменшою брехнею — разів сім, і поріг
  // стоїть посередині цього провалля. Перша редакція коментаря називала
  // найбільшою парою нідерландську з англійською; вимір показав німецьку з
  // англійською. Число, взяте зі здогаду, і число, взяте з заміру, тут
  // збіглися б випадково.
  for (let i = 0; i < codes.length; i += 1) {
    for (let j = i + 1; j < codes.length; j += 1) {
      const a = surface.dict[codes[i]];
      const b = surface.dict[codes[j]];
      const same = keys.filter((k) => a[k] === b[k]);
      const share = same.length / keys.length;
      assert.ok(share < 0.5,
        `${surface.what}: ${codes[i]} і ${codes[j]} збігаються на ${Math.round(share * 100)} % `
        + `(${same.length} із ${keys.length}) — це копія блоку, а не переклад. `
        + `Перші збіги: ${same.slice(0, 3).join(', ')}`);
    }
  }
  say(`${surface.what}: жодна пара мов не є копією`);

  // ── 4. Підстановки на місці ───────────────────────────────────────────
  //
  // Еталон — множина `{…}` у КОЖНОМУ ключі англійського блоку. Мова, у якій
  // підстановки бракує, лишає на екрані речення з діркою; мова, у якій
  // зʼявилась зайва, підставить у неї порожнечу.
  const holes = (v: string) => (v.match(/\{[a-zA-Z_]+\}/g) ?? []).sort().join(',');
  for (const key of keys) {
    const want = holes(surface.dict.en[key]);
    for (const lang of codes) {
      assert.strictEqual(holes(surface.dict[lang][key]), want,
        `${surface.what}: ${lang}.${key} має підстановки «${holes(surface.dict[lang][key])}», `
        + `а англійський — «${want}». Втрачена дужка лишає на екрані речення з діркою`);
    }
  }
  say(`${surface.what}: підстановки збігаються в усіх мовах`);
}

// ── 5. Підпис мови — її РІДНОЮ назвою ───────────────────────────────────
//
// Перемикач із кодами («DE/EN/CZ») читає той, хто вже знає, що шукати. Гість
// шукає слово, яке впізнає, — і саме тому підписи беруться з реєстру, а не
// пишуться поруч зі списком.
for (const [what, labels] of [
  ['гостьовий застосунок', guestApp.GUEST_LANG_LABELS as Record<string, string>],
  ['кіоск', kiosk.KIOSK_LANG_LABELS as Record<string, string>],
] as const) {
  assert.deepStrictEqual(Object.keys(labels).sort(), codes,
    `${what}: підписи є не для всіх мов — у перемикачі буде порожня кнопка`);
  for (const code of codes) {
    assert.ok(labels[code].length > 2,
      `${what}: підпис «${labels[code]}» для ${code} схожий на код, а не на назву мови`);
  }
  say(`${what}: кожна мова підписана рідною назвою`);
}

console.log(`guest-languages: гостьові поверхні говорять ${codes.length} мовами, ${ok} тверджень`);
