/**
 * Розмір, який мовчки перетворює «мало» на «нічого».
 *
 *   node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON src/core/format/bytes.check.ts
 *
 * Твердження одне, і воно про ВЛАСТИВІСТЬ, а не про конкретні рядки:
 * **жодне ненульове число байтів не друкується як нуль.** Саме це зламалось у
 * таблиці знімків Winhotel — `0.0 MB` для дельти на 31 610 байтів, і такий
 * самий `0.0 MB` для справжнього нуля (INC-053).
 *
 * Перевіряється не трьома зручними прикладами, а суцільним проходом по
 * порядках величини: якби гейт перелічував «1, 1024, 1048576», він доводив би
 * рівно ті три числа, а дефект жив рівно між ними.
 */
import assert from 'node:assert';
import { formatBytes } from './bytes.ts';

let checks = 0;
const ok = (what: string) => { checks++; console.log(`  ok  ${what}`); };

// ── Головне твердження: ненульове не друкується нулем ──────────────────────
//
// Від 1 байта до 8 ГБ, по кілька точок на кожен порядок. «Друкується нулем» —
// це не лише рядок «0»: `0.0 MB`, `0 KB`, `0.00 MB` однаково означають для
// оператора «нічого не приїхало».
const zeroish = (s: string) => /^0(\.0+)?\s*[KMG]?B$/i.test(s.trim());

let worst: { bytes: number; text: string } | null = null;
for (let e = 0; e <= 33; e++) {
  for (const k of [1, 1.5, 3, 7]) {
    const bytes = Math.round(2 ** e * k);
    if (bytes === 0) continue;
    const text = formatBytes(bytes);
    if (zeroish(text) && !worst) worst = { bytes, text };
  }
}
assert.strictEqual(worst, null,
  `ненульовий розмір надрукувався нулем: ${worst?.bytes} байтів → «${worst?.text}»`);
ok('жодне ненульове число від 1 Б до 8 ГБ не друкується як нуль');

// Те саме на числі З ЖИВОГО ГОТЕЛЮ, окремим твердженням: воно і зламало.
// 31 610 байтів — вимір дельти 18.09.2026.
const live = formatBytes(31610);
assert.ok(!zeroish(live), `дельта живого готелю надрукувалась як «${live}»`);
assert.ok(/KB/.test(live), `31 610 байтів мали б бути в КБ, отримали «${live}»`);
ok(`дельта живого готелю (31 610 Б) → «${live}», не «0.0 MB»`);

// ── Вісь не вироджена: нуль і НЕ-нуль мусять РОЗРІЗНЯТИСЬ ──────────────────
//
// Без цього твердження попереднє було б зеленим і у форматера, який усе
// друкує як «0 B» (AGENTS §26: два значення на осі, про яку стверджуємо).
assert.notStrictEqual(formatBytes(0), formatBytes(1),
  'нуль і один байт друкуються однаково — стовпець не розрізняє «порожньо» і «щось є»');
assert.notStrictEqual(formatBytes(0), formatBytes(31610),
  'нуль і дельта готелю друкуються однаково — рівно дефект INC-053');
ok(`нуль («${formatBytes(0)}») відрізняється і від 1 Б, і від дельти`);

// ── Невідоме — не нуль ─────────────────────────────────────────────────────
assert.strictEqual(formatBytes(null), '—', 'null мав би бути «невідомо»');
assert.strictEqual(formatBytes(undefined), '—', 'undefined мав би бути «невідомо»');
assert.strictEqual(formatBytes(0), '0 B', 'справжній нуль мав би називатись нулем');
ok('невідомий розмір («—») відрізняється від справжнього нуля («0 B»)');

// ── Одиниця відповідає величині ────────────────────────────────────────────
for (const [bytes, unit] of [[512, 'B'], [2048, 'KB'], [5 * 1024 * 1024, 'MB']] as const) {
  const text = formatBytes(bytes);
  assert.ok(text.endsWith(unit), `${bytes} Б мали б бути в ${unit}, отримали «${text}»`);
}
ok('одиниця береться за величиною: 512 Б, 2 КБ, 5 МБ');

// Рядок із бази (`bigint` приїжджає рядком) читається так само, як число.
assert.strictEqual(formatBytes('31610'), formatBytes(31610),
  'розмір із бази приїжджає рядком — він мусить друкуватись так само');
ok('розмір рядком із бази = розміру числом');

console.log(`bytes: ${checks} тверджень — ненульове ніколи не нуль`);
