/**
 * Розмір у байтах — одним написанням на весь продукт.
 *
 * ── Навіщо ────────────────────────────────────────────────────────────────
 *
 * Написань було три, і третє брехало. `settings/apps/page.tsx` друкував
 * розмір знімка Winhotel так:
 *
 *   const mb = (bytes) => `${(Number(bytes) / 1048576).toFixed(1)} MB`;
 *
 * Дельта дня важить десятки кілобайтів — вимір на живому готелі 18.09.2026
 * дав 31 610 байтів. Це `0.030…` МБ, тобто **`0.0 MB`** після `toFixed(1)`.
 * Наслідок гірший за некрасивий рядок: **справжній нуль виглядає так само**.
 * Стовпець існує рівно щоб сказати «щось приїхало», і для цілого роду знімків
 * він не казав нічого — а коли одного дня приїде порожньо, не скаже й поготів
 * (INC-053).
 *
 * Інші два написання (`sizeLabel` у картці броні, `fmtSize` у фінансових
 * вкладеннях) поводились правильно, але були двома копіями однієї логіки. Дати
 * знімкам ТРЕТЮ копію означало б завести той самий дефект ще раз через тиждень,
 * тому тут одна функція, і всі три місця кличуть її.
 *
 * ── Властивість, якої тримаємось ──────────────────────────────────────────
 *
 * **Жодне ненульове число байтів не друкується як «0».** Саме це і зламалось:
 * не точність, не одиниця, а нерозрізненність «мало» і «нічого». Тримає
 * `bytes.check.ts`.
 */

/** Порожнє значення: `null`/`undefined` — «невідомо», 0 байтів — справжній нуль. */
export function formatBytes(bytes: number | string | null | undefined, empty = '—'): string {
  if (bytes === null || bytes === undefined || bytes === '') return empty;
  const n = Number(bytes);
  if (!Number.isFinite(n)) return empty;
  if (n < 0) return empty;
  if (n === 0) return '0 B';
  // Менше кілобайта — байтами, без дробу: «812 B» точне і коротке.
  if (n < 1024) return `${Math.round(n)} B`;
  // До мегабайта — кілобайтами. Дробовий знак нижче 10 КБ — це точність, а не
  // захист від нуля: у цю гілку не потрапляє нічого меншого за 1024 байти, тож
  // `Math.round` тут нулем не збрехав би. (Перевірено мутацією: гейт лишається
  // зеленим, і це правильно — він стереже нуль, а не красу.)
  if (n < 1024 * 1024) {
    const kb = n / 1024;
    return `${kb < 10 ? kb.toFixed(1) : Math.round(kb)} KB`;
  }
  const mbValue = n / (1024 * 1024);
  return `${mbValue < 10 ? mbValue.toFixed(2) : mbValue.toFixed(1)} MB`;
}
