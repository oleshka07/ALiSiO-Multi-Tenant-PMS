/**
 * Спільна фікстура не старіє.
 *
 *   node src/core/fixtures/two-properties.check.ts
 *
 * ── Навіщо перевіряти ФІКСТУРУ ──────────────────────────────────────────
 *
 * 11.09.2026 `npm run check` став червоним без жодної зміни коду: календар
 * дійшов до літералів. Фікстура сіяла броні датами `2026-09-10…17` без явного
 * статусу, тобто `confirmed`; того дня бронь на 10.09 стала ПРОСТРОЧЕНИМ
 * ЗАЇЗДОМ, і `alerts.scope` дістав 2 там, де стверджує 1. Сцена мала рацію —
 * підтверджена бронь із минулою датою заїзду справді є простроченим заїздом.
 * Брехала фікстура, якою користуються 41 сцена.
 *
 * Найгірше — що воно самоусувається: за два тижні рядки випали б із тижневого
 * вікна тривог, сцена позеленіла б сама, і бомба перезарядилась би. Червоне,
 * що зеленіє від календаря, — не полагоджене, а відкладене.
 *
 * ── Що саме тут стверджується, і чому саме так ──────────────────────────
 *
 * Не «дати зараз у майбутньому» — це було б істинно і для літерала
 * `2027-09-10`, тобто для тієї самої бомби з довшим ґнотом. Стверджується
 * ВЛАСТИВІСТЬ: фікстура, засіяна в будь-який майбутній день, дає дати
 * попереду ТОГО дня. Відносні дати проходять за побудовою, будь-який літерал
 * падає — і падає тим раніше, чим ближче його дата (§3.2.1).
 *
 * Перевірити це можна без подорожі в часі, бо `assertStaysAreFuture` бере
 * «сьогодні» ПАРАМЕТРОМ, а не читає годинник сам. Саме для цього воно там і
 * є: те, що функція не знає, який сьогодні день, і робить її перевірюваною.
 */
import assert from 'node:assert';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import '../../../scripts/lib/module-aliases.mjs';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'alisio-fixture-dates-'));
process.env.ALISIO_DATA_DIR = tmp;

await import('@core/db/index.ts');
const {
  seedTwoProperties, assertStaysAreFuture, assertQuietMonthIsQuiet, assertNotDegenerate,
  fixtureCheckIn,
} = await import('@core/fixtures/two-properties.ts');

const fx = await seedTwoProperties();

/** Той самий засів, але «сьогодні» зсунуте вперед. */
const shiftDays = (date: string, days: number) =>
  new Date(new Date(`${date}T00:00:00Z`).getTime() + days * 86_400_000).toISOString().slice(0, 10);

const today = new Date().toISOString().slice(0, 10);

// ── 1. Сьогодні ─────────────────────────────────────────────────────────
assertStaysAreFuture(fx, today);
assertQuietMonthIsQuiet(fx);
assertNotDegenerate(fx);
console.log('  ok  1. дати фікстури попереду сьогоднішнього дня');

// ── 2. І в будь-який майбутній день ─────────────────────────────────────
//
// Тут і є та властивість, заради якої все. Не «дати зараз у майбутньому» —
// це істинно й для літерала `2027-09-10`, — а «для БУДЬ-ЯКОГО дня засіву
// дати попереду нього». Відносна арифметика проходить за побудовою, будь-який
// літерал падає, і падає тим раніше, чим ближче його дата.
//
// Годинник не чіпається: `fixtureCheckIn` бере день параметром, і засів
// кличе саме її. Тобто перевіряється та сама арифметика, а не її копія.
//
// 400 днів, а не 30: бомба 11.09 мала ґніт у два тижні, і місячна перевірка
// її б не знайшла. Крок у 37 днів проходить усі позиції всередині місяця, а
// не лише перші числа; 29 лютого і переходи через рік у діапазон потрапляють.
for (let ahead = 0; ahead <= 400; ahead += 1) {
  const when = shiftDays(today, ahead);
  for (const key of ['a', 'b'] as const) {
    for (let i = 0; i < 3; i++) {
      const checkIn = fixtureCheckIn(when, key, i);
      assert.ok(checkIn > when,
        `засів у день ${when}: заїзд ${key}${i + 1} призначено на ${checkIn} — не пізніше за день засіву, `
        + 'тобто дата не рухається разом із календарем');
    }
  }
}
console.log('  ok  2. для кожного з 401 дня засіву дати попереду нього — арифметика відносна, не літерал');

// ── 3. Тихий місяць не торкається жодної броні ──────────────────────────
//
// Друга вісь, і вона окрема: місяць, у якому фікстура «нічого не має»,
// потрібен сценам, що рахують зайняті дати точно. Перевіряється ПЕРЕКРИТТЯ
// відрізків, а не різниця назв місяців: бронь через межу місяця пройшла б
// повз порівняння назв.
const stays = [
  ...fx.a.checkIns.map((from, i) => [from, fx.a.checkOuts[i]] as const),
  ...fx.b.checkIns.map((from, i) => [from, fx.b.checkOuts[i]] as const),
];
assert.ok(stays.length === 5, `очікували 5 броней фікстури, знайшли ${stays.length}`);
for (const [from, to] of stays) {
  assert.ok(to < fx.quietFrom || from > fx.quietTo,
    `бронь ${from}…${to} заходить у тихий місяць ${fx.quietMonth} (${fx.quietFrom}…${fx.quietTo})`);
}
assert.ok(fx.freeDay >= fx.quietFrom && fx.freeDay <= fx.quietTo,
  `freeDay ${fx.freeDay} лежить поза тихим місяцем ${fx.quietMonth}`);
// І запас із обох боків: сцена аркуша доби відступає на дві доби назад і
// вперед, і жодна з них не має перелізти через межу місяця.
assert.ok(shiftDays(fx.freeDay, -2) >= fx.quietFrom && shiftDays(fx.freeDay, 2) <= fx.quietTo,
  `freeDay ${fx.freeDay} не лишає сцені по дві доби з кожного боку всередині ${fx.quietMonth}`);
console.log('  ok  3. тихий місяць порожній, і freeDay лишає запас із обох боків');

// ── 4. Усі броні — в ОДНОМУ місяці ──────────────────────────────────────
//
// Звіти й експорти питають діапазон МІСЯЦЯ (`fx.from`…`fx.to`). Бронь, що
// перелізла через межу, зробила б їхні числа залежними від того, коли
// запустили перевірку, — тобто рівно тією вадою, від якої це все.
for (const [from, to] of stays) {
  assert.ok(from.startsWith(fx.month) && to.startsWith(fx.month),
    `бронь ${from}…${to} виходить за межі місяця фікстури ${fx.month}`);
}
console.log('  ok  4. усі 5 броней лежать усередині одного місяця — діапазон звіту їх покриває');

fs.rmSync(tmp, { recursive: true, force: true });
console.log('two-properties: фікстура рухається разом із календарем, тихий місяць тихий, місяць один');
