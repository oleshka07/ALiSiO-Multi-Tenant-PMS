/**
 * Палітри гостьових поверхонь — реєстр, названий КОЛЬОРОМ, не готелем.
 *
 * ── Навіщо взагалі реєстр ───────────────────────────────────────────────
 *
 * Гостьовий застосунок (`/stay/<ключ>`) і гостьова сторінка (`/guest/<токен>`)
 * — це те, що гість бачить замість рецепції. Вони мали рівно один вигляд на
 * всіх: теплий беж і латунь. Для одного готелю це його бренд, для наступного
 * — чужий одяг, і єдиним способом відрізнятись було «не заповнювати».
 *
 * ── Чому НАЗВАНО кольором, а не готелем ─────────────────────────────────
 *
 * Це інваріант 20 дослівно: дані, які клієнт може змінити сам, не бувають
 * літералом у коді. Ключ `schlossberghotel` перетворив би палітру на власність
 * одного клієнта — і наступний готель із бірюзою або вибирав би чужу назву зі
 * списку, або чекав на реліз заради власних кольорів. Тому ключ описує, ЩО це
 * за кольори: `teal_warm_grey`, `sand_brass`. Хто саме їх носить — рядок у
 * базі (`properties.brand_palette`), а не рядок тут.
 *
 * Той самий доказ, що з `GIFT_CARD_TEMPLATES` (INC-006): шість ваучерів одного
 * кемпінгу з цінами й продуктами бачив кожен готель на сервері.
 *
 * ── Де живуть самі кольори ──────────────────────────────────────────────
 *
 * У CSS, не тут. Цей файл знає ІМЕНА й підписи; значення — блоки
 * `[data-palette="…"]` у `src/app/stay/guest-app.css` і
 * `src/app/guest/guest-page.css`. Дві причини, і друга важливіша за першу:
 *
 *   1. шістнадцяткові літерали в коді екрана — те, що ловить
 *      `check-ui-tokens`, і ловить правильно;
 *   2. набір, розданий через CSS-змінні, застосовується до ОБОХ поверхонь
 *      однією стрічкою `data-palette`, а набір, розданий числами з JS, довелося
 *      б протягувати в кожен компонент — і перший же новий компонент
 *      лишився б у кольорах першої палітри. Це той самий клас, що П18.
 *
 * Звідси й твердження гейта (`brand-palettes.check.ts`): кожен ключ звідси
 * має блок в ОБОХ таблицях стилів, і жоден блок не існує без ключа. Палітра,
 * яку можна обрати і яка нічого не міняє, — це фальшивий вимикач (П5).
 */

/** Ключ палітри так, як він лежить у `properties.brand_palette`. */
export type BrandPaletteKey = 'sand_brass' | 'teal_warm_grey' | 'forest_stone' | 'ink_amber';

export interface BrandPalette {
  key: BrandPaletteKey;
}

/*
 * Підпису тут НЕМАЄ навмисно.
 *
 * Назва палітри — текст екрана оператора, і в цьому продукті такий текст
 * загортається в `t()` на самому екрані (`PALETTE_NAMES` у
 * `settings/guest-page`), бо саме звідти його бере `extract-strings`. Копія
 * підпису тут дала б другий рядок, який у каталог не потрапляє, — тобто
 * німецький адміністратор бачив би українське слово при 100 % покриття
 * (той самий випадок, що шостий у AGENTS §3.2.1).
 *
 * Що палітра без підпису не проскочить, стереже `brand-palettes.check`:
 * кожен ключ звідси мусить мати рядок у `PALETTE_NAMES`.
 */

/**
 * Перша в списку — та, що діяла до появи вибору.
 *
 * Порядок тут і є порядком на екрані. `sand_brass` стоїть першою не з
 * естетики: готель, який нічого не обирав, мусить побачити свій нинішній
 * вигляд першим рядком, інакше «за замовчуванням» читається як «нічого не
 * обрано» і хтось обере навмання.
 */
export const BRAND_PALETTES: readonly BrandPalette[] = [
  { key: 'sand_brass' },
  { key: 'teal_warm_grey' },
  { key: 'forest_stone' },
  { key: 'ink_amber' },
] as const;

/**
 * Палітра, яку показують першою в списку: вона ж — вигляд гостьового
 * ЗАСТОСУНКУ до появи вибору.
 *
 * Це НЕ значення за замовчуванням для колонки. Див. `readBrandPalette`.
 */
export const FIRST_BRAND_PALETTE: BrandPaletteKey = 'sand_brass';

/**
 * Слово з бази, приведене до відомого. Невідоме або порожнє → `null`.
 *
 * ── Чому `null`, а не «дефолтна палітра» ────────────────────────────────
 *
 * Перша редакція віддавала тут `sand_brass`, і це була тиха вада, яку знайшло
 * читання, а не гейт: історичний вигляд двох поверхонь РІЗНИЙ. Застосунок жив
 * у піску й латуні, гостьова сторінка — у лісовій зелені (`:root` її таблиці
 * стилів). Одне значення «за замовчуванням» на обидві означало б, що від самої
 * міграції кожен наявний готель отримує перефарбовану гостьову сторінку — при
 * тому, що ніхто нічого не обирав.
 *
 * `null` означає рівно «готель не обирав», і тоді стрічка `data-palette` не
 * ставиться взагалі, а кожна поверхня лишається у ВЛАСНОМУ базовому наборі.
 * Без токенів вона при цьому не лишається: базовий блок (`.guest-root`,
 * `:root`) називає повний набір — це стверджує `brand-palettes.check`.
 *
 * Невідоме значення в колонці читається так само, як порожнє. Тут «не знаємо»
 * коштує вигляду, а не даних, тож відмовляти нема чого — але й вигадувати теж.
 */
export function readBrandPalette(raw: unknown): BrandPaletteKey | null {
  return BRAND_PALETTES.some((p) => p.key === raw) ? raw as BrandPaletteKey : null;
}

/**
 * Адреса лого обʼєкта, приведена до придатної для `<img src>`.
 *
 * Пускаємо лише `https:` і власний шлях (`/…`). Це не параноя про XSS —
 * `src` не виконує коду, — а про дві речі, які видно гостю: `http:` на
 * сторінці по https дає порожній прямокутник (браузер блокує змішаний вміст,
 * мовчки), а `data:`/`javascript:` у колонці означає, що хтось поклав туди не
 * адресу, і показувати це гостю нема сенсу.
 *
 * Порожньо → `null`, і поверхня показує НАЗВУ готелю текстом. Назва є завжди;
 * лого — ні, і порожній прямокутник замість нього гірший за слово.
 */
export function readBrandLogoUrl(raw: unknown): string | null {
  if (typeof raw !== 'string') return null;
  const url = raw.trim();
  if (!url) return null;
  if (url.startsWith('/') && !url.startsWith('//')) return url;
  if (url.startsWith('https://')) return url;
  return null;
}
