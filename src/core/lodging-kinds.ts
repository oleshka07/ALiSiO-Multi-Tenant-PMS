/**
 * Рід житла: чим готель себе називає.
 *
 * ── Чому це в ядрі, а не в модулі каналів ────────────────────────────────
 *
 * Перелік лежав у `channels/ui/property-types.ts`, і писач обʼєкта
 * (`properties/data/properties.repo.ts`) читав його звідти. Наслідок: базовий
 * модуль відмовляв за списком ВЕНДОРА КАНАЛІВ навіть готелю, який модуль
 * каналів не купував — а він OFF і платний (`FEATURE_SPEC.channels`). Це
 * проти правила «модуль вимикається без шкоди решті»: вимкнений канал не
 * повинен вирішувати, який рід житла приймає форма обʼєкта.
 *
 * Рід житла — факт про сам обʼєкт, а не про його продаж: він у формі обʼєкта,
 * і залишиться там, якщо каналів у готелю не буде ніколи. Тому перелік тут, а
 * `modules/channels` мапить його у вендорські значення в себе
 * (`channex/property-type.ts`). Зворотний напрямок імпорту тримає
 * `check-boundaries --strict`.
 *
 * ── Звідки взяті значення ────────────────────────────────────────────────
 *
 * 22 значення, дослівно з `docs/vendor/channex/INVENTORY.md:50` (рядок
 * `property_type` у таблиці полів обʼєкта). Збіг із вендорським переліком —
 * навмисний і зручний, але не обовʼязок: якщо вендор перейменує чи додасть
 * значення, змінюється МАПА в модулі каналів, а не цей файл. Саме тому мапа
 * тотальна й перелічена поіменно, а не `as ChannexType`.
 *
 * ── Чому CHECK у базі немає ──────────────────────────────────────────────
 *
 * Свідомо: перелік може зрости, а міграція, що відстала, відмовляла б на
 * валідному роді. Звіряє писач — там, де помилку видно оператору.
 *
 * ── Чому це важливо, а не «поле як поле» ─────────────────────────────────
 *
 * Вендор каналів пише про своє відповідне поле «Recommended you set this
 * value since it affects billing»: значення вирішує, скільки готель ЗАПЛАТИТЬ.
 * Для готелю на 1-15 номерів «hotel» неправдиве частіше, ніж правдиве —
 * apartment, guest_house і camping це різні гроші й різні правила показу в
 * OTA. Тому дефолту немає: не названо — `NULL` (інваріант 20).
 */
export const LODGING_KINDS = [
  'apart_hotel', 'apartment', 'boat', 'camping', 'capsule_hotel', 'chalet',
  'country_house', 'farm_stay', 'guest_house', 'holiday_home', 'holiday_park',
  'homestay', 'hostel', 'hotel', 'inn', 'lodge', 'motel', 'resort', 'riad',
  'ryokan', 'tent', 'villa',
] as const;

export type LodgingKind = (typeof LODGING_KINDS)[number];

export function isLodgingKind(value: unknown): value is LodgingKind {
  return typeof value === 'string' && (LODGING_KINDS as readonly string[]).includes(value);
}
