/**
 * Спільна форма знахідки — щоб чотири модулі відповідали однаково.
 *
 * Живе в `core`, а не в модулі пошуку, бо кожен модуль шукає САМ і повертає
 * цей тип. Інакше «модуль пошуку» ходив би в чужі таблиці — тобто був би
 * пробоєм межі в кожен модуль одразу, і найгіршим із можливих: той, хто
 * читає `invoices` ззовні `@finance`, наступного разу читатиме її після того,
 * як колонка переїде.
 */
export interface SearchHit {
  /** Ідентифікатор рядка — для ключа в списку, не для показу. */
  id: string;
  /** Головний рядок: ім'я гостя, номер фактури, назва номера. */
  title: string;
  /** Другий рядок: дати, сума, статус — те, що відрізняє двох однофамільців. */
  subtitle?: string;
  /** Куди веде натискання. */
  href: string;
}

/**
 * Скільки знахідок віддає ОДИН розділ.
 *
 * Обмеження не для швидкості: без нього запит «а» повертає всіх гостей
 * готелю одним JSON-ом. Тобто пошук стає вивантаженням бази — тим самим, за
 * яке в іншому місці відповідає окремий екран із правами.
 */
export const SEARCH_LIMIT = 8;

/**
 * Найкоротше, що має сенс шукати.
 *
 * Один символ дає весь готель у відповідь і нічого не каже людині; два —
 * теж майже завжди. Порогом займається сервер, а не поле вводу: поле можна
 * обійти.
 */
export const SEARCH_MIN_LENGTH = 2;

/**
 * Шаблон для `dialect.ilike()`.
 *
 * `%` і `_` у запиті екрануються: без цього `%` знаходить усе, а `_` —
 * будь-який символ. Це не діра в безпеці (RLS усе одно тримає орендаря), але
 * це неправильна відповідь, а пошук, який іноді бреше, гірший за відсутній.
 */
export function likePattern(term: string): string {
  return `%${term.replace(/[\\%_]/g, (c) => `\\${c}`)}%`;
}
